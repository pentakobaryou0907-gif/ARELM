function 表示(見つけた) {
    const 止める = 見つけた.filter((x) => x.重さ >= 3);
    const 直す = 見つけた.filter((x) => x.重さ === 2);
    const 見る = 見つけた.filter((x) => x.重さ === 1);

    console.log('='.repeat(56));
    console.log(' ストッパー');
    console.log('='.repeat(56));

    if (!見つけた.length) {
        console.log('  止めるものはありません。渡してよい状態です。');
        console.log();
        return true;
    }

    if (止める.length) {
        console.log(`\n  ● 渡してはいけません（${止める.length}件）`);
        止める.slice(0, 12).forEach((x) => {
            console.log(`     ${x.道}${x.行 ? ':' + x.行 : ''}`);
            console.log(`       ${x.件}`);
            console.log(`       → ${x.直し方}`);
        });
        if (止める.length > 12) console.log(`     ほか ${止める.length - 12}件`);
    }

    if (直す.length) {
        console.log(`\n  ▲ 直したほうがよい（${直す.length}件）`);
        直す.slice(0, 8).forEach((x) => {
            console.log(`     ${x.道}${x.行 ? ':' + x.行 : ''}  ${x.件}`);
        });
        if (直す.length > 8) console.log(`     ほか ${直す.length - 8}件`);
    }

    if (見る.length) {
        console.log(`\n  ・ 見ておく（${見る.length}件）`);
        const まとめ = {};
        見る.forEach((x) => { まとめ[x.項目] = (まとめ[x.項目] || 0) + 1; });
        Object.entries(まとめ).forEach(([k, v]) => console.log(`     ${k}: ${v}件`));
    }

    console.log();
    return 止める.length === 0;
}

