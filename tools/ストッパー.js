/* ==========================================================
   見る前に、説明文と文字列を取り除く

   なぜこれが要るのか:

     行をそのまま見ていると、
     「eval は使わないこと」という<b>説明文</b>まで
     「eval を使っている」と読んでしまう。

     '// fetch(...) は禁止' や
     "const 案内 = 'https://... は使いません'" のような、
     <b>書いてあるだけで動かないもの</b>を止めてしまう。

     止めなくていいものを止めると、
     そのうち「またか」と思われて、
     本当に止めるべきときにも見られなくなる。

     だから、動く部分だけを見る。
     説明文と文字列は、空白に置き換えてから見る。
     行の数は変えない。行の番号がずれると、どこの話か分からなくなる。
   ========================================================== */

function 動く部分だけにする(中身) {
    const 出 = [];
    let ブロック説明の中 = false;

    中身.split('\n').forEach((行) => {
        let 結果 = '';
        let i = 0;

        while (i < 行.length) {
            const 二文字 = 行.slice(i, i + 2);

            // ブロック説明（/* … */）の中
            if (ブロック説明の中) {
                if (二文字 === '*/') { ブロック説明の中 = false; 結果 += '  '; i += 2; }
                else { 結果 += ' '; i += 1; }
                continue;
            }

            // ブロック説明の始まり
            if (二文字 === '/*') { ブロック説明の中 = true; 結果 += '  '; i += 2; continue; }

            // 行の説明（// と #）。そこから先は全部説明。
            if (二文字 === '//' || (行[i] === '#' && /\.py$/.test(''))) {
                結果 += ' '.repeat(行.length - i);
                break;
            }

            // 文字列。閉じるまで空白にする。
            if (行[i] === "'" || 行[i] === '"' || 行[i] === '`') {
                const 囲み = 行[i];
                結果 += ' ';
                i += 1;
                while (i < 行.length) {
                    if (行[i] === '\\') { 結果 += '  '; i += 2; continue; }
                    if (行[i] === 囲み) { 結果 += ' '; i += 1; break; }
                    結果 += ' ';
                    i += 1;
                }
                continue;
            }

            結果 += 行[i];
            i += 1;
        }

        出.push(結果);
    });

    return 出.join('\n');
}

/**
 * 文字列の中身も見たいときのため、
 * 「文字列だけ」を取り出せるようにしておく。
 *
 * 外国語の混入や、かぎの直書きは
 * 文字列の中にあるからこそ問題になる。
 */
function 文字列の中だけにする(中身) {
    const 動く = 動く部分だけにする(中身);
    const 元 = 中身.split('\n');
    const 抜き = 動く.split('\n');

    return 元.map((行, i) => {
        const 相手 = 抜き[i] || '';
        let 出 = '';
        for (let j = 0; j < 行.length; j++) {
            // 動く部分で空白になっているところ＝説明文か文字列
            出 += (相手[j] === ' ' && 行[j] !== ' ') ? 行[j] : ' ';
        }
        return 出;
    }).join('\n');
}

