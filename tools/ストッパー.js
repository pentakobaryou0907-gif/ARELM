#!/usr/bin/env node
/**
 * ストッパー ― 渡してはいけないものを、その場で止める
 *
 * なぜこれを作るのか:
 *
 *   はじめ「ストッパー」という名前で作った。
 *   だがストッパーは、見て点を付けて報告する人。
 *   報告されても、止まらなければ壊れたものが渡ってしまう。
 *
 *   要るのは<b>止めるもの</b>だった。
 *   だから名前も役目もストッパーに変えた。
 *
 *   ここで止まれば、壊れたものは外に出ない。
 *   書き換えのときは、その場で元に戻す。
 *
 * どこで止まるか:
 *
 *   ・自分でコードを書き換えるとき（server/自分を書き換える.js）
 *     止めるものが見つかったら、書き換えを取り消して元に戻す。
 *     人を待たない。壊れたまま待つ時間があってはいけない。
 *
 *   ・全体の検査のとき（check.sh）
 *     渡してよい状態かどうかを、最後に確かめる。
 *
 * 何を見るのか:
 *
 *   <b>この開発で実際に起きた失敗</b>を見る。
 *   一般論の「良いコード」ではなく、ここで本当に壊れたものを見る。
 *   そこが、いちばん確かな材料。
 *
 *   起きた失敗（すべて実際にあったもの）:
 *     ・同じ名前を二つのファイルで宣言 → 画面全体が止まった（3回）
 *     ・ロシア語・韓国語・スペイン語の混入（4回）
 *     ・シェルで日本語の変数名 → 変な名前のフォルダーができた（4回）
 *     ・URLに日本語 → 符号化されて一致せず動かない（3回）
 *     ・保存先が二つに分かれ、「覚えました」なのに「覚えていません」
 *     ・「〜してください」で終わり、こちらでできることを人にやらせる
 *     ・言うだけで直さない
 *
 * 三つの段階:
 *
 *   ● 止める   … これがあると渡さない。書き換えなら元に戻す。
 *   ▲ 直す     … 渡せるが、直したほうがよい。
 *   ・ 見ておく … 気に留めておく程度。
 *
 * 使い方:
 *   node tools/ストッパー.js            … 全部を見る
 *   node tools/ストッパー.js <ファイル>  … そのファイルだけ見る
 *
 * 外部へは一切問い合わせません。
 */

