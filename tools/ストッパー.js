function 見るファイルを集める(限定) {
    if (限定) return [限定];
    const 出 = [];
    ['js', 'server', 'tools', 'css'].forEach((場所) => {
        const 実 = path.join(本体, 場所);
        if (!fs.existsSync(実)) return;
        (function 潜る(道) {
            fs.readdirSync(道, { withFileTypes: true }).forEach((x) => {
                if (x.name === 'node_modules' || x.name.startsWith('.')) return;
                const 次 = path.join(道, x.name);
                if (x.isDirectory()) 潜る(次);
                else if (/\.(js|py|sh|command|css)$/.test(x.name)) {
                    出.push(path.relative(本体, 次));
                }
            });
        })(実);
    });
    // Python は server/ai にもある
    const ai = path.join(本体, 'server', 'ai');
    if (fs.existsSync(ai)) {
        fs.readdirSync(ai).forEach((f) => {
            if (/\.py$/.test(f)) {
                const 道 = path.relative(本体, path.join(ai, f));
                if (!出.includes(道)) 出.push(道);
            }
        });
    }
    return 出;
}

function 見張る(限定) {
    const 見つけた = [];

    見るファイルを集める(限定).forEach((道) => {
        let 中身;
        try {
            中身 = fs.readFileSync(path.join(本体, 道), 'utf8');
        } catch {
            return;
        }

        // 説明文と文字列を取り除いたものも渡す。
        //
        // 「動くコードとして」見たいものは 動く部分 を、
        // 「書かれた文字として」見たいものは 元のまま を使う。
        //
        // これを分けないと、
        // 「eval は使わないこと」という説明まで止めてしまう。
        const 動く = 動く部分だけにする(中身);

        止める決まり.forEach((項) => {
            const 見る中身 = 項.文字も見る ? 中身 : 動く;
            項.見る(見る中身, 道, 中身).forEach((x) => {
                見つけた.push({
                    項目: 項.名,
                    重さ: 項.重さ,
                    なぜ: 項.なぜ,
                    道,
                    行: x.行,
                    件: x.件,
                    直し方: x.直し方,
                });
            });
        });
    });

    // 名前の衝突は、全体を見ないと分からない
    if (!限定) 名前の衝突を見る().forEach((x) => 見つけた.push(x));

    見つけた.sort((a, b) => b.重さ - a.重さ);
    return 見つけた;
}

