#!/usr/bin/env node
/**
 * サーバー側（Node）の自動テスト
 *
 * 見るもの:
 *   ・門番: 中継された通信（tailscale serve 等）を、Mac本体と見間違えない
 *   ・夜の当番: いつ実行するか／いつ知らせるか／点検の中身／報告の読み書き
 *
 * 本物のデータには触れない（一時フォルダだけを使う）。外部へは一切問い合わせない。
 */

const fs = require('fs');
const os = require('os');
const path = require('path');

const 門番 = require('../server/門番');
const 夜 = require('../server/夜の当番');

const 結果 = [];
function 確かめる(名, 条件, 詳細 = '') { 結果.push({ 名, ok: !!条件, 詳細 }); }

/* ---------- 門番: 中継された通信 ---------- */
const 通信 = (headers) => ({ headers });
確かめる('門番: localhost で直接開いた通信は、中継ではない', !門番.中継された通信か(通信({ host: 'localhost:8090' })));
確かめる('門番: 127.0.0.1 で直接開いた通信は、中継ではない', !門番.中継された通信か(通信({ host: '127.0.0.1:8090' })));
確かめる('門番: [::1] で直接開いた通信は、中継ではない', !門番.中継された通信か(通信({ host: '[::1]:8090' })));
確かめる('門番: 宛先が .ts.net なら、中継', 門番.中継された通信か(通信({ host: 'arelm-mac.tail1234.ts.net' })));
確かめる('門番: 転送ヘッダー（X-Forwarded-For）つきは、中継', 門番.中継された通信か(通信({ host: 'localhost:8090', 'x-forwarded-for': '100.1.2.3' })));
確かめる('門番: tailscale-user-login つきは、中継', 門番.中継された通信か(通信({ host: 'localhost', 'tailscale-user-login': 'a@b' })));
確かめる('門番: Via つきは、中継', 門番.中継された通信か(通信({ host: 'localhost', via: '1.1 proxy' })));
確かめる('門番: 宛先の無い通信は、中継として扱う（安全側）', 門番.中継された通信か(通信({})));

/* ---------- 夜の当番: 時刻の判断 ---------- */
const 設定 = { 有効: true, 時刻: '03:30', 通知: true, 通知の時刻: '08:00' };
const 日時 = (時, 分 = 0, 日 = 8) => new Date(2026, 9, 日, 時, 分, 0);   // 2026-10-08
const 報告 = (実行, 要確認数 = 0, id = 'n_1') => ({ id, 実行時刻: 実行.toISOString(), 要確認: Array.from({ length: 要確認数 }, () => ({ 係: '在庫係', 文: 'x' })) });

確かめる('夜: 無効なら実行しない', 夜.実行すべきか({ ...設定, 有効: false }, null, 日時(4)) === null);
確かめる('夜: 予定の前は実行しない', 夜.実行すべきか(設定, null, 日時(3, 0)) === null);
確かめる('夜: 予定のあとで、報告が無ければ実行する', 夜.実行すべきか(設定, null, 日時(3, 31))?.理由 === '予定どおり');
確かめる('夜: 前日の報告しか無ければ、実行する', 夜.実行すべきか(設定, 報告(日時(3, 31, 7)), 日時(3, 40)) !== null);
確かめる('夜: 今日の予定の分を実行済みなら、もう実行しない', 夜.実行すべきか(設定, 報告(日時(3, 31)), 日時(9)) === null);
確かめる('夜: 眠っていて2時間遅れたら、「遅れて」と書いて実行する', 夜.実行すべきか(設定, 報告(日時(3, 31, 7)), 日時(5, 40))?.理由 === '遅れて（眠っていたため）');

/* ---------- 夜の当番: 朝の通知 ---------- */
const 状態なし = {};
確かめる('通知: 要確認が無ければ、知らせない（毎日「異常なし」を出さない）', !夜.通知すべきか(設定, 報告(日時(3, 31), 0), 状態なし, 日時(8, 5)));
確かめる('通知: 通知の時刻の前は、知らせない', !夜.通知すべきか(設定, 報告(日時(3, 31), 2), 状態なし, 日時(7, 59)));
確かめる('通知: 要確認があり、通知の時刻を過ぎたら、知らせる', 夜.通知すべきか(設定, 報告(日時(3, 31), 2), 状態なし, 日時(8, 1)));
確かめる('通知: 同じ報告では、二度知らせない', !夜.通知すべきか(設定, 報告(日時(3, 31), 2, 'n_9'), { 最後に知らせた報告: 'n_9' }, 日時(9)));
確かめる('通知: 古い報告（20時間以上前）では知らせない', !夜.通知すべきか(設定, 報告(日時(3, 31, 6), 2), 状態なし, 日時(8, 5)));
確かめる('通知: 通知を切っていたら、知らせない', !夜.通知すべきか({ ...設定, 通知: false }, 報告(日時(3, 31), 2), 状態なし, 日時(8, 5)));

/* ---------- 夜の当番: 点検の中身 ---------- */
const 同期 = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, { value: JSON.stringify(v), updatedAt: 1 }]));
const 基本 = { 今日: '2026-10-08', バックアップの状態: { ok: true, 最新: { 作成: new Date().toISOString() }, 古すぎる: false }, 永久の記憶の状況: { ok: true }, AIは動いているか: true, 空きGB: 100, 合言葉が要るのに無い: false, 近く切れる端末: [], どこでも: { 許している: false }, 同期を読めるか: true };

const 良い = 夜.点検する({ ...基本, 同期: 同期({ products: [{ name: '黒T', price: 4800, quantity: 20, reorderLevel: 5 }], areglm_tasks: [{ title: 'a', due: '2099-01-01', done: false }] }) });
確かめる('点検: 問題が無ければ、要確認は0件', 良い.要確認.length === 0);
確かめる('点検: 五つの係が、それぞれ報告する', 良い.係ごと.map((k) => k.係).join() === '在庫係,段取り係,作り方係,記録係,点検係');

const 悪い = 夜.点検する({
    ...基本, AIは動いているか: false, 空きGB: 2, 合言葉が要るのに無い: true, どこでも: { 許している: true, 公開中: '' },
    同期: 同期({
        products: [{ name: '白T', price: 0, quantity: 1 }, { name: '白T', price: 3000, quantity: 50 }],
        areglm_tasks: [{ title: '発注', due: '2026-10-01', done: false }, { title: '済み', due: '2026-10-01', done: true }],
        areglm_production_log: [{ name: 'No.21', 状態: '公開可' }],
    }),
});
const 文たち = 悪い.係ごと.flatMap((k) => k.件.map((x) => `${k.係}:${x.重さ}:${x.文}`)).join('\n');
確かめる('点検: 在庫が少ない商品を、要確認にする', /在庫係:要確認:在庫が少ない商品が1件/.test(文たち));
確かめる('点検: 期限の過ぎたやることを要確認にする（済みのものは数えない）', /段取り係:要確認:期限が過ぎたやることが1件/.test(文たち));
確かめる('点検: 公開待ちは、あなたの操作待ちと書く（公開は押さない）', /公開」操作を待っている/.test(文たち) && /あなたが押します/.test(文たち));
確かめる('点検: AIエンジンが止まっていたら要確認', /点検係:要確認:自作AIエンジン/.test(文たち));
確かめる('点検: 空き容量が少なければ要確認', /ディスクの空きが少なく/.test(文たち));
確かめる('点検: 合言葉の無い公開は要確認', /合言葉が決まっていません/.test(文たち));
確かめる('点検: 「どこでも」が止まっていたら要確認', /いま外から開けない/.test(文たち));
確かめる('点検: 要約の件数と、要確認の中身が一致する', 悪い.要確認.length >= 6 && 悪い.要約.includes(`要確認 ${悪い.要確認.length}件`));

const 壊れた = 夜.点検する({ ...基本, 同期: {}, 同期を読めるか: false });
確かめる('点検: 同期のデータが壊れていたら要確認', 壊れた.要確認.some((x) => /同期のデータ/.test(x.文)));

/* ---------- 夜の当番: 設定と報告の読み書き ---------- */
const 場所 = fs.mkdtempSync(path.join(os.tmpdir(), 'arelm-night-'));
try {
    確かめる('設定: 何も無ければ既定（有効・03:30）', 夜.設定を読む(場所).有効 === true && 夜.設定を読む(場所).時刻 === '03:30');
    夜.設定を書く(場所, { 時刻: '25:99ばかり' });
    確かめる('設定: おかしな時刻は、受け付けない', 夜.設定を読む(場所).時刻 === '03:30');
    夜.設定を書く(場所, { 時刻: '04:15', 有効: false });
    確かめる('設定: 正しい時刻と、切り替えは反映する', 夜.設定を読む(場所).時刻 === '04:15' && 夜.設定を読む(場所).有効 === false);
    確かめる('設定: 片方だけ変えても、もう片方を壊さない', (夜.設定を書く(場所, { 通知: false }), 夜.設定を読む(場所).時刻 === '04:15'));

    確かめる('報告: 何も無ければ空', 夜.報告を読む(場所).length === 0);
    for (let i = 1; i <= 3; i++) {
        fs.appendFileSync(path.join(場所, '朝の報告.jsonl'), JSON.stringify({ id: 'n_' + i }) + '\n');
    }
    確かめる('報告: 新しい順に読める', 夜.報告を読む(場所, 2).map((x) => x.id).join() === 'n_3,n_2');
    fs.appendFileSync(path.join(場所, '朝の報告.jsonl'), 'これは壊れた行\n');
    確かめる('報告: 壊れた行があっても、他は読める', 夜.報告を読む(場所, 10).length === 3);
} finally { fs.rmSync(場所, { recursive: true, force: true }); }

/* ---------- まとめ ---------- */
const 失敗 = 結果.filter((x) => !x.ok);
console.log(`サーバーの試験: ${結果.length - 失敗.length}/${結果.length} 件が成功`);
失敗.forEach((x) => console.log(`  ✗ ${x.名}${x.詳細 ? ' — ' + x.詳細 : ''}`));
process.exit(失敗.length ? 1 : 0);
