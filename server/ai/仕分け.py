def _小文字(s):
    return (s or '').lower()


def 触ってはいけないか(道):
    低 = _小文字(道)
    return any(w.lower() in 低 for w in 触らない)


def 塊の中か(道):
    部分 = 道.replace('\\', '/').split('/')
    return any(x in 部分 for x in ソフトの塊)


def 事業に関わるか(道):
    """
    このファイルが事業に関わるか。

    見るのは「ファイル名」と「すぐ上のフォルダー名」だけ。
    道すじ全部を見てはいけない。

    はじめは道すじ全部を見ていた。
    ところが置き場所が「新規ビジネス素材」という名前だったため、
    その下にある全部のファイルが「ビジネス」に当たってしまい、
    163件のうち147件が「使う」になった。.DS_Store まで資料扱いだった。
    それでは仕分けたことにならない。
    """
    名 = os.path.basename(道)
    親 = os.path.basename(os.path.dirname(道))
    低 = _小文字(名 + '｜' + 親)
    return any(w.lower() in 低 for w in 事業の言葉)


def 見分ける(道):
    """
    一つのファイルが、どの行き先かを決める。

    @return (行き先, 訳)
      行き先: '使う' | '種類別' | '学習して移す' | '不要' | '触らない'
    """
    名 = os.path.basename(道)
    拡張 = os.path.splitext(名)[1].lower()

    # 「.DS_Store」のように、点で始まって拡張子が無い名前がある。
    # splitext は ('.DS_Store', '') と返すので、
    # 拡張子が空のまま「種類が分からない」に流れていた。
    if not 拡張 and 名.startswith('.'):
        拡張 = 名.lower()

    # 画面の並び順を覚えているだけの、macOSの置き土産
    if 名 in ('.DS_Store', '.localized', 'Icon\r', 'Thumbs.db', 'desktop.ini'):
        return '不要', 'macOS・Windowsが勝手に作る目印で、中身はありません'

    # 認証情報らしきものは、何もしない
    if 触ってはいけないか(道):
        return '触らない', '認証情報らしいので、開かず動かしません'

    # 未完了のダウンロード、インストーラ、一時ファイル
    if 拡張 in 不要の形:
        return '不要', f'{拡張} は資料ではありません（インストーラ・一時ファイル等）'

    # ソフトウェアの塊の中は、一つずつ見る意味がない
    if 塊の中か(道):
        return '学習して移す', 'ソフトウェアの部品置き場の中'

    # 資料の形をしていて、事業に関わる
    if 拡張 in 資料の形:
        if 事業に関わるか(道):
            return '使う', '事業に関わる資料'
        return '種類別', '資料だが、事業には直接関わらない'

    # 画像・動画
    if 拡張 in 見るもの:
        if 事業に関わるか(道):
            return '使う', '事業に関わる画像・動画'
        return '種類別', '画像・動画（事業には直接関わらない）'

    # ソフトウェアの部品
    if 拡張 in ソフトの形:
        return '学習して移す', 'ソフトウェアの部品'

    # 分からないもの。
    # 迷ったら残す側に寄せる。捨てて困る方が重いため。
    if 事業に関わるか(道):
        return '使う', '種類は分からないが、名前が事業に関わる'
    return '種類別', '種類が分からないので、そのまま残します'


# 種類別に分けるときの、まとめ方
種類のまとめ = [
    ('学校の課題', ['レポート', '課題', '小テスト', '試験', '解答', '演習',
                  '講義', '授業', '20123019', '学籍', 'ゼミ', '実習',
                  '微分積分', '線形代数', '情報科学', 'アルゴリズム',
                  'オペレーティング', 'アーキテクチャ']),
    ('写真と動画', list(見るもの)),
    ('表', ['.xlsx', '.xls', '.csv', '.numbers']),
    ('スライド', ['.pptx', '.ppt', '.key']),
    ('文書', ['.docx', '.doc', '.pdf', '.txt', '.md', '.rtf', '.pages']),
]


def 種類を決める(道):
    低 = _小文字(道)
    拡張 = os.path.splitext(道)[1].lower()
    for 名, 手がかり in 種類のまとめ:
        for w in 手がかり:
            if w.startswith('.'):
                if 拡張 == w:
                    return 名
            elif w.lower() in 低:
                return 名
    return 'その他'


def _まとめて数える(根):
    """
    中へ入らずに、そこにある件数と大きさだけを数える。
    一つずつ見分ける意味が無い場所で使う。
    """
    件 = 0
    量 = 0
    for 現在, _, ファイルたち in os.walk(根):
        for f in ファイルたち:
            件 += 1
            try:
                量 += os.path.getsize(os.path.join(現在, f))
            except OSError:
                pass
    return 件, 量


def 調べる(根, 上限=None):
    """
    フォルダーを見て回り、仕分けの案を作る。
    ここでは**何も動かさない**。数えて返すだけ。
    """
    結果 = {'使う': [], '種類別': {}, '学習して移す': [], '不要': [], '触らない': []}
    数 = {'使う': 0, '種類別': 0, '学習して移す': 0, '不要': 0, '触らない': 0}
    大きさ = {k: 0 for k in 数}
    見た = 0

    for 現在, フォルダたち, ファイルたち in os.walk(根):
        # ソフトウェアの塊は、中へ入らない。
        # 入ると数万件になり、時間だけかかって得るものがない。
        #
        # ただし「入らない」と「数えない」は違う。
        # はじめは入口の直下だけ数えて先へ進んでいたので、
        # 57,310件あるはずのものが8件と出ていた。
        # 入らない代わりに、そこで丸ごと数える。
        if 塊の中か(現在):
            フォルダたち[:] = []
            件, 量 = _まとめて数える(現在)
            数['学習して移す'] += 件
            大きさ['学習して移す'] += 量
            if len(結果['学習して移す']) < 60:
                結果['学習して移す'].append(
                    {'道': 現在, '訳': f'ソフトウェアの部品置き場（丸ごと{件}件・{大きさを言葉に(量)}）'})
            continue

        for f in ファイルたち:
            道 = os.path.join(現在, f)
            行き先, 訳 = 見分ける(道)
            数[行き先] += 1
            見た += 1

            try:
                大きさ[行き先] += os.path.getsize(道)
            except OSError:
                pass

            if 行き先 == '種類別':
                種 = 種類を決める(道)
                結果['種類別'].setdefault(種, [])
                if len(結果['種類別'][種]) < 20:
                    結果['種類別'][種].append(道)
            elif len(結果[行き先]) < 60:
                結果[行き先].append({'道': 道, '訳': 訳})

            if 上限 and 見た >= 上限:
                return 結果, 数, 大きさ, 見た

    return 結果, 数, 大きさ, 見た


def 大きさを言葉に(バイト):
    for 単位 in ['B', 'KB', 'MB', 'GB', 'TB']:
        if バイト < 1024:
            return f'{バイト:.1f}{単位}'
        バイト /= 1024
    return f'{バイト:.1f}PB'
