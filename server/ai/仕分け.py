"""
データを仕分ける

なぜこれが要るのか:
    アプリの中に107GB、Downloads に1.0GB の資料がある。
    数万件あるので、一つずつ手で分けるのは無理がある。

    しかも中身を見ると、大半は資料ではなかった。
    ComfyUI のコピーが89GB、Unityのプロジェクトが6.5GB、
    インストーラや未完了のダウンロード——
    どれも「服のブランドをやる」ためのものではない。

    必要なものと、そうでないものを分ける。

分け方の考え:

    使う      … アパレル・ブランド・経営・デザインに関わるもの
    種類別    … 資料だが、この事業には直接関わらないもの（学校の課題など）
    学習して移す … ソフトウェアの塊。中身から学べるものは学んでから不要へ
    不要      … どこにも使えないもの（インストーラ、未完了ダウンロード等）

決まり:
    ・**消さない。** 移すだけ。
    ・迷ったら「使う」に寄せる。捨てて困る方が、残して困るより重い。
    ・認証情報らしきものは、学習させない。仕分けからも外す。
    ・まず一覧を出すだけ。移すのは、人が見て決めてから。

外部へは一切問い合わせません。すべてこの端末の中で完結します。
"""

