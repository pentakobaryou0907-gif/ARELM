# -*- coding: utf-8 -*-
"""
自分が覚えた資料から、ファッションの話題を拾う

なぜこれを作ったのか:
    旧サイトには「ファッション・ニュース（学習用）」という枠があり、
    外のニュースを取ってきて並べる作りだった。
    中身は空のまま、「Gemini / ニュースRSS連携後、
    自動で最新トピックを表示します」とだけ書かれていた。

    このツールは外へ一切出ない決まりなので、
    その枠は永久に埋まらない。
    埋まらない枠を置いておくのは、嘘をついているのと同じ。

    そこで、向きを変えた。
    外から取ってくるのではなく、
    すでに覚えている資料の中から話題を拾う。

    覚えた文は1万件を超えていて、
    その中に何が多く出てくるかは、こちらで数えられる。
    それは「世の中の流行」ではないが、
    「あなたが集めてきたものの傾向」ではある。

はっきりさせておきます:
    これは世の中の最新の流行ではありません。
    あなたがこのツールに入れた資料の中の話です。
    外を見に行っていないので、そこは言い換えません。

外部へは一切問い合わせません。すべてこの端末の中で完結します。
"""

# ファッションの話を手繰るための、出発点になる言葉。
#
# ここから意味の近い言葉をたどって広げる。
# 出発点を置かずに「多い順」で出すと、
# 「データ」「情報」のような、どの資料にも出る言葉が並んでしまう。
出発点 = [
    '服', '生地', '素材', '縫製', 'シルエット', 'デザイン',
    '色', '柄', 'ブランド', '古着', 'ヴィンテージ',
    'ストリート', 'コーディネート', 'サイズ', 'パターン',
]

# 話題として出しても意味のない言葉。
#
# 二文字の切れ端や、どの資料にも出る一般語は落とす。
# 落とさないと、話題の一覧が読めなくなる。
#
# 最初のふるいが緩く、「hash」「テキストボックス」「ニーズ・」が
# 話題として並んでしまった。どれも話題ではなく、
# 資料の中の部品や、切り出しの失敗にすぎない。
外す言葉 = {
    'こと', 'もの', 'ため', 'よう', 'それ', 'これ', 'その', 'この',
    'データ', '情報', '場合', '内容', '以下', '以上', '必要', '可能',
    '対応', '実施', '確認', '検討', '結果', '状況', '重要', '影響',
    'について', 'における', 'として', 'による',
    # 書類の部品であって、話題ではないもの
    'メモ', 'テキスト', 'テキストボックス', 'ボックス', 'タイトル',
    '見出し', '本文', '表題', '図表', 'ページ', 'ファイル', 'フォルダ',
    '一覧', '項目', '記載', '参照', '添付', '資料', '文書',
}

# 一文字も含まれていてはいけない記号。
# 切り出しに失敗した跡なので、話題にならない。
壊れた印 = ('・', '＿', '_', '/', '\\', '|', '「', '」', '(', ')', '（', '）')


def _片仮名だけか(語):
    return all('\u30a0' <= c <= '\u30ff' or c == 'ー' for c in 語)


def _使える言葉か(語, 件数表):
    if not 語 or len(語) < 2:
        return False
    if 語 in 外す言葉:
        return False
    if any(x in 語 for x in 壊れた印):
        return False

    # 英数字だけのものは、型番か記号。話題ではない。
    if 語.isascii():
        return False

    # 片仮名は、二文字だと切れ端になりやすい。
    # 「ータ」「デー」のような、語の途中を切っただけのものを落とす。
    if _片仮名だけか(語) and len(語) < 4:
        return False

    # 資料の中に数件しか出ないものは、話題とは呼べない。
    # たまたま近くに並んだだけ、ということが多い。
    if int(件数表.get(語, 0)) < 8:
        return False

    return True


def 拾う(learner, semantic, 数=12):
    """
    覚えた資料から、ファッションに近い話題を拾う。

    やり方:
      1. 出発点の言葉それぞれについて、意味の近い言葉を引く
      2. 引けた言葉が、資料の中で何件に出てくるかを数える
      3. 件数の多い順に並べる

    @return {'ある': bool, '話題': [...], '訳': str}
    """
    if semantic is None or learner is None:
        return {'ある': False, '話題': [], '訳': 'まだ何も覚えていません'}

    集めた = {}
    件数表 = getattr(learner, 'doc_freq', None) or {}

    for 種 in 出発点:
        try:
            近い = semantic.similar_words(種, 10)
        except Exception:
            continue
        if not 近い:
            continue

        for x in 近い:
            語 = x.get('term') if isinstance(x, dict) else (
                x[0] if isinstance(x, (list, tuple)) else x)
            if not _使える言葉か(語, 件数表):
                continue
            # 同じ言葉が複数の出発点から引けたら、
            # それだけ中心にある話題ということ。
            集めた.setdefault(語, {'語': 語, '元': set(), '件数': 0})
            集めた[語]['元'].add(種)

    if not 集めた:
        return {
            'ある': False,
            '話題': [],
            '訳': '覚えた資料の中に、ファッションに近い話題が見つかりませんでした。'
                  '資料を読み込ませると、ここに出てきます。',
        }

    # 資料の中で何件に出てくるかを入れる
    for 語, x in 集めた.items():
        x['件数'] = int(件数表.get(語, 0))

    並び = sorted(集めた.values(),
                 key=lambda x: (-len(x['元']), -x['件数'], x['語']))

    return {
        'ある': True,
        '話題': [
            {
                '語': x['語'],
                '件数': x['件数'],
                'どこから': sorted(x['元'])[:3],
            }
            for x in 並び[:数]
        ],
        '訳': '',
    }
