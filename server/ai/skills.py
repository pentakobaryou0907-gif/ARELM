        #
        # ふつう、質問には技能を動かさない。
        # 「在庫は？」は中身が知りたいのであって、
        # 画面を開いてほしいわけではないため。
        #
        # だが「いま何をしてる？」は違う。
        # 様子を出すことが、そのまま答えになる。
        # そういう作業だけ、質問でも動かす。
        self.答えになる = 答えになる

        # 言われたこと全体が中身になる作業か。
        #
        # 「黒い千鳥格子の柄を作って」のように、
        # 頼み言葉の前に大事なもの（色・柄）が入っている場合、
        # 後ろだけ切り出すと「って」しか残らない。
        self.全文を使う 	= 全文を使う


