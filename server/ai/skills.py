def ranked(text):
    """
    作業ごとの点数を、高い順に返す [(Skill, 点数), ...]（0点のものは含めない）。

    find_skill と、頼みを分ける（複数の頼みを手順にする）の両方が使う。
    点数のつけ方は一か所にしておかないと、二つの見分け方がずれていく。
    """
    if not text:
        return []
    low = text.lower()
    tokens = set(tokenize(text, use_ngram=False))
    結果 = []
    for skill in SKILLS:
        score = 0.0
        for w in skill.words:
            wl = w.lower()
            if wl in low:
                # 長い言い回しほど、偶然一致しにくいので重くする
                score += 1.0 + min(len(wl), 6) * 0.1
            elif wl in tokens:
                score += 0.8
        if score > 0:
            結果.append((skill, score))
    # 同点のときは、定義した順を保つ（sorted は安定）
    return sorted(結果, key=lambda x: -x[1])


def find_skill(text):
    """
    言われたことが、どの作業に当たるかを見分ける。

    見分け方:
        作業ごとの言葉が、どれだけ含まれているかで点を付ける。
        長い言葉ほど、その作業を強く示すため重く数える。
        （「在庫」より「タスク」のほうが短いが、
          どちらも他の作業には出てこないので同じ重みになる）

    確信が持てないときは None を返す。
    決めつけて動くより、聞き返したほうが害が小さいため。

    次点との差が小さいときも「確信が持てない」うちに入れる。
    たとえば「今日は在庫が少ない商品を教えて」は
    show_schedule（「今日」に反応）と show_inventory（「在庫」に反応）が
    同点になる。同点のときソート順で先に定義した方が勝ってしまうと、
    たまたま先に書いた作業がいつも勝つだけの、意味のない決め方になる。
    僅差の同点は「見分けられなかった」として扱い、確信度を落とす。

    @return (Skill, 確信度 0.0〜1.0) または (None, 0.0)
    """
    if not text:
        return None, 0.0

    順位 = ranked(text)
    best, best_score = (順位[0] if 順位 else (None, 0.0))
    second_score = 順位[1][1] if len(順位) > 1 else 0.0

    if not best:
        return None, 0.0

    # 点数を 0〜1 に収める。2点あればほぼ確実とみなす。
    confidence = min(best_score / 2.0, 1.0)

    # 次点が僅差（8割以上）なら、どちらの話かを取り違えている恐れがある。
    # 「今日」1語だけの一致のような弱い根拠どうしがぶつかったときに
    # 起きやすいので、その分だけ確信度を割り引く。
    if second_score >= best_score * 0.8:
        confidence *= 0.5

    return best, confidence


def describe_all():
    """
    できることを、そのまま読める形にまとめる。

    並べるだけでなく、例を添える。
    「何ができるか」を聞く人が本当に知りたいのは
    「どう言えばいいか」だから。
    """
    lines = ['いま、私にできることです。', '']
    for s in SKILLS:
        lines.append(f'・{s.label}')
        lines.append(f'　{s.summary}')
        if s.example:
            lines.append(f'　例: {s.example}')
        lines.append('')

    # まとめての仕事も伝える。
    #
    # 一手ずつしか言えないと思われていると、
    # せっかく代わりに進められるのに使ってもらえない。
    try:
        import 段取り
        lines.append('それから、ひとまとまりの仕事として、'
                     'まとめて代わりに進められるものがあります。')
        lines.append('')
        for 型 in 段取り.段取りたち:
            lines.append(f'・{型.label}')
            lines.append(f'　{型.summary}')
            lines.append('')
        lines.append('まとめて進めるときは、まず順番をお見せします。'
                     '見てから「実行して」と言ってください。')
        lines.append('途中で止まったら、そこで止めて理由を言います。'
                     '残りを飛ばして「終わりました」とは言いません。')
        lines.append('')
    except Exception:
        # 段取りが読み込めなくても、できることの一覧は返す。
        # ここで落ちると「何ができるの」に何も返せなくなる。
        pass

    lines.append('この一覧にないことは、まだできません。')
    lines.append('できないことを、できるとは言いません。')
    return '\n'.join(lines)


def describe_one(skill):
    """作業ひとつ分の説明"""
    lines = [f'「{skill.label}」について。', '', skill.summary]
    if skill.slots:
        lines.append('')
        lines.append('実行するには、次のことが要ります:')
        for _, ask in skill.slots:
            lines.append(f'・{ask}')
    if skill.example:
        lines.append('')
        lines.append(f'言い方の例: {skill.example}')
    return '\n'.join(lines)
