"""
できること（技能）の一覧

なぜこれが要るのか:
    「何ができるの」と聞かれて答えられなかった。
    自分に何ができるか分かっていないと、
    言われたことを実行に移すこともできない。

ここでやっていること:
    このツールで実際に行える作業を、一つずつ書き出す。
    それぞれに「どう言われたら、それだと分かるか」と
    「実行に何が要るか」を持たせてある。

    これがあるので、
      - 何ができるかを自分の言葉で説明できる
      - 言われたことがどの作業に当たるか判断できる
      - 足りない情報を、こちらから聞き返せる

外部へは一切問い合わせない。すべてこの端末の中で完結する。
"""

