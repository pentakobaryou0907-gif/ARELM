def _品名を拾う(text):
    """
    文の中から、品物の名前らしいところを拾う。

    拾えなければ空で返す。
    分からないものを埋めると、それが嘘になるため、
    空のまま返して、あとで聞き返してもらう。
    """
    import re

    for 型 in (r'(?:商品名|品名|名前)[はが:：]\s*([^\s、。]+)',
               r'「([^」]{1,30})」'):
        m = re.search(型, text)
        if m:
            return m.group(1).strip()
    return ''


