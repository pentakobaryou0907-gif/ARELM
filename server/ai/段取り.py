# -*- coding: utf-8 -*-
"""
段取り（ひとつの目的を、順序のある作業に分ける）

なぜこれが要るのか:
    これまでは、一度に一つの作業しか受け取れなかった。
    「やること追加」「在庫を見せて」——どれも一手で終わるもの。

    だが実際の仕事は一手で終わらない。
    「新しい商品を出す準備をして」と言われたとき、
    本当にやることは、登録して、似ていないか調べて、
    説明文を書いて、投稿文を書いて、撮影を予定に入れて——
    という並びになる。

    それを一つずつ言い直させるなら、代わりに働いているとは言えない。
    ここで、目的をその並びに開く。

ここでの決まり:

  1. 並びに入れられるのは、実際に動く作業だけ。
     skills.py に無いものは絶対に入れない。
     「やります」と並べて動かないのが、いちばんたちが悪い。

  2. 勝手に始めない。
     並びを見せて、実行と言われてから動く。
     まとめて動くものほど、間違えたときの戻しが大変なため。

  3. 途中で失敗したら、そこで止めて正直に言う。
     残りを飛ばして「終わりました」とは言わない。

外部へは一切問い合わせない。すべてこの端末の中で完結する。
"""

from tokenizer import tokenize


class 手順:
    """
    段取りの中の一手。

    作業   … skills.py にある作業の名前
    説明   … 何のためにこれをやるのか（人に見せる）
    材料   … その作業に渡す中身
    確かめる … 実行前に人に確かめるか
    """

    def __init__(self, 作業, 説明, 材料=None, 確かめる=False):
        self.作業 = 作業
        self.説明 = 説明
        self.材料 = 材料 or {}
        self.確かめる = 確かめる

    def 辞書(self):
        return {
            'action': self.作業,
            'why': self.説明,
            'params': self.材料,
            'confirm': self.確かめる,
        }


class 段取りの型:
    """
    よくある目的ひとつ分の、決まった並び。

    words … こう言われたら、この段取りだと見分ける言葉
    作る  … 言われた文から、手順の並びを組み立てる
    """

    def __init__(self, name, label, summary, words, 作る):
        self.name = name
        self.label = label
        self.summary = summary
        self.words = words
        self.作る = 作る


