def find_plan(text):
    """
    言われた文が、どの段取りに当たるかを見る。

    当たらなければ (None, 0.0) を返す。
    無理に当てはめると、頼んでいない作業まで動き出すため、
    ここは厳しめにしてある。

    @return (段取りの型, 確からしさ)
    """
    if not text:
        return None, 0.0

    低 = text.lower()
    語 = set(tokenize(text))

    最良 = None
    最高 = 0.0

    for 型 in 段取りたち:
        点 = 0.0
        for w in 型.words:
            if w in 低:
                # 長い言い方ほど、たまたま当たる見込みが低い
                点 = max(点, 0.5 + min(0.4, len(w) * 0.06))
            elif w in 語:
                点 = max(点, 0.45)

        if 点 > 最高:
            最高 = 点
            最良 = 型

    return (最良, round(最高, 2)) if 最良 else (None, 0.0)


# 段取りとして受け取るには、こう頼まれている必要がある。
#
# 「新商品ってどう出すの」は質問であって、依頼ではない。
# 質問に対して勝手に六つの作業を始めたら、それは押しつけになる。
頼まれ方 = [
    'して', 'してほしい', 'してくれ', 'お願い', 'やって', 'やっといて',
    '準備', '進めて', '始めて', '代わりに', '任せ', 'よろしく',
    # 「〜したい」も頼み。
    #
    # 「新作を出したい」が拾えず「分かりません」と返していた。
    # 望みを言うのも、頼んでいることに変わりはない。
    'したい', 'たい', 'しよう', 'やりたい', 'つくりたい', '作りたい',
]


# 依頼の形で終わっているか。
#
# 「在庫を整えて」には上の言葉が一つも入らないが、
# これは明らかに頼んでいる。日本語では、
# 動詞の「て」で終わる形そのものが依頼になる。
頼みの語尾 = ('て', 'てね', 'てよ', 'といて', 'とけ', 'ください', 'くれ', 'ちょうだい',
        'たい', 'たいです', 'たいん', 'よう')

# ただし、疑問で終わっていたら依頼ではない。
# 「どう出すの？」に六つの作業を始めたら、それは押しつけになる。
問いの語尾 = ('か', 'かな', 'の', 'のか', '？', '?', 'ですか', 'ますか')


def 頼まれているか(text):
    t = (text or '').strip().rstrip('。 　')
    if not t:
        return False
    if t.endswith(問いの語尾):
        return False
    if any(w in t for w in 頼まれ方):
        return True
    return t.endswith(頼みの語尾)


def 段取りの返事(型, text, 確からしさ):
    """
    段取りを、人に見せる形にして返す。

    ここでは並べて見せるだけで、実行はしない。
    まとめて動くものほど、間違えたときに戻すのが大変なため、
    見てもらってから動く。
    """
    手順たち = 型.作る(text)

    文 = [f'「{型.label}」として受け取りました。', '',
          f'{型.summary}', '',
          '次の順で進めます:', '']
    for i, h in enumerate(手順たち, 1):
        印 = '（確かめてから）' if h.確かめる else ''
        文.append(f'{i}. {h.説明}{印}')

    文 += ['',
           '足りない中身は、その手順のところで聞きます。',
           'この順で進めてよければ「実行して」と言ってください。'
           '違うところがあれば、そこだけ言ってもらえれば直します。']

    return {
        'ok': True,
        'certainty': 'confirmed',
        'answer': '\n'.join(文),
        'sources': ['あなたの指示'],
        'plan': {
            'name': 型.name,
            'label': 型.label,
            'summary': 型.summary,
            'steps': [h.辞書() for h in 手順たち],
        },
    }
