# -*- coding: utf-8 -*-
"""
よくある質問 ― お客様からの問い合わせに、下書きで答える（AI受付の最小版）

なぜこれが要るのか:

    マスタープロンプトの方針:「このツールは世に公開・発信しない。
    私だけがアクセスできる形にする」。

    つまり、AIが勝手にInstagramのDMへ直接返事を送ることはしない。
    Instagramの公式APIも、まだ繋いでいない。

    代わりに、<b>お客様から来た質問をここに貼り付けると、
    返信の下書きをAIが作る</b>という形にする。
    送るのは、必ずあなた自身がSNS側の画面で行う。

    JARVISのような「電話に出て予約を取る」自動応対の考え方を、
    「勝手に送らない」という、この道具の一貫した方針に合わせて調整した形。

使うもの:
    ・よくある質問（発送日数・返品条件・サイズ感など。ここで編集できる）
    ・在庫（商品一覧が渡されれば、実際の在庫を踏まえて答える）
    ・ローカルLLM（Qwen2.5・この端末の中だけ）

外部へは一切送らない。
"""

import json
import os

import ローカルLLM

置き場 = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'よくある質問.json')

既定のFAQ = [
    {'問': '発送日数はどれくらいですか', '答': '受注生産のため、発送まで半年前後お時間をいただいております。'},
    {'問': '返品はできますか', '答': '受注生産の性質上、お客様都合による返品はお受けしておりません。不良品の場合は個別にご相談ください。'},
    {'問': 'サイズ感を教えてください', '答': '商品ページのサイズ表をご確認ください。ご不明な点があればお申し付けください。'},
    {'問': '支払い方法は何がありますか', '答': '銀行振込・コンビニ決済に対応しております。'},
]


def _読む():
    try:
        with open(置き場, encoding='utf-8') as f:
            r = json.load(f)
        return r if isinstance(r, list) and r else 既定のFAQ
    except (OSError, ValueError):
        return 既定のFAQ


def _書く(一覧):
    場所 = os.path.dirname(os.path.abspath(置き場))
    os.makedirs(場所, exist_ok=True)
    with open(置き場, 'w', encoding='utf-8') as f:
        json.dump(一覧, f, ensure_ascii=False, indent=1)


def 一覧を出す():
    return _読む()


def 追加する(問, 答):
    問 = (問 or '').strip()
    答 = (答 or '').strip()
    if not 問 or not 答:
        return {'ok': False, '訳': '質問と答えの両方が要ります'}
    一覧 = _読む()
    一覧.append({'問': 問, '答': 答})
    _書く(一覧)
    return {'ok': True, '訳': 'よくある質問に足しました'}


def _FAQ文():
    行 = [f'Q: {x["問"]} / A: {x["答"]}' for x in _読む()]
    return '\n'.join(行)


def _在庫文(商品一覧):
    if not 商品一覧:
        return ''
    行 = []
    for p in 商品一覧[:30]:
        名 = p.get('name') or ''
        在庫 = p.get('stock')
        価格 = p.get('price')
        中身 = 名
        if 価格:
            中身 += f'（¥{価格}）'
        if 在庫 is not None:
            中身 += f' 在庫{在庫}点' if 在庫 else ' 在庫切れ'
        行.append(f'・{中身}')
    return '\n'.join(行)


def 返信を作る(質問, 商品一覧=None, ブランド='AReGLM'):
    """
    お客様からの問い合わせに対する、返信の下書きを作る。

    自分からは何も送らない。文面を作って返すだけ。
    """
    質問 = (質問 or '').strip()
    if not 質問:
        return {'ok': False, '訳': 'お客様からの質問文が要ります'}

    if not ローカルLLM.使えるか():
        return {'ok': False, '訳': 'ローカルAI（Ollama）が動いていません。'}

    指示 = (
        f'あなたはアパレルブランド「{ブランド}」のカスタマーサポート担当です。\n'
        f'お客様から届いた質問に、丁寧で簡潔な返信を1つだけ作ってください。\n'
        f'\n'
        f'守ること:\n'
        f'・「よくある質問」に答えがあれば、それに沿って答えてください。\n'
        f'・在庫情報が渡されていれば、実際の数字を使ってください（無ければ在庫の話はしない）。\n'
        f'・分からないことは、憶測で答えず「確認してお答えします」としてください。\n'
        f'・返信文だけを出力し、前置きや説明は書かないでください。\n'
        f'・敬語で、絵文字は使っても1〜2個までにしてください。\n'
        f'\n'
        f'【よくある質問】\n{_FAQ文()}\n'
    )

    在庫文 = _在庫文(商品一覧 or [])
    if 在庫文:
        指示 += f'\n【現在の在庫】\n{在庫文}\n'

    指示 += f'\n【お客様からの質問】\n{質問}'

    答え = ローカルLLM.聞く(指示, タイムアウト=60)
    if not 答え:
        return {'ok': False, '訳': 'ローカルAIから答えが返りませんでした'}

    return {'ok': True, '訳': '下書きを作りました', '返信案': 答え.strip()}
