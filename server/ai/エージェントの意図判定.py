# -*- coding: utf-8 -*-
"""
エージェントの意図判定 ― 話しかけられた言葉から、やりたいことを選ぶ

なぜこれが要るのか:

    これまでのエージェント（js/modules/console.js）は、
    決まった短いキーワードに部分一致するか、
    タイプミスをあいまい一致（編集距離）で拾うだけだった。

    短い言葉のあいまい一致は、無関係な長い文の中の
    たまたま似た部分に引っかかりやすく、見当違いの操作に化けていた
    （「変な認識になる」という報告の原因）。
    決まった言い方以外は、ほぼ聞き返すだけにもなっていた。

    ここでは、その判定をローカルLLM（Qwen2.5・この端末の中だけ）に任せる。
    文字列のあいまい一致ではなく、文の意味を読んで選ばせるほうが、
    自然な話し方に強くなる。

安全のための線引き（リモート作業.py と同じ考え方）:

    ・<b>渡した「実行できる操作」の一覧に無いものは、選ばせても実行しない。</b>
      LLMが存在しない操作名を作っても、こちらで弾く。
    ・<b>実際に動かすコードは書かせない。</b>
      選ぶのは操作の「id」だけで、そのidに紐づく処理は
      あらかじめ画面側（console.js）に決めてあるものだけを実行する。
    ・操作に当てはまらないときは、自然な返事（reply）をそのまま返す。
      「分かりません」で終わらせず、会話として答えられるようにする。

外部へは一切問い合わせません。すべてこの端末の中で完結します。
"""

import json

import _import_fix  # noqa: F401  日本語ファイル名のimportがNFC/NFDの食い違いで失敗しないようにする
import ローカルLLM
import エージェント定義


def _JSONを取り出す(文):
    """LLMの返事から、いちばん外側の { … } だけを取り出す。"""
    始 = 文.find('{')
    終 = 文.rfind('}')
    if 始 < 0 or 終 < 0 or 終 <= 始:
        return None
    try:
        return json.loads(文[始:終 + 1])
    except (ValueError, TypeError):
        return None


def _操作の説明(操作たち):
    """
    LLMに見せる、使える操作の一覧文。

    先頭を「id=」のような接頭辞にすると、LLMがその接頭辞ごと
    そのまま答えに書き写してしまうことがあった
    （"goto-inventory" ではなく "id=goto-inventory" と返る等）。
    識別子だけを裸のまま先頭に置き、括弧の中に説明を添える形にする。
    """
    行 = []
    for a in 操作たち:
        名 = a.get('id', '')
        説 = a.get('label', '')
        例 = a.get('examples') or []
        材料要る = 'あり（残りの言葉を渡す）' if a.get('needsArg') else 'なし'
        例文 = '、'.join(例[:4])
        行.append(f'・{名}（{説}／言い方の例:「{例文}」／引数:{材料要る}）')
    return '\n'.join(行)


def 意図を選ぶ(発言, 操作たち, 直近の会話=None, persona=None, page=None):
    """
    発言から、実行できる操作のどれに当たるかを選ぶ。

    @param 発言       ユーザーが話しかけた・打ち込んだ文
    @param 操作たち    [{'id':…, 'label':…, 'examples':[…], 'needsArg': bool}]
    @param 直近の会話  [{'role': 'user'|'assistant', 'text': …}]（任意、文脈用）
    @param persona    設定ページ「AIの話し方」に書かれた口調の指示（任意）
    @param page       今見ている画面のページID（任意、担当エージェント選びに使う）
    @return {'ok': True, '操作id': str|None, '材料': str, '会話の返事': str}
            LLMが使えない・形が読めない場合は {'ok': False, '訳': str}
    """
    発言 = (発言 or '').strip()
    if not 発言:
        return {'ok': False, '訳': '発言が空です'}

    if not ローカルLLM.使えるか():
        return {'ok': False, '訳': 'ローカルLLM（Ollama）が動いていません'}

    操作id一覧 = {a.get('id') for a in 操作たち}

    会話文 = ''
    if 直近の会話:
        行 = []
        for m in 直近の会話[-6:]:
            役 = 'ユーザー' if m.get('role') == 'user' else 'あなた'
            行.append(f'{役}: {m.get("text", "")}'[:200])
        会話文 = '\n'.join(行)

    persona = (persona or '').strip()

    # マルチエージェント化: 名指し＞今の画面＞発言の言葉、の順で専門の担当を選ぶ。
    # 操作idの選び方には影響させず、"会話の返事"の立場づけにだけ使う。
    担当選択 = エージェント定義.エージェントを選ぶ詳細(page=page, 発言=発言)
    担当id = 担当選択['id']
    担当指示 = エージェント定義.エージェントの指示文(担当id, 担当選択['引き継ぎ元']) if 担当id else ''

    指示 = (
        'あなたは「アレラム」という名前の、ARELMというアパレルブランド運営ツールの'
        '中で動くエージェントです。ユーザーの発言を読み、'
        '次の「実行できる操作」の中から最も合うものを一つだけ選ぶか、'
        'どれにも当てはまらなければ、あなた自身が自然に会話で返事をしてください。\n'
        '\n'
        + ((
            '【担当（"会話の返事"を書くときだけ、この立場で。'
            '操作idの選び方には影響させないでください）】\n' + 担当指示 + '\n\n'
        ) if 担当指示 else '')
        + ((
            '【話し方の指示（本人が設定した口調。"会話の返事"を書くときだけ守り、'
            '操作idの選び方には影響させないでください）】\n' + persona + '\n\n'
        ) if persona else '')
        + '【実行できる操作】\n' + _操作の説明(操作たち) + '\n'
        + (('\n【直前までの会話】\n' + 会話文 + '\n') if 会話文 else '') +
        '\n'
        '必ず、次のJSON形式だけで答えてください。前置きや説明文、コードの囲みは書かないでください。\n'
        '・操作に当てはまる場合: '
        '{"操作id": "上の一覧の先頭にある識別子そのもの（例: goto-inventory）", '
        '"材料": "操作に渡す残りの言葉（無ければ空文字）", "会話の返事": ""}\n'
        '・操作に当てはまらず、あなたが会話で答える場合: '
        '{"操作id": null, "材料": "", "会話の返事": "ユーザーへの自然な日本語の返事をここに書く"}\n'
        '・"操作id" と "会話の返事" は別々の項目です。混ぜて一つにまとめないでください。\n'
        '・操作idには、一覧にある識別子をそのまま書いてください。'
        '「id=」やかっこなど、余計な文字を付け足さないでください。\n'
        '・一覧に無いidは、絶対に作らないでください。\n'
        '・分からないことは、知ったかぶりせず正直に「分かりません」と会話の返事に書いてください。\n'
        '・会話の返事を空文字のままにしないでください。必ず何か書いてください。'
    )

    # 短いJSON＋一言の返事で十分なので、出力の上限だけ付けて早く返らせる。
    # 上限が無いと、長話を続けようとして生成に時間がかかることがあった。
    #
    # 時間の上限（タイムアウト）はあえて付けない。
    # 以前は30秒→60秒と数字を変えて対策していたが、操作一覧を積んだ
    # 本番の指示文（1900字前後）では実測31秒前後かかることがあり、
    # どんな数字を選んでも「正しく判定できているのに、その手前で
    # 切り捨てられる」ことが起き続けていた。切り捨てられると、
    # 聞き取れているのに何も実行されない・話が通じていないように見える
    # 不具合になる（報告のあった不具合の主因）。この端末の中だけで
    # 動くモデルで、待たせた分だけ料金がかさむものでもないので、
    # 急いで切る理由が無い。詳しい理由は ローカルLLM.聞く() 側を参照。
    答え = ローカルLLM.聞く(f'{指示}\n\n【ユーザーの発言】\n{発言}', 最大出力=220)
    if not 答え:
        return {'ok': False, '訳': 'ローカルLLMから答えが得られませんでした'}

    担当情報 = エージェント定義.エージェント情報(担当id, 担当選択['引き継ぎ元']) if 担当id else None

    決めた = _JSONを取り出す(答え)
    if not isinstance(決めた, dict):
        # JSONにならなくても、文章としてはもらえていることが多い。
        # 会話が止まるより、そのまま返事として使うほうがまし。
        return {'ok': True, '操作id': None, '材料': '', '会話の返事': 答え.strip(), 'agent': 担当情報}

    操作id = 決めた.get('操作id')
    if isinstance(操作id, str):
        # 「id=」やかぎ括弧など、書式の指示ごと書き写されることがあるので、
        # よくある余計な飾りは落としてから照合する。
        操作id = 操作id.strip().strip('「」').strip()
        if 操作id.lower().startswith('id='):
            操作id = 操作id[3:].strip()
        操作id = 操作id or None

    会話の返事 = (決めた.get('会話の返事') or '').strip()

    if 操作id is not None and 操作id not in 操作id一覧:
        # 存在しない操作をでっち上げたときは、操作扱いにしない。
        # 返事があればそれを使い、無ければ正直に伝える。
        return {
            'ok': True, '操作id': None, '材料': '',
            '会話の返事': 会話の返事 or f'「{操作id}」という操作は無いようです。言い方を変えてもらえますか。',
            'agent': 担当情報,
        }

    if 操作id is None and not 会話の返事:
        # 操作でも無く、会話の返事も空だったときは、
        # 「聞こえているのに黙っている」ことになってしまう。
        # 空のまま画面に出すより、正直に言えなかったと伝える。
        会話の返事 = 'うまく言葉にできませんでした。もう一度、違う言い方で伝えてもらえますか。'

    return {
        'ok': True,
        '操作id': 操作id,
        '材料': (決めた.get('材料') or '').strip(),
        '会話の返事': 会話の返事,
        'agent': 担当情報,
    }
