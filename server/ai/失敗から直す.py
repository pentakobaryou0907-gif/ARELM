# -*- coding: utf-8 -*-
"""
失敗から、自分のやり方を直す

なぜこれが要るのか:

    「違う、そうじゃない」と言われたとき、
    いまは謝って終わっていた。次も同じことをする。

    <b>直さなければ、同じことを繰り返す。</b>

    覚えるべきは「何を間違えたか」ではなく、
    「次はどうするか」。

どう直すのか:

    ・言われたことと、そのとき何をしたかを組にして残す
    ・同じ言われ方をされたら、前と違う手を選ぶ
    ・何を直したかは、必ず見られるようにする

やらないこと:

    <b>自分でコードを書き換えることはしません。</b>
    直すのは「どの言い方に、どう応じるか」まで。
    仕組みそのものには手を出しません。

    誰も見ていないところで自分を書き換える道具は、
    一度おかしくなったら止められません。

外部へは一切問い合わせません。すべてこの端末の中で完結します。
"""

import 永久の記憶
import json
import os
import re

置き場 = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                    '..', 'data', '直したやり方.json')

# 「違う」と言われたと分かる言い方
違うと言われた形 = [
    r'違う', r'ちがう', r'そうじゃない', r'そうではない',
    r'間違', r'まちが', r'だめ', r'ダメ',
    r'そっちじゃない', r'やり直', r'もう一度',
]


def _読む():
    try:
        with open(置き場, encoding='utf-8') as f:
            r = json.load(f)
        return r if isinstance(r, list) else []
    except (OSError, ValueError):
        return []


def _書く(一覧):
    場所 = os.path.dirname(os.path.abspath(置き場))
    os.makedirs(場所, exist_ok=True)
    with open(置き場, 'w', encoding='utf-8') as f:
        json.dump(永久の記憶.切り詰める('失敗から直した記録', 一覧, 200), f, ensure_ascii=False, indent=2)


def 一覧を出す():
    return _読む()


def 違うと言われたか(文):
    """「違う」と言われたかどうか"""
    t = (文 or '').strip()
    return any(re.search(x, t) for x in 違うと言われた形)


def 直しを覚える(言われたこと, したこと, 本当はどうすべきだったか=None):
    """
    間違いを、次に活かせる形で残す。

    @param 言われたこと          そのとき言われた言葉
    @param したこと              こちらが行った作業
    @param 本当はどうすべきだったか  分かっていれば
    """
    if not 言われたこと or not したこと:
        return {'ok': False, '訳': '何を間違えたか分かりません'}

    一覧 = _読む()

    # 同じ組み合わせが既にあるなら、回数だけ増やす
    for x in 一覧:
        if x.get('言われ方') == 言われたこと and x.get('選んだ手') == したこと:
            x['回数'] = x.get('回数', 1) + 1
            if 本当はどうすべきだったか:
                x['本当は'] = 本当はどうすべきだったか
            _書く(一覧)
            return {
                'ok': True,
                '訳': f'同じ間違いを {x["回数"]}回 しています。次は避けます。',
                '回数': x['回数'],
            }

    一覧.append({
        '言われ方': 言われたこと[:100],
        '選んだ手': したこと,
        '本当は': 本当はどうすべきだったか or '',
        '回数': 1,
        '覚えた日': __import__('datetime').date.today().isoformat(),
    })
    _書く(一覧)

    return {
        'ok': True,
        '訳': '次に同じことを言われたら、別の手を選びます。',
        '回数': 1,
    }


def 避けるべき手を調べる(言われたこと):
    """
    この言われ方で、前に間違えた手はあるか。

    @return {'避ける':[…], '代わりに':…}
    """
    t = (言われたこと or '').strip()
    if not t:
        return {'避ける': [], '代わりに': ''}

    避ける = []
    代わりに = ''

    for x in _読む():
        言われ方 = x.get('言われ方', '')
        if not 言われ方:
            continue

        # 言葉の重なりで見る。
        # 一字一句同じでなくても、似た言い方なら効くようにする。
        重なり = _どれくらい似ているか(t, 言われ方)
        if 重なり >= 0.6:
            避ける.append(x['選んだ手'])
            if x.get('本当は') and not 代わりに:
                代わりに = x['本当は']

    return {'避ける': list(set(避ける)), '代わりに': 代わりに}


def _どれくらい似ているか(あ, い):
    """
    二つの言い方が、どれくらい似ているか。

    細かい言い回しの違いは無視して、中身の言葉で見る。
    """
    def 言葉にする(文):
        文 = re.sub(r'[、。！？!?\s]', '', 文 or '')
        return {文[i:i + 2] for i in range(max(0, len(文) - 1))}

    あの語 = 言葉にする(あ)
    いの語 = 言葉にする(い)
    if not あの語 or not いの語:
        return 0.0
    return len(あの語 & いの語) / max(1, min(len(あの語), len(いの語)))


def どれくらい直したか():
    """いくつ直したかを数える"""
    一覧 = _読む()
    return {
        '覚えた間違い': len(一覧),
        '繰り返した数': sum(x.get('回数', 1) - 1 for x in 一覧),
        '直し方まで分かっているもの': len([x for x in 一覧 if x.get('本当は')]),
    }
