# -*- coding: utf-8 -*-
"""
アドバイザー ― 今の状況から、今日いちばん大事なことを選ぶ

なぜこれが要るのか:
    在庫・SNS・タスク・裏作業など、見るところが増えるほど、
    「結局、今日は何から手を付ければいいのか」が埋もれてしまう。
    ここでは、渡された「今の状況」の文章から、今日中に手を付けた
    ほうがよいことを3つだけ選び、それぞれ一言の理由を添えて返す。

    実際に何を優先すべきかの判断材料（在庫が少ない・タスクの期限が
    過ぎている等）は、すべて呼び出し側（クライアント）がこの端末に
    実際にある数字から作った「今の状況」の文章だけを使う。
    ここで新しく数字や実績を作ることはしない。

外部へは一切問い合わせません。すべてこの端末の中で完結します。
"""

import ローカルLLM


def 今日の優先順位を選ぶ(状況):
    状況 = (状況 or '').strip()
    if not 状況:
        return {'ok': False, '訳': '今の状況が渡されていません', '答え': ''}

    if not ローカルLLM.使えるか():
        return {
            'ok': False,
            '訳': 'ローカルAI（Ollama）が動いていません。起動してからお試しください。',
            '答え': '',
        }

    指示 = (
        'あなたはアパレルブランド「ARELM」の運営を手伝うアドバイザーです。'
        '次の「今の状況」を読んで、今日中に本人が手を付けたほうがよいことを'
        '3つだけ選び、日本語で答えてください。\n'
        '\n'
        '守ること:\n'
        '・3つだけに絞る。多くても少なくてもいけない。状況に書かれていない'
        '  ことが1つも無ければ、無理に3つ作らず、ある分だけ挙げる。\n'
        '・状況に書かれていない事実（実績・数字・締切）を作り話しない。\n'
        '・それぞれ「（すること）／（一言の理由）」の形で、1行ずつ書く。\n'
        '・優先順位が高い順に並べる。\n'
        '・前置きや締めの言葉は書かず、選んだ分の行だけを出力する。\n'
        '\n'
        f'【今の状況】\n{状況}'
    )

    答え = ローカルLLM.聞く(指示)
    if not 答え:
        return {'ok': False, '訳': 'ローカルAIから答えが返りませんでした', '答え': ''}

    return {'ok': True, '訳': '', '答え': 答え.strip()}
