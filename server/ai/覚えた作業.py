"""
教わった作業を、自分で覚える

なぜこれが要るのか:
    いまエージェントができるのは、私が書いた14の作業だけ。
    新しいことをさせたければ、そのたびにコードを足すしかない。
    それでは「何でもできる」には永久に届かない。

    だが、やり方を言葉で教えてもらえれば、
    それを手順として覚えて、次から一言で実行できる。
    作業が増えるのに、コードは増えない。

    これが、この道具が自分で伸びる道。

守ること:

  ・並べられるのは、実際に動く作業だけ。
    「やります」と言って動かないものを覚えたら、それは嘘になる。
    存在しない作業を言われたら、その場で断る。

  ・覚えたものは、いつでも見られて、直せて、忘れられる。
    中身の分からない手順が勝手に動くのは、いちばん怖い。

  ・外へ出る作業、お金がかかる作業は覚えない。
    あなたの決まりに反するので、頼まれても入れない。

外部へは一切問い合わせません。すべてこの端末の中で完結します。
"""

import json
import os
import re

置き場 = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                    '..', 'data', '覚えた作業.json')


def _読む():
    try:
        with open(置き場, encoding='utf-8') as f:
            r = json.load(f)
        return r if isinstance(r, list) else []
    except (OSError, ValueError):
        return []


def _書く(一覧):
    場所 = os.path.dirname(os.path.abspath(置き場))
    os.makedirs(場所, exist_ok=True)
    with open(置き場, 'w', encoding='utf-8') as f:
        json.dump(一覧, f, ensure_ascii=False, indent=2)


# 覚えてはいけない作業。
#
# 頼まれても入れない。
# 一度覚えると、あとで気づかないうちに動くため、
# 入口で止めるほうが確実。
覚えない作業 = {
    'send_mail', 'post_sns', 'pay', 'purchase', 'publish', 'upload',
}


# 何にでも使える道具。
#
# 決まった作業だけでは「何でも」に届かない。
# 読む・書く・数える・探す・比べる——
# これらを組み合わせれば、教わっていない作業も組み立てられる。
#
# 消す道具は入れていない。取り返しがつかないため。
# 外へ出る道具も入れていない。
汎用の道具 = ['読む', '書く', '数える', '探す', '比べる',
           '知らせる', '開く', '書き出す']

# パソコンを操る操作。
#
# これは強い。だから、手順に入れられるのは
# 「取り返しがつくもの」だけにしてある。
#
# 文字を打つ・クリックするは、ここに入れていない。
# 覚えた手順が勝手に動くとき、
# 画面のどこに何が出ているかは分からない。
# 分からないまま打つのは危ない。
パソコンの操作 = [
    'アプリを開く', '音量を変える', '音を消す', '読み上げる', '知らせる',
    'フォルダーを開く', 'ページを開く', '画面を撮る',
    '明るくする', '暗くする', '作業に入る', '休みに入る', '撮影に入る',
]


def 使える作業を集める():
    """
    いま実際に動く作業の名前を返す。

    ここに無いものは、手順に入れられない。
    存在しない作業を並べたら、それは動かない手順になる。
    """
    import skills
    使える = set()
    for s in skills.SKILLS:
        if s.action in 覚えない作業:
            continue
        使える.add(s.action)
        使える.add(s.name)

    # 道具も手順に入れられる
    for 道具 in 汎用の道具:
        使える.add('道具:' + 道具)

    # パソコンの操作も入れられる（取り返しがつくものだけ）
    for 操作 in パソコンの操作:
        使える.add('パソコン:' + 操作)

    return 使える


def 手順を確かめる(手順たち):
    """
    並べられた手順が、本当に動くかを確かめる。

    @return (よいか, 訳)
    """
    使える = 使える作業を集める()

    if not 手順たち:
        return False, '手順が一つもありません'

    if len(手順たち) > 12:
        return False, '手順が多すぎます（12まで）。分けて覚えさせてください'

    for i, h in enumerate(手順たち, 1):
        作業 = h.get('action')
        if not 作業:
            return False, f'{i}番目に、何をするかが書かれていません'
        if 作業 in 覚えない作業:
            return False, (f'{i}番目の「{作業}」は覚えられません。'
                           '外へ出るものや、お金がかかるものは入れない決まりです')
        if 作業 not in 使える:
            return False, (f'{i}番目の「{作業}」は、いまこの道具にありません。'
                           '動かない手順を覚えると、'
                           '「やります」と言って何も起きないことになります')
    return True, ''


def 覚える(名前, 手順たち, 呼び方=None):
    """
    新しい作業を覚える。

    @param 名前     人に見せる名前（例: 撮影の準備）
    @param 手順たち [{'action': 'add_task', 'why': '…', 'params': {}}]
    @param 呼び方   これで呼ばれたら、この作業だとみなす言葉の並び
    """
    名前 = (名前 or '').strip()
    if not 名前:
        return {'ok': False, '訳': '名前を教えてください'}
    if len(名前) > 30:
        return {'ok': False, '訳': '名前が長すぎます（30文字まで）'}

    よい, 訳 = 手順を確かめる(手順たち)
    if not よい:
        return {'ok': False, '訳': 訳}

    一覧 = _読む()

    # 同じ名前があれば置き換える。二つあると、どちらが動くか分からない。
    一覧 = [x for x in 一覧 if x.get('名前') != 名前]

    一覧.append({
        '名前': 名前,
        '手順': 手順たち,
        '呼び方': 呼び方 or [名前],
        '覚えた日': __import__('datetime').date.today().isoformat(),
        '使った回数': 0,
    })
    _書く(一覧)

    return {
        'ok': True,
        '訳': f'「{名前}」を覚えました（{len(手順たち)}手）。'
              f'次からは「{名前}」と言えば、この順で進めます。',
        '手順数': len(手順たち),
    }


def 忘れる(名前):
    一覧 = _読む()
    残り = [x for x in 一覧 if x.get('名前') != 名前]
    if len(残り) == len(一覧):
        return {'ok': False, '訳': f'「{名前}」は覚えていません'}
    _書く(残り)
    return {'ok': True, '訳': f'「{名前}」を忘れました'}


def 一覧を出す():
    return _読む()


def 見つける(text):
    """
    言われた文が、覚えた作業に当たるかを見る。

    @return (作業, 確からしさ)
    """
    if not text:
        return None, 0.0

    低 = text.lower()
    最良 = None
    最高 = 0.0

    for x in _読む():
        for 呼 in x.get('呼び方', []):
            呼低 = str(呼).lower()
            if not 呼低:
                continue
            if 呼低 in 低:
                # 長い言い方ほど、たまたま当たる見込みが低い
                点 = min(0.95, 0.6 + len(呼低) * 0.05)
                if 点 > 最高:
                    最高 = 点
                    最良 = x

    return (最良, round(最高, 2)) if 最良 else (None, 0.0)


def 使ったことを数える(名前):
    一覧 = _読む()
    for x in 一覧:
        if x.get('名前') == 名前:
            x['使った回数'] = x.get('使った回数', 0) + 1
    _書く(一覧)


def 段取りの形にする(作業):
    """覚えた作業を、段取りと同じ形にして返す（実行の仕組みを共有するため）"""
    return {
        'name': 'learned:' + 作業['名前'],
        'label': 作業['名前'],
        'summary': f'あなたが教えた手順です（{len(作業["手順"])}手）。',
        'steps': [
            {
                'action': h['action'],
                'why': h.get('why') or h['action'],
                'params': h.get('params') or {},
                'confirm': bool(h.get('confirm')),
            }
            for h in 作業['手順']
        ],
        '教わったもの': True,
    }
