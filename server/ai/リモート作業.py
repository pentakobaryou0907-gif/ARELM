# -*- coding: utf-8 -*-
"""
リモート作業 ― エージェントの指示で、遠隔操作の画面から自動で作業する

なぜこれが要るのか:

    遠隔操作の画面（画面を映して押す）は、人が自分で押す前提だった。
    「エージェントの指示で自動で」と頼まれたので、
    AI自身が次の一手を決めて、実際に動かせるようにする。

どこまでやらせるか（安全のための線引き）:

    <b>座標を当てずっぽうに押す・打つことはさせない。</b>

    いまのローカルLLM（Qwen2.5）は文字しか読めず、画面が見えない。
    見えないのに座標を決めさせたら、当てずっぽうで押すことになる。
    それは危ない。

    代わりに、すでに名前が付いた安全な操作
    （アプリを開く・音量を変える・ページを開く・タブを選ぶ、など）
    の中からだけ選ばせる。実行する側（パソコンを操る.js・ブラウザを操る.js）に
    元から入っている決まり（合言葉の画面では打たない、動きすぎない、
    触ってはいけない先には行かない）は、そのまま全部かかる。

    座標を押す・文字を打つ操作は、いまも人が画面を見て押す形のまま。

止まらなくならないために:

    ・考える上限（既定8回）を超えたら、そこで止める。
    ・同じ作業を続けて2回選んだら、進んでいないとみなして止める。
    ・「する」と決めた作業が、渡された使える作業一覧に無ければ、
      そこで止める（無い作業を勝手に作らせない）。

外部へは一切問い合わせません。すべてこの端末の中で完結します。
"""

import json
import re

import ローカルLLM

考える上限 = 8


def _使える作業の説明(使える作業):
    """LLMに見せる、使える作業の一覧文。"""
    行 = []
    for a in 使える作業:
        名 = a.get('名', '')
        説 = a.get('説', '')
        要る = a.get('要る') or []
        要る文 = f'（材料: {"、".join(要る)}）' if 要る else ''
        行.append(f'・{名}: {説}{要る文}')
    return '\n'.join(行)


def _これまでの説明(これまで):
    if not これまで:
        return '（まだ何もしていません）'
    行 = []
    for i, x in enumerate(これまで, 1):
        結果 = x.get('結果') or {}
        訳 = 結果.get('訳', '') if isinstance(結果, dict) else str(結果)
        行.append(f'{i}. 「{x.get("作業")}」{x.get("材料") or ""} → {訳}'[:160])
    return '\n'.join(行)


def _JSONを取り出す(文):
    """
    LLMの返事から、いちばん外側の { … } だけを取り出す。

    LLMは指示通りに書いてくれないことがある
    （前置きを付けたり、コードの囲みを付けたり）。
    最初と最後の中かっこの間だけを見れば、たいてい直る。
    """
    始 = 文.find('{')
    終 = 文.rfind('}')
    if 始 < 0 or 終 < 0 or 終 <= 始:
        return None
    try:
        return json.loads(文[始:終 + 1])
    except (ValueError, TypeError):
        return None


def 一手を決める(目的, これまで, 使える作業):
    """
    次に何をするかを、ローカルLLMに一手だけ決めてもらう。

    @param 目的       頼まれた作業の目的（自由文）
    @param これまで    [{'作業':…, '材料':…, '結果':…}]
    @param 使える作業  [{'名':…, '説':…, '要る':[…]}]
    @return {'する': bool, '作業':…, '材料':…, '訳':…} または
            {'する': False, '終わり': True, '訳':…}
    """
    # --- 止める条件を、LLMに聞く前に機械的に確かめる ---
    #
    # LLMに「もう十分か」を毎回自己申告させると、
    # 続けたがる方に流れやすい。回数と繰り返しは、こちらで数える。
    if len(これまで) >= 考える上限:
        return {
            'する': False, '終わり': True,
            '訳': f'{考える上限}回 動いたので、ここで止めます。'
                  '考え続けて止まらないほうが困るためです。',
        }

    if len(これまで) >= 2:
        直前 = これまで[-1].get('作業')
        その前 = これまで[-2].get('作業')
        if 直前 and 直前 == その前:
            return {
                'する': False, '終わり': True,
                '訳': f'「{直前}」を続けて2回行いました。'
                      '同じ手を繰り返しているので、ここで止めます。',
            }

    作業名たち = {a.get('名') for a in 使える作業}

    指示 = (
        'あなたは遠隔操作の画面を通じて、パソコンを実際に操作するアシスタントです。\n'
        '次の「使える作業」の中から、目的を果たすために次に行う一つだけを選んでください。\n'
        '\n'
        '【使える作業】\n' + _使える作業の説明(使える作業) + '\n'
        '\n'
        '【これまでに行ったこと】\n' + _これまでの説明(これまで) + '\n'
        '\n'
        '必ず、次のJSON形式だけで答えてください。前置きや説明文は書かないでください。\n'
        '・続ける場合: {"作業": "使える作業から選んだ名前", "材料": {…必要な材料…}, "訳": "なぜその作業を選んだか"}\n'
        '・目的をすでに果たした、またはこれ以上できることが無い場合: '
        '{"終わり": true, "訳": "なぜ終わりだと判断したか"}\n'
        '・「使える作業」に無いことは選ばないでください。'
    )

    答え = ローカルLLM.聞く(f'{指示}\n\n【目的】\n{目的}')
    if not 答え:
        return {
            'する': False, '終わり': True,
            '訳': 'ローカルAIが使えなかったため、ここで止めます。'
                  '（Ollamaが動いているか確かめてください）',
        }

    決めた = _JSONを取り出す(答え)
    if not isinstance(決めた, dict):
        return {
            'する': False, '終わり': True,
            '訳': 'AIの返事の形が読み取れなかったため、ここで止めます。',
        }

    if 決めた.get('終わり'):
        return {'する': False, '終わり': True, '訳': (決めた.get('訳') or '目的を果たしたと判断しました。')}

    作業 = (決めた.get('作業') or '').strip()
    if not 作業 or 作業 not in 作業名たち:
        return {
            'する': False, '終わり': True,
            '訳': f'AIが「{作業 or "（空)"}」を選びましたが、使える作業にありません。'
                  '無い作業を行わせないため、ここで止めます。',
        }

    return {
        'する': True,
        '作業': 作業,
        '材料': 決めた.get('材料') if isinstance(決めた.get('材料'), dict) else {},
        '訳': (決めた.get('訳') or '')[:120],
    }
