    def advise(self, topic, options=None, context=None):
        """
        「どれを選べばいい？」に答える。

        過去の記録（うまくいった／失敗した）を根拠にして勧める。
        根拠が無いときは勧めず、正直に「決められる材料がない」と言う。
        決めるのは本人なので、選択肢と判断材料を出すことに徹する。
        """
        context = context or {}
        options = options or []

        if not self.knowledge:
            return {
                'ok': False,
                'certainty': 'unknown',
                'answer': '判断材料がありません。知識メモに経験を記録しておくと、次から根拠を示して勧められます。',
                'sources': [],
            }

        # 過去に失敗と分かっているものを洗い出す
        mistakes = self.knowledge.find_mistakes(topic)
        hits = self.knowledge.search(topic, top_n=5, include_unverified=False)

        lines = []
        recommend = None
        avoid = []

        if mistakes:
            lines.append('過去にうまくいかなかった記録があります:')
            for m in mistakes[:3]:
                lines.append(f'  ・{m["text"]}')
                if m.get('note'):
                    lines.append(f'    → 実際: {m["note"]}')
                avoid.append(m['text'])
            lines.append('')

        if hits:
            lines.append('確認済みの記録:')
            for h in hits[:3]:
                lines.append(f'  ・{h["text"]}')
            recommend = hits[0]['text']
            lines.append('')

        # 選択肢が渡されていれば、避けるべきものに印を付ける
        if options:
            lines.append('選択肢:')
            for opt in options:
                risky = any(self._match_score(set(tokenize(opt, use_ngram=False)), a) > 0.3 for a in avoid)
                mark = '⚠ 過去に問題あり' if risky else ''
                lines.append(f'  ・{opt} {mark}'.rstrip())
            lines.append('')

        if not lines:
            return {
                'ok': False,
                'certainty': 'unknown',
                'answer': f'「{topic}」について記録がないため、お勧めできる根拠がありません。\n'
                          '判断材料が必要でしたら、試した結果を知識メモに残してください。次から根拠を示せます。',
                'sources': [],
            }

        if avoid and not recommend:
            lines.append('避けたほうがよいものは分かりますが、代わりに何を選ぶべきかの記録はありません。')
        elif recommend:
            lines.append('上の記録をふまえると、確認済みの方法を選ぶのが安全です。')

        lines.append('最終的な判断はご自身でお願いします。')

        return {
            'ok': True,
            'certainty': 'confirmed' if hits else 'guess',
            'answer': '\n'.join(lines),
            'sources': ['知識メモ'] + (['誤りの記録'] if mistakes else []),
        }

