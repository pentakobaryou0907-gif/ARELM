    def _answer_inventory(self, query_tokens, products):
        if not products:
            return self._unknown('商品がまだ登録されていません。在庫ページから登録できます。')

        hits = self._search_products(query_tokens, products)
        if not hits:
            total = sum(p.get('quantity', 0) for p in products)
            low = [p for p in products if p.get('quantity', 0) <= p.get('reorderLevel', 5)]
            lines = [f'登録されている商品は{len(products)}種類、在庫は合計{total}点です。']
            if low:
                lines.append('在庫が少ないもの: ' + '、'.join(p.get('name', '') for p in low[:5]))
            return self._ok('\n'.join(lines), ['在庫データ'])

        lines = []
        for p in hits:
            qty = p.get('quantity', 0)
            note = '（在庫が少なくなっています）' if qty <= p.get('reorderLevel', 5) else ''
            lines.append(f'{p.get("name", "")}: {qty}点{note}')
        return self._ok('\n'.join(lines), [f'在庫データ（{len(hits)}件）'])

    def _answer_price(self, query_tokens, products):
        if not products:
            return self._unknown('商品がまだ登録されていません。')

        hits = self._search_products(query_tokens, products)
        if not hits:
            return self._unknown(
                'どの商品の価格かを特定できませんでした。商品名を入れてもう一度お聞きください。'
            )

        lines = []
        for p in hits:
            price = p.get('price', 0)
            lines.append(f'{p.get("name", "")}: {price:,}円')
            # 原価が分かるときだけ粗利を出す。分からないものは推測しない。
            cost = p.get('cost')
            if cost:
                gross = price - cost
                rate = gross / price if price else 0
                lines.append(f'  （原価{cost:,}円 / 粗利{gross:,}円 = {rate * 100:.1f}%）')
        return self._ok('\n'.join(lines), ['商品データ'])

    def _answer_product(self, query_tokens, products):
        if not products:
            # 商品が1件も無いのに「商品がまだ登録されていません」で
            # 会話を止めていた。
            #
            # 「素材」「サイズ」は、intentの手がかりとしては商品向けだが、
            # 「麻の素材の特徴を教えて」のような一般知識の質問にも出てくる。
            # 商品が0件なら、そもそも自分の商品の話のはずがない。
            # None を返し、下の一般知識・ローカルLLMへ続けさせる。
            return None

        hits = self._search_products(query_tokens, products)
        if not hits:
            names = '、'.join(p.get('name', '') for p in products[:8])
            return self._unknown(f'該当する商品が見つかりませんでした。登録されているのは: {names}')

        lines = []
        for p in hits:
            parts = [f'{p.get("name", "")}（{p.get("sku", "")}）']
            for key, label in (('material', '素材'), ('color', 'カラー'), ('size', 'サイズ')):
                if p.get(key):
                    parts.append(f'{label}: {p[key]}')
            if p.get('price'):
                parts.append(f'価格: {p["price"]:,}円')
            lines.append('\n  '.join(parts))
        return self._ok('\n\n'.join(lines), ['商品データ'])

    def _answer_schedule(self, tasks, events, today):
        open_tasks = [t for t in tasks if not t.get('done')]
        overdue = [t for t in open_tasks if t.get('due') and today and t['due'] < today]
        due_today = [t for t in open_tasks if t.get('due') == today]
        today_events = [e for e in events if e.get('date') == today]

        lines = []
        if overdue:
            lines.append(f'期限が過ぎているタスクが{len(overdue)}件あります:')
            lines += [f'  ・{t.get("title", "")}（期限 {t.get("due", "")}）' for t in overdue[:5]]
        if due_today:
            lines.append(f'今日が期限のタスクが{len(due_today)}件あります:')
            lines += [f'  ・{t.get("title", "")}' for t in due_today[:5]]
        if today_events:
            lines.append(f'今日の予定が{len(today_events)}件あります:')
            lines += [f'  ・{e.get("title", "")}' for e in today_events[:5]]

        if not lines:
            if open_tasks:
                return self._ok(
                    f'急ぎのものはありません。未完了のタスクは{len(open_tasks)}件です。',
                    ['タスクデータ']
                )
            return self._ok('未完了のタスクはありません。', ['タスクデータ'])

        return self._ok('\n'.join(lines), ['タスク・予定データ'])

    def _answer_knowledge(self, text):
        """記録した知識から探す。無ければ None を返して次の手に回す。"""
        if not self.knowledge:
            return None

        hits = self.knowledge.search(text, top_n=3)
        mistakes = self.knowledge.find_mistakes(text)

        # 関わりの薄いものは出さない。
        #
        # 「生地について」に会計監査の話が出ていた。
        # 言い換えで広げたぶん、遠いものまで拾うようになったため。
        #
        # 見当違いの答えを返すくらいなら、
        # 「分かりません」と言うほうがましだった。
        # 一度でも的外れを返すと、次から信じてもらえなくなる。
        hits = [h for h in hits if h.get('score', 0) >= 0.75]

        if not hits and not mistakes:
            return None

        lines = []
        sources = []

        if mistakes:
            lines.append('この件では、過去に誤りと分かったことがあります:')
            for m in mistakes[:2]:
                lines.append(f'  ・{m["text"]}')
                if m.get('note'):
                    lines.append(f'    → 実際: {m["note"]}')
            sources.append('誤りの記録')

        if hits:
            if lines:
                lines.append('')
            lines.append('記録から見つかりました:')
            for h in hits:
                mark = '確認済' if h['status'] == 'verified' else '未検証'
                lines.append(f'  ・[{mark}] {h["text"]}')
            sources.append('知識メモ')

        return self._ok('\n'.join(lines), sources)

