    def _画像作成を頼まれたか(self, text):
        """
        画像を作ってと頼まれたかを見る。頼まれていれば、何を描くかを返す。

        「〜の画像を作って」のような形が多いので、
        頼む言い方そのものは取り除き、残りを描く内容とする。
        残りが空なら、何を描くか分からないので頼まれたと見なさない。
        """
        t = (text or '').strip()
        if not any(w in t for w in self.画像を頼む言い方):
            return None

        残り = t
        for w in self.画像を頼む言い方:
            残り = 残り.replace(w, '')
        残り = re.sub(r'[、。 　！!？?を]+$', '', 残り).strip()
        return 残り or None

    # ブランドの記録を頼む言い方
    #
    # 「ブランド名」＋「の記録:」または「について覚えておいて:」＋内容、の形。
    # 記号は全角・半角どちらでも受け取る。
    _ブランド記録の形 = re.compile(
        r'^(?P<ブランド>.{1,30}?)(?:の記録|について覚えておいて)[:：]\s*(?P<内容>.+)$',
        re.S,
    )

    def _ブランド記録を頼まれたか(self, text):
        """
        「ARELMの記録: 値下げして売上が伸びた」のような形かを見る。

        頼まれていれば (ブランド, 内容) を返す。そうでなければ None。
        """
        m = self._ブランド記録の形.match((text or '').strip())
        if not m:
            return None
        ブランド = m.group('ブランド').strip()
        内容 = m.group('内容').strip()
        if not ブランド or not 内容:
            return None
        return ブランド, 内容

