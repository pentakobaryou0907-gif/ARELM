# 「見せて」と頼まれたか。
#
# 「在庫を見せて」は問いの形をしているが、
# <b>見せること自体が答え</b>なので、知識ではなく作業に回す。
_見せての言い方 = ('見せて', '見せる', '出して', '教えてほしい', '一覧',
              'を見る', 'を見たい', 'どうなってる', 'どうなっている')


def _見せてと頼まれたか(text):
    t = (text or '').strip()
    return any(w in t for w in _見せての言い方)


def is_question(text):
    if QUESTION_MARKS.search(text or ''):
        return True

    # 「〜について」などで終わる／含む言い方も、問いとして扱う
    t = (text or '').strip().rstrip('。 　')
    return any(w in t for w in 問いの言い方)



class ChatEngine:
    """
    会話の受け答えを組み立てる。

    データはツール側（ブラウザ）から渡してもらう。
    エンジン側は外部と通信しないため、必要な情報は引数で受け取る。
    """

    def __init__(self, learner=None, knowledge=None, semantic=None):
        # 会話を続けるための記憶。端末のメモリ上にだけ置き、外へは出さない。
        self.会話たち = conversation.ConversationStore()
        self.learner = learner
        self.knowledge = knowledge
        self.semantic = semantic

    # ---------- 検索 ----------

    def _match_score(self, query_tokens, text):
        """語の重なりで関連度を測る。意味モデルがあれば言い換えも拾う。"""
        if not text:
            return 0.0
        t_tokens = set(tokenize(text, use_ngram=False))
        if not t_tokens:
            return 0.0

        overlap = len(query_tokens & t_tokens)
        base = overlap / max(len(query_tokens), 1)

        if self.semantic and base < 0.5:
            try:
                sem = self.semantic.text_similarity(' '.join(query_tokens), text)
                if sem and sem > base:
                    base = max(base, sem * 0.8)  # 意味の一致は少し控えめに評価
            except Exception:
                pass
        return base

    def _search_products(self, query_tokens, products, top_n=3):
        hits = []
        for p in products:
            text = ' '.join(
                str(p.get(k, '')) for k in ('name', 'sku', 'material', 'color', 'description')
            )
            score = self._match_score(query_tokens, text)
            if score > 0.15:
                hits.append((score, p))
        hits.sort(key=lambda x: -x[0])
        return [p for _, p in hits[:top_n]]

    # ---------- 回答の組み立て ----------

    def respond(self, text, context=None):
        """
        質問に答える。
        context にはツール側の現在のデータ（商品・タスク等）を入れてもらう。
        """
        text = (text or '').strip()
        if not text:
            return self._unknown('何をお聞きになりたいですか？')

        context = context or {}
        会話体 = self.会話たち.get(context.get('session_id'))
        会話体.加える('あなた', text)

        # --- 画像を作ってほしいと頼まれた場合 ---
        #
        # この端末の中の ComfyUI（Flux.2 Klein）で作る。外部のAPIは使わない。
        # 生成には数分かかるので、すぐには終わらない。
        # 番号を返し、「できたら教えて」と案内するところまでで一旦返事をする。
        画像の頼み = self._画像作成を頼まれたか(text)
        if 画像の頼み:
            答え = self._画像作成を始める(画像の頼み)
            会話体.加える('私', 答え['answer'])
            return 答え

        # --- ブランドの記録を、はっきり頼まれた場合 ---
        #
        # 「ARELMの記録: 値下げして売上が伸びた」のような形。
        # 会話が終わると忘れてしまう分を、ブランドごとに積み重ねる。
        ブランド記録の頼み = self._ブランド記録を頼まれたか(text)
        if ブランド記録の頼み:
            ブランド, 内容 = ブランド記録の頼み
            結果 = ブランドの記憶.記録する(ブランド, 内容)
            答え = {
                'ok': 結果['ok'], 'certainty': 'confirmed' if 結果['ok'] else 'unknown',
                'answer': 結果['訳'], 'sources': [f'{ブランド}の記憶'],
            }
            会話体.加える('私', 答え['answer'])
            return 答え

        # --- 持っていない情報は、何より先に断る ---
        #
        # ここを後回しにしたところ、「明日の天気を教えて」が
        # 「教えて」という言葉だけで技能として受け取られ、
        # 断れなくなっていた。
        # 嘘をつかないことが最優先なので、この確認を先頭に置く。
        持たない = find_out_of_scope(text)
        if 持たない:
            答え = {
                'ok': False,
                'certainty': 'unknown',
                'answer': f'「{持たない}」については分かりません。\n'
                          'このAIは、あなたがこのツールに入れたデータからしか答えられません。\n'
                          '商品・在庫・価格・タスク・記録した知識・ツールの使い方についてなら答えられます。',
                'sources': [],
            }
            会話体.加える('私', 答え['answer'])
            return 答え

        # --- 前の質問への答えを待っている場合は、それを最優先で受け取る ---
        if 会話体.待っていること:
            返事 = self._続きを受け取る(text, 会話体, context)
            if 返事:
                会話体.加える('私', 返事.get('answer', ''))
                return 返事

        # --- 「それ」「さっきの」を、直前の話に結びつける ---
        text, 結びつけた先 = conversation.前の話に結びつける(text, 会話体)

        # --- 脇に置いた作業へ戻るか ---
        #
        # 別の話に移ったあと、「戻る」「続き」と言われたら、
        # 途中まで集めた中身のまま再開する。
        if 会話体.脇に置いた and not 会話体.待っていること:
            if getattr(会話体, '脇は今置いた', False):
                # 置いたばかりの発言では、まだ何も判断しない
                会話体.脇は今置いた = False
            else:
                返事 = self._脇に置いたものへ戻るか(text, 会話体)
                if 返事:
                    会話体.加える('私', 返事.get('answer', ''))
                    return 返事

        # --- 見せた段取りに「実行して」と言われたか ---
        #
        # 先に見て、それから動く。
        # ここを飛ばして即実行にしていたら、
        # 言い間違いがそのまま六つの作業になっていた。
        if 会話体.待っている段取り:
            返事 = self._段取りの実行を受け取る(text, 会話体)
            if 返事:
                会話体.加える('私', 返事.get('answer', ''))
                return 返事

        # --- ひとまとまりの仕事として頼まれていないか ---
        #
        # 「新商品を出す準備をして」は、一手では終わらない。
        # ここを一つの技能として受け取ると、
        # 六つ要る作業のうち一つだけやって終わってしまう。
        #
        # 質問には反応しない。
        # 「新商品ってどう出すの」に六つ動き出したら、それは押しつけになる。
        # あなたが教えた作業を、先に見る。
        #
        # 私が書いた段取りより、あなたが教えたものを優先する。
        # 同じ言葉に両方当たったなら、
        # あなたが決めた手順のほうが、あなたの意図に近い。
        教わった, 教わり確度 = 覚えた作業.見つける(text)
        if 教わった and 教わり確度 >= 0.6 and 段取り.頼まれているか(text):
            段 = 覚えた作業.段取りの形にする(教わった)
            文 = [f'「{段["label"]}」ですね。あなたに教わった手順です。', '',
                  '次の順で進めます:', '']
            for i, h in enumerate(段['steps'], 1):
                文.append(f'{i}. {h["why"]}')

            # 本人が「確認なしで最後まで進める」を選んでいるときは、そのまま進める
            自動 = bool((context or {}).get('自動で進める'))
            if 自動:
                段 = dict(段, steps=[dict(h, confirm=False) for h in 段['steps']])
                文[2:3] = ['そのまま、次の順で進めます:']
                文 += ['', '途中で止まったら、そこで止めて理由を言います。']
            else:
                文 += ['', 'この順でよければ「実行して」と言ってください。']

            答え = {
                'ok': True, 'certainty': 'confirmed',
                'answer': '\n'.join(文), 'sources': ['あなたが教えた手順'],
                'plan': 段,
            }
            if 自動:
                答え['run'] = True
            else:
                会話体.待っている段取り = 段
            会話体.加える('私', 答え['answer'])
            return 答え

        型, 段取りの確からしさ = 段取り.find_plan(text)
        if 型 and 段取りの確からしさ >= 0.55:
            if 段取り.頼まれているか(text):
                自動 = bool((context or {}).get('自動で進める'))
                答え = 段取り.段取りの返事(型, text, 段取りの確からしさ, 自動=自動)
                # 自動のときは、すぐ進めるので、「実行してと言われるのを待つ」状態にはしない
                会話体.待っている段取り = None if 自動 else 答え['plan']
                会話体.加える('私', 答え['answer'])
                return 答え

            # 頼まれてはいないが、まとめてできることは伝えておく。
            # 黙って一手だけやるより、選べる方がよい。
            会話体.出せる段取り = 型.name

        # --- 一文に、いくつもの頼みが入っているとき ---
        #
        # 「在庫を確認して、少ないものをやることに入れて」が、在庫の確認だけで止まっていた。
        # 決まった段取りや教わった手順でなくても、頼みごとに分けて、順番に進める。
        # 質問には反応しない。分からなかった部分は、推測で埋めず、そのまま伝える。
        if 段取り.頼まれているか(text):
            複数 = 頼みを分ける.手順に直す(text, ChatEngine._言葉から拾う)
            if 複数:
                自動 = bool((context or {}).get('自動で進める'))
                段 = {
                    'name': 'adhoc',
                    'label': f'頼まれた作業（{len(複数["steps"])}手）',
                    'summary': '頼まれたことを、順番に進めます。',
                    'steps': 複数['steps'],
                }
                文 = [f'{len(複数["steps"])}つの頼みとして受け取りました。', '',
                      'そのまま、次の順で進めます:' if 自動 else '次の順で進めます:', '']
                for i, h in enumerate(段['steps'], 1):
                    文.append(f'{i}. {h["why"]}')
                if 複数['分からなかった']:
                    文 += ['', '次の部分は分からなかったので、行いません:']
                    文 += [f'・「{x}」' for x in 複数['分からなかった']]
                文 += ['', '足りない中身は、その手順のところで聞きます。']
                文.append('途中で止まったら、そこで止めて理由を言います。' if 自動
                          else 'この順でよければ「実行して」と言ってください。')
                答え = {
                    'ok': True, 'certainty': 'confirmed',
                    'answer': '\n'.join(文), 'sources': ['あなたの指示'],
                    'plan': 段,
                }
                if 自動:
                    答え['run'] = True
                else:
                    会話体.待っている段取り = 段
                会話体.加える('私', 答え['answer'])
                return 答え

        # --- 話し方の調子を読む（「？」「！」も手がかりとして使う） ---
        調子 = tone.read(text)
        応じ = tone.応じ方(調子)

        # --- 会話の中から、覚えるべきことを自分で拾う ---
        #
        # 大事なことは、たいてい<b>ついでに言われる</b>。
        # 改まって「これを覚えて」とは言わない。
        # だから、こちらが拾わなければ貯まらない。
        #
        # 答えることとは別に、裏で拾っておく。
        # 拾ったことは、あとで見られるようにしてある。
        自分で覚えたもの = None
        if self.knowledge:
            try:
                拾えるか = 自分で覚える.会話から拾う(text, self.knowledge.entries[-200:])
                if 拾えるか['覚えるか']:
                    見立て = rules.check(拾えるか['中身'])
                    if 見立て['ok']:
                        self.knowledge.add(拾えるか['中身'], source='manual',
                                           topic='会話:' + 拾えるか['種類'],
                                           note='会話から自分で拾いました')
                        self.knowledge.save()
                        自分で覚えたもの = 拾えるか['種類']
            except Exception as e:
                # 拾えなくても、答えることはできる。
                # ここで止めると、会話そのものが返らない。
                print(f'会話から拾えませんでした: {e}')

        # --- 「違う」と言われたとき ---
        #
        # いままでは謝って終わっていた。次も同じことをしていた。
        # <b>直さなければ、同じことを繰り返す。</b>
        #
        # 覚えるべきは「何を間違えたか」ではなく「次はどうするか」。
        if 失敗から直す.違うと言われたか(text):
            # 名前は 履歴 と 内容。
            # やりとり／中身 と書いて、一度も動いていなかった。
            直前の手 = None
            try:
                for 発言 in reversed(会話体.履歴[-6:]):
                    if 発言.get('誰') == '私' and '実行します' in (発言.get('内容') or ''):
                        直前の手 = 発言['内容'].split('を実行')[0].strip()
                        break
            except Exception:
                直前の手 = None

            if 直前の手:
                直前の言葉 = ''
                try:
                    for 発言 in reversed(会話体.履歴[-8:]):
                        if 発言.get('誰') != '私':
                            直前の言葉 = 発言.get('内容') or ''
                            break
                except Exception:
                    直前の言葉 = ''

                r = 失敗から直す.直しを覚える(直前の言葉 or text, 直前の手)
                答え = self._ok(
                    f'すみません。「{直前の手}」は違いましたね。\n\n'
                    + r['訳'] + '\n\n'
                    + '正しくは何をすればよかったか教えていただけると、'
                    + '次はそちらを選びます。', [])
                会話体.加える('私', 答え['answer'])
                return 答え

        # --- 「やめて」だけを言われたとき ---
        #
        # 段取りを待っているときにしか受け取っていなかったので、
        # 単独で言うと「分かりません」と返っていた。
        #
        # やめたいときに通じないのは、いちばん困る。
        # 動いている最中に止められないのと同じ。
        低 = (text or '').strip().lower()
        if 低 in ['やめて', 'やめ', 'やめる', 'キャンセル', '中止', 'ストップ',
                  'とめて', '止めて', 'もういい', '結構です']:
            会話体.待っている段取り = None
            会話体.待っていること = None
            答え = self._ok('分かりました。やめておきます。'
                           '必要になったら、また言ってください。', [])
            会話体.加える('私', 答え['answer'])
            return 答え

        # --- 名前を呼ばれただけのとき ---
        #
        # 「アレラム」とだけ言われて
        # 「どの操作か分かりません」と返していた。
        #
        # 呼ばれたら、まず返事をする。
        # 用件はそのあとでよい。
        # 名前を呼んだだけで操作名を求められるのは、
        # 呼びかけとして成り立っていない。
        呼ばれた = self._名前を呼ばれただけか(text)
        if 呼ばれた:
            答え = self._ok(呼ばれた, [])
            答え['tone'] = 調子
            会話体.加える('私', 答え['answer'])
            return 答え

        # --- 挨拶・お礼などの雑談 ---
        雑 = smalltalk.find(text)
        if 雑:
            答え = self._ok(smalltalk.reply(雑), [])
            答え['tone'] = 調子
            会話体.加える('私', 答え['answer'])
            return 答え

        # --- このツールの決まり（消さない・外へ出さない・公開は本人）に触れる頼み ---
        #
        # 黙って別の作業にすり替えたり（「外へ送信して」に在庫を出す）、
        # 無関係な記録を出したり（「パスワードを教えて」）していた。
        # できないことは、できないと言い、代わりにできることを添える。
        境界の返事 = self._決まりに触れるか(text)
        if 境界の返事:
            答え = self._ok(境界の返事, ['このツールの決まり'])
            答え['tone'] = 調子
            会話体.加える('私', 答え['answer'])
            return 答え

        # --- 「全部自動でやって」「任せる」のように、中身のない、お任せの言葉 ---
        #
        # 何をするかが入っていないので、雑談の返事（「具体的に教えてください」）に流れていた。
        # 任せてもらえること、いまの進め方、頼み方の例を、はっきり返す。
        if self._お任せの言葉か(text):
            自動 = bool((context or {}).get('自動で進める'))
            文 = ['はい、任せてください。頼んでもらえれば、代わりに進めます。']
            文.append('いまの進め方: ' + ('確認なしで、最後まで進めます。' if 自動
                                    else '順番を見せて、「実行して」と言われてから進めます（設定の「エージェントの進め方」で、確認なしにできます）。'))
            文 += ['', '頼み方の例（いくつ続けて言っても、順番に進めます）:',
                   '・「在庫を確認して、少ないものをやることに入れて」',
                   '・「新しいTシャツを登録して、説明文も作って」',
                   '・「今日を始めて」「一日を終えて」',
                   '・「バックアップを取って、ひらめき箱を見せて」',
                   '', '足りない中身（商品名など）は聞きます。失敗したら、そこで止めて理由を言います。',
                   '消す・外へ送る・公開する、は行いません。', '', '何をしましょうか。']
            答え = self._ok('\n'.join(文), ['このツールの決まり'])
            答え['tone'] = 調子
            会話体.加える('私', 答え['answer'])
            return 答え

        # --- このツール自身について聞かれた場合 ---
        #
        # 「なんで画像生成ができないの？」に「分かりません」と
        # 返していた。自分の作りについて聞かれているのに
        # 答えられないのは、使う人にとって行き止まりになる。
        自分の話, 確信度 = 自分のこと.find(text)
        if 自分の話 and 確信度 >= 0.6:
            答え = self._ok(自分の話.答え, ['このツールの作り'])
            会話体.加える('私', 答え['answer'])
            return 答え

        # --- 係で分けて受け持つ ---
        #
        # 一人が全部やると、どの話も同じ調子の答えになる。
        # 在庫の話は在庫係が、値段の話はお金係が答える。
        # それぞれ、見るところが違う。
        #
        # 迷っているときは、一人に答えさせない。
        # 迷いは、一つの見方では解けないから起きる。
        # --- 何ができるかを聞かれた場合 ---
        if self._能力を聞かれているか(text):
            答え = self._ok(skills.describe_all(), ['このツールの機能一覧'])
            会話体.加える('私', 答え['answer'])
            return 答え

        # 問いの形なら、作業より先に知識を見る。
        #
        # 「粗利率について」で値段の作業が動き、
        # 「適正在庫の考え方」で在庫一覧が出ていた。
        #
        # <b>尋ねられているのに、作業を始めるのは押しつけ</b>。
        # 知りたいだけの人に、勝手に何かを始めない。
        #
        # ただし「〜を見せて」のような、
        # 見せること自体が答えになるものは、この先の作業に任せる。
        # 知識が見つからなければ、そちらに回る。
        # 「どっちがいい？」のような、選ぶための問いは別に扱う。
        #
        # そちらは、失敗と成功の両方の記録を出して、
        # 判断は本人に委ねる形にしてある。
        # 知識で先回りすると、その良さが消えてしまう。
        # intent はこの先で決まるので、ここでは自分で見る。
        # 先に使おうとして、定義される前に触っていた。
        # 「バックアップはいつ取った？」のように、ツール自身の状況を聞く言い方は、
        # 一般の知識メモ（無関係な歴史の記録まで拾っていた）ではなく、
        # 先に技能（答えを出す作業）へ回す。
        先の技能, 先の確信 = skills.find_skill(text)
        技能で答える = bool(先の技能 and getattr(先の技能, '答えになる', False) and 先の確信 >= 0.6)

        if (self.knowledge and is_question(text)
                and not 技能で答える
                and detect_intent(text) != 'advise'
                and not _見せてと頼まれたか(text)):
            知識の答え = self._answer_knowledge(text)
            if 知識の答え:
                会話体.加える('私', 知識の答え['answer'])
                return 知識の答え

        # --- 作業として受け取れるか ---
        #
        # 二段構えにしてある。
        #
        # 1. 見るだけの作業（今日の状況・在庫を見る・点検など）は、
        #    頼み方に関わらず通す。
        #    「今日の状況」とだけ言われても通じてほしいため。
        #    データを変えないので、間違って通しても害が小さい。
        #
        # 2. データを変える作業（登録・追加・削除）は、
        #    はっきり頼まれたときだけ通す。
        #    質問のつもりで書き換わってしまうと困るため。
        作業, 確信 = skills.find_skill(text)
        # 質問には技能を動かさない。ただし「見せること自体が答え」になる
        # 作業だけは、質問でも動かす。
        # 「いま何をしてる？」に様子を出さないのでは、答えたことにならない。
        質問だが答えになる = 作業 is not None and getattr(作業, '答えになる', False)
        if 作業 and 確信 >= 0.6 and (not self._質問の形か(text) or 質問だが答えになる):
            見るだけ = not 作業.slots
            if 見るだけ or self._実行を頼まれているか(text):
                返事 = self._作業を始める(作業, text, 会話体, context)
                if 返事:
                    会話体.加える('私', 返事.get('answer', ''))
                    return 返事

        intent = detect_intent(text)



        # ただし、実際の記録から答えられるなら、そちらが先。
        #
        # 「海外発注と国内発注どっちがいい？」に対して、
        # 一般論の見方を三つ並べていた。
        # だがこの道具には、実際に6週間かかった記録がある。
        # 持っている事実より一般論を先に出すのは、劣化。
        #
        # 見方を並べるのは、記録から答えられないときだけにする。
        # 判定は自分で作らない。すでにある intent を使う。
        # 二つの判定が食い違うと、どちらが正しいか分からなくなる。
        割り振り = 係たち.割り振る(text)

        if (割り振り['働かせ方'] == '相談して'
                and len(割り振り['係たち']) >= 2
                and intent != 'advise'
                and intent != 'knowledge'):
            答え = self._相談の答え(text, 割り振り)
            会話体.加える('私', 答え['answer'])
            return 答え

        query_tokens = set(tokenize(text, use_ngram=False))

        products = context.get('products') or []
        tasks = context.get('tasks') or []
        events = context.get('events') or []
        today = context.get('today') or ''

        # --- 在庫について ---
        if intent == 'inventory':
            return self._answer_inventory(query_tokens, products)

        # --- 価格・原価について ---
        if intent == 'price':
            return self._answer_price(query_tokens, products)

        # --- 商品について ---
        if intent == 'product':
            答え = self._answer_product(query_tokens, products)
            if 答え:
                return 答え

        # --- どれを選ぶべきか（過去の記録を根拠に助言する） ---
        if intent == 'advise':
            return self.advise(text, context=context)

        # --- 次に何をすべきか ---
        if intent == 'next':
            steps = self.next_steps(context)
            lines = ['今の状況から、次にできることです:', '']
            for i, s in enumerate(steps, 1):
                lines.append(f'{i}. {s["label"]}')
                if s['detail']:
                    lines.append(f'   {s["detail"]}')
                lines.append(f'   理由: {s["why"]}')
                lines.append('')
            lines.append('どれから進めますか。順番はご自身で決めてください。')
            return self._ok('\n'.join(lines), ['タスク・在庫データ'])

        # --- タスク・予定について ---
        if intent in ('task', 'schedule'):
            return self._answer_schedule(tasks, events, today)

        # --- 記録した知識について ---
        if intent == 'knowledge' or is_question(text):
            answer = self._answer_knowledge(text)
            if answer:
                return answer

        # --- 使い方について ---
        #
        # 載っていない使い方のときは None が返る。
        # そのまま返すと、答えが空のまま画面に届いてしまう。
        # 実際「フランスの首都はどこ」で何も返らなくなっていた。
        if intent == 'howto':
            答え = self._answer_howto(text)
            if 答え:
                return 答え

        # --- どれにも当てはまらない ---
        #
        # 自作AIの知識には無くても、ローカルLLM（Ollama・Qwen2.5）が
        # 動いているなら、そちらに聞く。端末の中だけで完結し、
        # 外部には一切送らない。
        #
        # 動いていない・答えられなかったときは、
        # これまで通り正直に「分かりません」と言う。
        # ローカルLLMが無くても、会話が止まってはいけない。
        # 話に出ているブランドの、過去の記録があれば混ぜる。
        #
        # 「このブランド、前に何をやってどうなったか」に答えるには、
        # 会話の記憶（30分で切れる）だけでは足りない。
        # ブランドごとに積み重ねた記録から、直近ぶんだけ質問に添える。
        話題のブランド = ブランドの記憶.文中のブランドを探す(text)
        記憶の文 = ブランドの記憶.プロンプトへ差し込む文(話題のブランド) if 話題のブランド else ''

        # 直前までのやり取りを添える。
        #
        # 会話体.履歴 には毎ターン積んでいるのに、ここでは使わずに
        # 今回の発言（text）だけをLLMへ渡していたため、「さっきの文章の
        # ここを直して」と言っても、AIには「さっきの文章」が何なのか
        # まったく伝わっていなかった（対話的な編集ができない不具合）。
        # 直近数往復だけを渡す（長すぎると答えが遅くなるため）。
        直近 = [h for h in 会話体.履歴[:-1] if h.get('内容')][-8:]
        やり取りの文 = ''
        if 直近:
            行たち = [f"{h['誰']}: {h['内容']}" for h in 直近]
            やり取りの文 = '【これまでのやり取り】\n' + '\n'.join(行たち)

        質問の中身 = '\n\n'.join(p for p in [やり取りの文, f'【今回の発言】\n{text}' if やり取りの文 else text] if p)
        LLMへの質問 = f'{記憶の文}\n\n{質問の中身}' if 記憶の文 else 質問の中身

        # マルチエージェント化: 名指し＞今の画面＞発言の言葉、の順で
        # 専門の担当を選び、その立場で答えるよう指示を先頭に付ける。
        # 画面と話題が食い違うときは、話題に合う担当が「引き継いで」答える。
        担当選択 = エージェント定義.エージェントを選ぶ詳細(page=context.get('page'), 発言=text)
        担当id = 担当選択['id']
        担当指示 = エージェント定義.エージェントの指示文(担当id, 担当選択['引き継ぎ元']) if 担当id else ''
        if 担当指示:
            LLMへの質問 = f'【担当】\n{担当指示}\n\n{LLMへの質問}'

        # 設定ページ「AIの話し方」。書かれていれば、口調の指示として先頭に付ける。
        # 空なら何も変わらない（これまで通りの返事）。
        話し方 = (context.get('persona') or '').strip()
        if 話し方:
            LLMへの質問 = (
                f'【話し方の指示。この通りの口調で答えてください】\n{話し方}\n\n{LLMへの質問}'
            )

        ローカルの答え = None
        if ローカルLLM.使えるか():
            ローカルの答え = ローカルLLM.聞く(LLMへの質問)

        if ローカルの答え:
            出所たち = ['ローカルAI（Qwen2.5・この端末の中だけで動作）']
            if 記憶の文:
                出所たち.append(f'{話題のブランド}の記憶')
            返事 = {
                'ok': True,
                'certainty': 'external',
                'answer': ローカルの答え,
                'sources': 出所たち,
                'agent': エージェント定義.エージェント情報(担当id, 担当選択['引き継ぎ元']) if 担当id else None,
            }
        else:
            返事 = self._fallback(text)
        # 困っている・急いでいると読めた場合は、まずそれを受け止める。
        # 同じ内容でも、いきなり説明を並べるより通じやすい。
        if 応じ['前置き']:
            返事['answer'] = 応じ['前置き'] + '\n\n' + 返事['answer']
        返事['tone'] = 調子
        会話体.加える('私', 返事.get('answer', ''))
        if 結びつけた先:
            返事['answer'] = f'（「{結びつけた先}」のことだと受け取りました）\n\n' + 返事['answer']
        return 返事


    # ---------- 会話を続けるための処理 ----------

    # 何ができるかを尋ねる言い方
    能力を聞く言い方 = [
        '何ができる', 'なにができる', 'できること', '機能', '使い方',
        'どうやって', 'ヘルプ', 'help', 'できるの', '何をしてくれる',
    ]

    # 実行を頼まれたことを示す言い方
    #
    # 「在庫は？」は質問。「在庫を見せて」は依頼。
    # この違いを取り違えると、答えるべきときに実行しようとする。
    実行を頼む言い方 = [
        'して', 'したい', 'してほしい', 'してください', 'ください',
        '登録', '追加', '作って', '書いて', '消して', '忘れて',
        '見せて', '出して', '教えて', '調べて', '始め', 'やって',
        '残して', '記録', 'つけて', '点検',
        # 「バックアップを取って」が、末尾の「って」で質問と取り違えられ、
        # 技能が動かず、一般の会話に流れていた。
        '取って', '入れて', '入れといて', '保存して', 'しといて',
    ]

    # このツールが「しない」と決めていること。ここに当たる頼みは、
    # 別の作業に流さず、理由と代わりにできることを返す。
    _決まりの対象 = r'(データ|ファイル|フォルダ|商品|在庫|売上|記録|履歴|バックアップ|控え|ひらめき|学習|全部|すべて|全て|ぜんぶ)'

    @staticmethod
    def _お任せの言葉か(text):
        """
        「全部自動でやって」「任せるよ」のような、中身のないお任せの言葉か。
        何をするかが入っていれば（「在庫を見てやって」など）、お任せ扱いにしない。
        """
        t = re.sub(r'[\s。！!、,]+', '', text or '')
        前 = r'(?:(?:全部|全て|すべて|ぜんぶ|全自動|自動|代わりに|私の代わりに|何でも|なんでも)(?:で|を)?)+'
        やる = r'(?:やって|やっといて|お願い|おねがい|行って|進めて|してね|しといて)(?:ください|ね|よ|くれ)?'
        任せ = r'(?:任せる|任せた|まかせる|まかせた)(?:よ|ね)?(?:ください)?'
        return bool(re.fullmatch(前 + やる, t) or re.fullmatch(任せ, t) or re.fullmatch(前 + 任せ, t))

    @classmethod
    def _決まりに触れるか(cls, text):
        t = (text or '').strip()
        if not t:
            return None

        # 消す。「覚えたことを忘れて」は、このツールの正式な作業（忘れる）なので対象外。
        if (re.search(cls._決まりの対象 + r'.{0,8}(消して|消去|削除|全部消|空にして|初期化|破棄|捨てて)', t)
                and not re.search(r'(覚え|忘れ)', t)):
            return ('それは行いません。このツールは、データやファイルを消す操作を持っていません（「消さない」決まりです）。\n'
                    '使わなくなったものは、「整理済み」「見送り」に移せます。記録は残るので、あとで戻せます。\n'
                    '覚えさせたことを取り除きたいときは、「〇〇を忘れて」と言ってください。')

        # 外へ送る
        if (re.search(r'(外部|外に|外へ|社外|クラウド|ネット(に|へ)|他社|他人|第三者).{0,10}(送|出し|アップロード|共有|渡し)', t)
                or re.search(cls._決まりの対象 + r'.{0,8}(を)?.{0,4}(アップロード|送信|外部へ|外部に)', t)):
            return ('それは行いません。このツールは、データを外へ送信しません（「外へ出さない」決まりです）。\n'
                    '手元で使うために書き出すことはできます。「在庫を書き出して」と言うと、CSVにして手元に落とせます。'
                    '渡すかどうかは、あなた自身が決めて、あなたの手で渡してください。')

        # 公開・出品。「公開前チェック」は、公開そのものではないので対象外。
        if (re.search(r'(公開|出品|投稿|販売開始)(して|しといて|お願い|してください|したい)', t)
                and '公開前' not in t):
            return ('公開は、こちらからは行いません。SUZURIの「商品を公開する」ボタンは、あなた自身が押します。\n'
                    '公開の前に、決めた約束を守れているかを一緒に確かめられます。「公開前チェックの状況」と言ってください。')

        # パスワード・鍵を見せる
        if re.search(r'(パスワード|暗証番号|APIキー|秘密鍵|合言葉)(を|は|って)?.{0,6}(教えて|見せて|表示して|出して|知りたい|何)', t):
            return ('パスワードや鍵は、ここでは見せません（このツール側では、元に戻せない形でしか持っていません）。\n'
                    '忘れたときは、設定の「ログインなしで使う」（このMacだけ）や、パスワードの作り直しから入れます。')

        return None

    def _質問の形か(self, text):
        """
        答えを求められているかを見る。

        「在庫は？」は在庫の中身を知りたいのであって、
        在庫の画面を開いてほしいわけではない。
        ここを取り違えると、答えるべきときに画面を開いてしまう。
        """
        t = (text or '').strip()
        if not t:
            return False

        if t.endswith(('？', '?')):
            return True

        # 「〜は」「〜って」で終わるのも、たいてい問いかけ。
        #
        # ただし「作って」「書いて」のように、
        # 動詞の「〜て」で終わる依頼も「って」で終わることがある。
        # 「黒い千鳥格子の柄を作って」を問いかけと見なして、
        # 技能が動かなくなっていた。
        #
        # はっきり頼む言葉が入っていれば、問いかけではない。
        if t.endswith(('は', 'って', 'かな', 'だっけ')):
            if not self._実行を頼まれているか(t):
                return True

        # 「いくら」「どれくらい」など、答えを求める言い方
        return any(w in t for w in ['いくら', 'どれくらい', 'どのくらい', '何個', '何件', '残って'])

    def _実行を頼まれているか(self, text):
        """
        質問ではなく、何かを行ってほしいと言われているかを見る。

        末尾が「？」「か」で終わるものは質問とみなす。
        ただし「登録して？」のように、依頼の言葉が入っていれば依頼とする。
        """
        t = (text or '').strip()
        if not t:
            return False

        頼んでいる = any(w in t for w in self.実行を頼む言い方)
        質問の形 = t.endswith(('？', '?')) or t.endswith(('か', 'かな', 'かね'))

        if 頼んでいる:
            return True
        if 質問の形:
            return False

        # 「タスク 〇〇」「メモ 〇〇」のように、
        # 名前のあとに中身が続く形も依頼として受け取る
        for 技 in skills.SKILLS:
            if not 技.slots:
                continue
            for w in 技.words:
                if t.startswith(w) and len(t) > len(w) + 1:
                    return True

        return False

    # 聞き返しの答えではなく、別の話だと分かる言い方
    #
    # ここに載せるのは、答えとしてはまず出てこないものだけにしてある。
    # 広く取りすぎると、ふつうの答えまで別の話と見なしてしまう。
    別の話の合図 = [
        '何ができる', 'なにができる', 'できること', '使い方', 'ヘルプ',
        'やめ', 'キャンセル', '中止', '違う話', 'それより',
        'こんにちは', 'おはよう', 'こんばんは', 'ありがとう',
    ]

    # 数で答えてもらう項目
    数で答える項目 = {'price', 'quantity', 'cost', 'amount', '数量', '価格', '原価'}

    def _困っているときの答え(self, text):
        """
        困っている人に、手を貸す。

        「やめておきます」で終わらせない。
        困っているのは、次に何をすればいいか分からないから。
        なら、次にできることを差し出す。

        並べすぎない。三つまで。
        たくさん並べても、選べないから困っているのは変わらない。
        """
        文 = ['分からないときは、こちらで見てみます。', '']

        できること = []

        # いま実際に手を付けられることを、データから拾う。
        # 一般論の一覧を出しても、選べない。
        try:
            import 覚えた作業
            覚え = 覚えた作業.一覧を出す()
            for x in 覚え[:3]:
                できること.append(f"「{x['名前']}」— {len(x['手順'])}手で進みます")
        except Exception:
            pass

        if not できること:
            できること = [
                '「今日の状況」— 予定とやることを出します',
                '「在庫を見せて」— 残りと金額を出します',
                '「次は何をすればいい」— いま手を付けるものを選びます',
            ]

        for x in できること:
            文.append(f'・{x}')

        文.append('')
        文.append('どれかを言ってもらえれば、そこから進めます。')
        文.append('決めるのが難しい話なら、「どう思う」と聞いてください。'
                 'いくつかの見方を出します。')

        return self._ok('\n'.join(文), [])

    def _相談の答え(self, text, 割り振り):
        """
        複数の係が、それぞれの見方で言う。

        <b>無理にまとめない。</b>
        食い違ったら、それも含めて出す。
        食い違いこそ、判断の材料になる。

        一つにまとめると、
        「なぜそう決まったか」が消えてしまう。
        """
        係一覧 = 割り振り['係たち']

        # 「係」という言葉は表に出さない。
        #
        # 中で何人が見ているかは、使う人には関係のないこと。
        # 大事なのは<b>見方が複数あること</b>であって、
        # 誰が言ったかではない。
        #
        # 「在庫係が言うには」と書くと、
        # 中の作りを覚えないと読めない文になる。
        # 見出しは、その係が何を見るかで書く。
        #
        # 「値段・原価・利益から見ると」は日本語として不自然だった。
        # 「◯◯から見ると」に入れて自然な言い方を、係ごとに持たせる。
        言い方 = {
            'お金係': 'お金の面',
            '在庫係': '在庫の面',
            'SNS係': '売り方の面',
            '分析係': '数字の面',
            '作り方係': '作りの面',
            '段取り係': '進め方の面',
        }

        数の言い方 = {1: '一つ', 2: '二つ', 3: '三つ'}.get(len(係一覧), f'{len(係一覧)}つ')
        文 = [f'決めるのが難しい話ですね。見るところが{数の言い方}あります。', '']

        for i, c in enumerate(係一覧, 1):
            見出し = 言い方.get(c['名前']) or c.get('得意') or c['名前']
            文.append(f"{i}. {見出し}から見ると")
            文.append(f"　{c['見方']}")
            文.append('')

        # 太字の印は使わない。
        # ここは文字のまま画面に出るので、印がそのまま見えてしまう。
        文.append(f'この{数の言い方}は、食い違うことがあります。')
        文.append('食い違うところが、いちばん考えるべきところです。')
        文.append('どれか一つが正しい、という話ではありません。')
        文.append('')
        文.append('材料があれば、もっと踏み込めます。')
        文.append('「在庫を見せて」「値段を考えて」と言えば、実際に調べます。')

        return {
            'ok': True,
            'certainty': 'confirmed',
            'answer': '\n'.join(文),
            'sources': ['いくつかの見方から'],
            '係': [c['名前'] for c in 係一覧],
            '働かせ方': '相談して',
        }

    def _名前を呼ばれただけか(self, text):
        """
        名前を呼ばれただけかどうか。

        呼ばれただけなら、返す言葉を返す。
        用件が付いているなら None を返して、いつもの流れに任せる。
        """
        t = (text or '').strip()

        # 呼び名を読む。決めていなければ既定の名前。
        #
        # 以前は「data/声の設定.json」（キー: 呼び名）を見ていたが、
        # そのファイルは存在せず、常に既定の名前に落ちていた。
        # 画面・待ち受けが実際に使っているのは「data/呼び名.json」
        # （キー: 名）なので、そちらに合わせた。
        呼び名 = 'アレラム'
        try:
            with open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                   '..', 'data', '呼び名.json'), encoding='utf-8') as f:
                呼び名 = (json.load(f).get('名') or 呼び名).strip()
        except (OSError, ValueError):
            pass

        # 名前と、そのまわりに付く程度の言葉だけなら「呼ばれただけ」
        # 「アレン」は前の呼び名。呼び方を変えても、しばらくは
        # 呼ばれても気づけるよう、両方を認める。
        呼び名たち = {呼び名, 'アレラム', 'あれらむ', 'ARELM', 'ARELM', 'アレラムさん',
                  'アレン', 'あれん', 'アレンさん'}
        残り = t
        for 名 in 呼び名たち:
            残り = 残り.replace(名, '')
        残り = re.sub(r'[、。 　！!？?ー…・]', '', 残り)

        if not any(名 in t for 名 in 呼び名たち):
            return None

        # 用件が付いているなら、そちらを優先する
        if len(残り) > 2:
            return None

        # やることの数を見て、あれば添える。
        # 「はい」だけで終わると、こちらから何も差し出していない。
        添え = ''
        try:
            道 = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                              '..', 'data', 'やること.json')
            if os.path.exists(道):
                with open(道, encoding='utf-8') as f:
                    やること = json.load(f)
                残り数 = len([x for x in やること if not x.get('done')])
                if 残り数:
                    添え = f'今日のやることが {残り数}件 あります。'
        except (OSError, ValueError):
            添え = ''

        return (
            'はい、聞いています。\n\n'
            + (添え + '\n\n' if 添え else '')
            + 'ご用をどうぞ。'
            '「今日の状況」「在庫を見せて」「何ができる」などで動きます。'
        )

    @staticmethod
    def _項目に合わない訳(鍵, 答え):
        """
        受け取った答えが、その項目の形に合っているか。

        合っていなければ、その訳を返す。
        合っていれば None を返す。

        ここが無かったため、値段の欄に文章がそのまま入り、
        おかしな中身のまま登録されようとしていた。
        受け取る前に断るほうが、後から直すより軽い。
        """
        if not 答え:
            return 'すみません、聞き取れませんでした。'

        if 鍵 in ChatEngine.数で答える項目:
            # 「3500円」「3,500」なども受け取る
            数 = re.sub(r'[,、円\s]', '', 答え)
            if not re.fullmatch(r'\d+(\.\d+)?', 数):
                return f'「{答え[:20]}」は数として受け取れませんでした。'

        # 名前の欄が長すぎるのは、たいてい文章が紛れ込んでいる
        if 鍵 in ('name', 'title', 'item') and len(答え) > 60:
            return '長すぎるようです。名前だけを教えてください。'

        return None

    def _別の話か(self, text):
        """
        聞き返しへの答えではなく、別の用件かを見る。

        「？」で終わるものは、答えではなく質問とみなす。
        答えるつもりなら、ふつう疑問符は付けないため。
        """
        t = (text or '').strip()
        if not t:
            return False

        低 = t.lower()
        if any(w in 低 for w in self.別の話の合図):
            return True

        # 問いかけの形は、答えではない
        if t.endswith(('？', '?')):
            return True

        # はっきり別の頼み方をしているものは、答えではない。
        #
        # 「さっきの商品を教えて」を値段として受け取り、
        # そのまま登録しようとしていた。
        # 聞き返しの最中でも、別の用件だと分かるものは、
        # そちらへ移るのが正しい。
        if any(w in t for w in ('教えて', '見せて', '出して', '調べて',
                                'どうなって', '何がある', 'ある？', 'ありますか')):
            return True

        # 指示語で前を指しているのも、答えではなく話題の切り替え
        if t.startswith(('さっき', 'その前', 'それより', 'やっぱり', '前の')):
            return True

        return False

    def _能力を聞かれているか(self, text):
        low = (text or '').lower()
        return any(w in low for w in self.能力を聞く言い方)

    def _作業を始める(self, 作業, text, 会話体, context):
        """
        作業として受け取り、足りない情報があれば聞き返す。

        いきなり実行せず聞き返すのは、
        推測で動いて間違ったものを作るほうが、
        一手間かけるより害が大きいため。
        """
        埋まったもの = self._言葉から拾う(作業, text)
        足りないもの = [(k, ask) for (k, ask) in 作業.slots if not 埋まったもの.get(k)]

        会話体.最後の話題 = 作業.label

        if 足りないもの:
            鍵, 聞き方 = 足りないもの[0]
            会話体.待っていること = {
                'skill': 作業.name,
                'slots': 埋まったもの,
                '次に聞くこと': (鍵, 聞き方),
            }
            return {
                'ok': True,
                'certainty': 'confirmed',
                'answer': f'{作業.label}ですね。\n\n{聞き方}？',
                'sources': ['できることの一覧'],
                'skill': 作業.name,
                'waiting': 鍵,
            }

        return self._作業を実行する(作業, 埋まったもの, 会話体, context)

    def _続きを受け取る(self, text, 会話体, context):
        """待っていた答えを受け取り、揃えば実行、足りなければまた聞く。"""
        待ち = 会話体.待っていること
        作業 = skills.SKILL_BY_NAME.get(待ち['skill'])
        if not 作業:
            会話体.待っていること = None
            return None

        # やめると言われたら、素直に引き下がる
        if conversation.否定か(text):
            会話体.待っていること = None
            return {
                'ok': True, 'certainty': 'confirmed',
                'answer': f'{作業.label}はやめておきます。', 'sources': [],
            }

        # --- 別の話に切り替えられるようにする ---
        #
        # 聞き返している間、何を言っても答えとして受け取っていた。
        # そのため「何ができるの」と聞いても、
        # それが文章の種類として登録されてしまっていた。
        #
        # 質問や、別の作業の指示だと分かるものは、
        # 聞き返しをいったん止めて、そちらに答える。
        if self._別の話か(text):
            # 元の作業を捨てない。脇に置いて、あとで戻れるようにする。
            #
            # ここで捨てていたため、
            # 「商品名 → 種類」まで進んでいたのに、
            # 別のことを一言聞いただけで最初からになっていた。
            # せっかく答えたことが消えるのは、いちばん腹が立つ壊れ方。
            会話体.脇に置いた = 待ち

            # いま置いたばかり、という印を付ける。
            #
            # これが無いと、脇に置いた直後の同じ発言で
            # 「別の作業が始まった」と判断して、すぐ手放していた。
            # 置いた瞬間に捨てるのでは、置いた意味がない。
            会話体.脇は今置いた = True
            会話体.待っていること = None
            return None

        鍵, 聞き方 = 待ち['次に聞くこと']
        答え = text.strip()

        # 項目の形に合っているかを見る。
        #
        # 何でも受け取っていたので、
        # 「さっきの商品を教えて」が値段として入り、
        # そのまま登録されかけた。
        # 値段なら数、数量なら数——形が違えば、もう一度聞く。
        合わない = self._項目に合わない訳(鍵, 答え)
        if 合わない:
            会話体.待っていること = 待ち
            return {
                'ok': True, 'certainty': 'confirmed',
                'answer': f'{合わない}\n{聞き方}？',
                'sources': [], 'skill': 作業.name, 'waiting': 鍵,
            }

        待ち['slots'][鍵] = 答え

        残り = [(k, ask) for (k, ask) in 作業.slots if not 待ち['slots'].get(k)]
        if 残り:
            k, ask = 残り[0]
            待ち['次に聞くこと'] = (k, ask)
            会話体.待っていること = 待ち
            return {
                'ok': True, 'certainty': 'confirmed',
                'answer': f'{ask}？', 'sources': [],
                'skill': 作業.name, 'waiting': k,
            }

        会話体.待っていること = None
        return self._作業を実行する(作業, 待ち['slots'], 会話体, context)

    # 段取りを進めてよい、という返事
    進めてよい = ['実行', 'やって', 'お願い', 'はい', 'うん', 'そう', 'いいよ',
                'ok', 'OK', 'オッケー', '進めて', 'どうぞ', 'よろしく', 'それで']

    # 段取りをやめる、という返事
    やめる返事 = ['やめ', 'いい', 'いらない', 'キャンセル', '中止', 'ちがう',
                '違う', 'いや', 'しない', '結構']

    # 元の作業へ戻る、という返事
    戻る返事 = ['戻', 'つづき', '続き', 'さっきの続き', '再開', 'そのまま続け']

    def _脇に置いたものへ戻るか(self, text, 会話体):
        """
        脇に置いた作業へ戻るかを見る。

        「戻って」「続き」と言われたら、途中の中身のまま再開する。
        そうでなければ None を返し、ふつうの流れに任せる。

        置いたままにしておくと、いつまでも残って
        関係ない返事を吸い込んでしまうので、
        別の作業が始まったら手放す。
        """
        低 = text.lower().strip()

        if any(w in 低 for w in self.戻る返事):
            待ち = 会話体.脇に置いた
            会話体.脇に置いた = None
            会話体.待っていること = 待ち

            作業 = skills.SKILL_BY_NAME.get(待ち['skill'])
            鍵, 聞き方 = 待ち['次に聞くこと']

            すでに = [f'{k}: {v}' for k, v in 待ち['slots'].items() if v]
            文 = [f'{作業.label if 作業 else ""}の続きですね。']
            if すでに:
                文.append('ここまで伺っています: ' + '、'.join(すでに))
            文.append(f'{聞き方}？')

            return {
                'ok': True, 'certainty': 'confirmed',
                'answer': '\n'.join(文), 'sources': [],
                'skill': 待ち['skill'], 'waiting': 鍵,
            }

        # 別の作業が始まったら、脇に置いたものは手放す。
        # いつまでも持っていると、関係ない返事を吸い込む。
        作業, 確信 = skills.find_skill(text)
        if 作業 and 確信 >= 0.6:
            会話体.脇に置いた = None

        return None

    def _段取りの実行を受け取る(self, text, 会話体):
        """
        見せた段取りへの返事を受け取る。

        「実行して」なら進める。「やめて」ならやめる。
        どちらでもなければ、この段取りの話ではないものとして扱い、
        None を返してふつうの流れに戻す。

        判断がつかないのに進めてしまうと、
        頼んでいない作業がまとめて動くことになるため、
        迷ったときは進めない側に倒す。
        """
        低 = text.lower().strip()

        # 困っている言い方を、やめる合図と間違えない。
        #
        # 「どうすればいいか分からない」に「やめておきます」と答えていた。
        # 「しない」が「分からない」に当たっていたため。
        #
        # 助けを求めている人を突き放すのは、いちばんしてはいけないこと。
        # 困っているなら、やめるのではなく、手を貸す。
        if any(w in 低 for w in ['分からない', 'わからない', '分かりません',
                                 'どうすれば', 'どうしたら', '教えて', '困って',
                                 '助けて', 'どうすべき']):
            return self._困っているときの答え(text)

        # やめる方を先に見る。
        # 「いいよ」と「もういい」は逆の意味なのに、字が重なる。
        # 進める側を先に見ていたら、やめてほしいときに動き出していた。
        if any(w in 低 for w in self.やめる返事) and not any(
                w in 低 for w in ['いいよ', 'いいですよ', 'それでいい']):
            会話体.待っている段取り = None
            return self._ok('分かりました。やめておきます。'
                            '必要になったら、また言ってください。', [])

        if any(w in 低 for w in self.進めてよい):
            段 = 会話体.待っている段取り
            会話体.待っている段取り = None

            文 = [f'「{段["label"]}」を始めます。', '',
                  '一手ずつ進めて、それぞれ結果をお見せします。',
                  '途中で止まったら、そこで止めて理由を言います。'
                  '残りを飛ばして「終わりました」とは言いません。']

            return {
                'ok': True,
                'certainty': 'confirmed',
                'answer': '\n'.join(文),
                'sources': ['あなたの指示'],
                'plan': 段,
                'run': True,
            }

        return None

    def _作業を実行する(self, 作業, 材料, 会話体, context):
        """
        揃った材料で作業を行う。

        ここでは「何を、どの画面で行うか」を返すだけにしてある。
        実際にデータを書き換えるのは画面側の役目で、
        AIが勝手に書き換えないほうが、取り消しやすく安全なため。
        """
        # 見せることが答えになる作業は、「実行します」とは言わない。
        # 聞かれたことに答えているのであって、
        # 何かを行うと宣言しているわけではないため。
        頭 = f'{作業.label}。' if getattr(作業, '答えになる', False) \
            else f'{作業.label}を実行します。'
        文 = [頭, '']
        for 鍵, 聞き方 in 作業.slots:
            値 = 材料.get(鍵)
            if 値:
                名 = 聞き方.rstrip('はか？ ')
                文.append(f'・{名}: {値}')
        if len(文) > 2:
            文.append('')
        if getattr(作業, '答えになる', False):
            文.append('下に出します。')
        else:
            文.append(f'この内容で「{作業.label}」を行います。')

        会話体.最後の話題 = 材料.get('name') or 材料.get('title') or 作業.label

        return {
            'ok': True,
            'certainty': 'confirmed',
            'answer': '\n'.join(文),
            'sources': ['あなたの指示'],
            'skill': 作業.name,
            'action': 作業.action,
            'page': 作業.page,
            'params': 材料,
        }

    # 切り出した後に残りやすい、意味を持たない言い方
    #
    # 「商品を登録したい」から「商品」の後ろを取ると
    # 「を登録したい」が残る。これを商品名として受け取ってしまい、
    # おかしな中身で実行しかけたため、はじく決まりを設けた。
    意味のない残り = [
        'したい', 'して', 'する', 'したいです', 'ください', 'ほしい', 'たい',
        'お願い', 'よろしく', 'です', 'ます', 'を', 'が', 'は', 'の',
    ]

    @staticmethod
    def _言葉から拾う(作業, text):
        """
        言われた文から、作業に要る情報を拾えるだけ拾う。

        「タスク サンプル発注」なら「サンプル発注」を拾う。
        「商品を登録したい」からは何も拾わない。
        「を登録したい」は名前ではないため。

        拾えなければ空のままにする。
        無理に切り出すと、見当違いのものが入って
        そのまま実行されてしまうため。
        """
        if not 作業.slots:
            return {}

        # 言われたこと全体が中身になる作業がある。
        #
        # 「黒い千鳥格子の柄を作って」の場合、
        # 「柄を作」の後ろを切り出すと「って」しか残らない。
        # 色も柄の種類も、切り落とした前半に入っている。
        #
        # こういう作業では、頼み言葉だけを外して、
        # 残り全部を渡すのが正しい。
        if getattr(作業, '全文を使う', False):
            残り = text
            for w in ['を作って', 'を作成して', 'をつくって', '作って', 'つくって',
                      'を書いて', '書いて', 'してください', 'して', 'お願い']:
                残り = 残り.replace(w, ' ')
            残り = ' '.join(残り.split()).strip(' 　:：、。,')
            return {作業.slots[0][0]: 残り} if len(残り) >= 2 else {}

        for w in 作業.words:
            if w not in text:
                continue

            後ろ = text.split(w, 1)[1]

            # 先頭の助詞・記号を取り除く
            後ろ = 後ろ.lstrip(' 　:：、。,')
            while 後ろ and 後ろ[0] in 'をがはにのへとで':
                後ろ = 後ろ[1:].lstrip(' 　')

            後ろ = 後ろ.strip(' 　:：、。,')

            if not ChatEngine._中身のある言葉か(後ろ, 作業):
                return {}

            return {作業.slots[0][0]: 後ろ}

        return {}

    @staticmethod
    def _中身のある言葉か(語, 作業):
        """
        切り出したものが、本当に中身のある言葉かを見る。

        中身が無いとみなすもの:
          - 短すぎる
          - 「したい」「してください」のような、指示の言い回しだけ
          - その作業を指す言葉そのもの（「商品」を商品名とはしない）
        """
        if not 語 or len(語) < 2:
            return False

        if 語 in ChatEngine.意味のない残り:
            return False

        # 「〜したい」「〜してください」だけで終わっているもの
        for 尾 in ChatEngine.意味のない残り:
            if 語 == 尾 or 語.rstrip('。！!') == 尾:
                return False

        # 「〜したい」「〜してください」で終わるものは、
        # 頼みごとの言い回しであって、名前でも中身でもない。
        # 漢字が混じっていても同じなので、文字種では判断しない。
        頼みの語尾 = (
            'したい', 'して', 'してほしい', 'してください', 'ください',
            'ほしい', 'お願い', 'おねがい', 'よろしく', 'たいです',
            'できる', 'できますか', 'ますか', 'ですか',
        )
        if any(語.rstrip('。！!？?').endswith(尾) for 尾 in 頼みの語尾):
            return False

        # その作業を指す言葉そのもの
        if 語 in 作業.words:
            return False

        return True

