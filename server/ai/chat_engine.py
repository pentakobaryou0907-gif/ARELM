# 質問の種類を見分ける手がかり
INTENT_PATTERNS = [
    ('inventory', ['在庫', 'ざいこ', '残り', '個数', '数量', 'いくつ', '足り']),
    ('price', ['価格', '値段', 'いくら', '原価', '粗利', '利益', '円']),
    ('product', ['商品', 'アイテム', '服', 'デザイン', '素材', 'サイズ', 'カラー']),
    ('task', ['タスク', 'やること', '予定', '期限', '締切', 'いつまで']),
    ('schedule', ['今日', '明日', '今週', 'スケジュール', 'カレンダー']),
    ('knowledge', ['知識', '前に', '以前', '教えて', 'どうだった', '覚えて']),
    ('howto', ['どうやって', 'やり方', '使い方', 'できる', '方法', 'どこ']),
    ('brand', ['ブランド', '競合', '他社']),
    # 「どっちがいい？」「次は何をすべき？」に答えるための種類
    ('advise', ['どっち', 'どちら', 'おすすめ', 'お勧め', '選べ', '選ぶ', '良い', 'いい？', 'べき']),
    ('next', ['次は', '次に', 'これから', '何をすれば', '何から', '優先']),
]

# 質問かどうかの手がかり
QUESTION_MARKS = re.compile(r'[?？]|ですか|でしょうか|かな|教えて|知りたい|どう|なに|何|いつ|どこ|だれ|誰|いくら|いくつ')


# このツールが持っていない情報。
# 「明日の天気は？」の「明日」に反応して予定を答えてしまう、
# といった的外れな回答を防ぐために、先に弾く。
OUT_OF_SCOPE = [
    '天気', '気温', '雨', '晴れ', '台風', '気候',
    'ニュース', '株価', '為替', 'レート', '選挙',
    '電車', '運行', '渋滞', '交通',
    'レシピ', '料理', '献立',
    '翻訳', '英語で', '意味は',
]

# 予定として答えてよいと判断するための語。
# 日付の語だけでは予定の質問とみなさない。
SCHEDULE_CONFIRM = ['予定', 'タスク', 'やること', 'スケジュール', '締切', '期限', '仕事']


def find_out_of_scope(text):
    """答えられない話題が含まれていれば、その語を返す。"""
    for w in OUT_OF_SCOPE:
        if w in text:
            return w
    return None


def detect_intent(text):
    """何について聞かれているかを判定する。分からなければ None。"""
    scores = {}
    for intent, keywords in INTENT_PATTERNS:
        hit = sum(1 for k in keywords if k in text)
        if hit:
            scores[intent] = hit
    if not scores:
        return None

    best = max(scores, key=scores.get)

    # 日付の語だけで予定と判断しない。
    # 「明日の天気」を「明日の予定」と取り違えないため。
    if best == 'schedule' and not any(w in text for w in SCHEDULE_CONFIRM):
        scores.pop('schedule')
        if not scores:
            return None
        best = max(scores, key=scores.get)

    return best


# 問いの形をした言い方。
