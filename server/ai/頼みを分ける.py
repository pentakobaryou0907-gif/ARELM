# -*- coding: utf-8 -*-
"""
頼みを分ける ― 一文に入った、いくつもの頼みを、順番のある手順にする

なぜこれが要るのか:
    「在庫を確認して、少ないものをやることに入れて」と言っても、
    在庫の確認だけをして止まっていた。
    「新しいTシャツを登録して、説明文も作って」と言っても、
    説明文のところで「何の文章ですか」と聞き返して止まっていた。

    決まった5つの段取り（新商品・発注・一日の始め…）と、教わった手順だけが、
    複数の手順として動く作りで、ふつうに言った複数の頼みは、一手しか動かなかった。
    これでは、「頼んだら全部代わりにやる」とは言えない。

ここでやること:
    1. 一文を、頼みごとに分ける（「、」「そして」「〜して」の切れ目で）
    2. それぞれを、すでにある技能（skills.py）に当てる
       → 当たらなかった部分は、勝手に作らず、そのまま「分からなかった」と返す
    3. 前の手で出てきた名前（商品名など）を、あとの手に引き継ぐ
    4. 順番のある手順にして返す（動かすのは、画面側の段取りの仕組み）

守っていること:
    ・並べられるのは、skills.py にある、実際に動く作業だけ。
    ・分からない部分を、推測で埋めない。足りない中身は、その手順のところで聞く。
    ・技能の数が2つ未満なら、何もしない（これまでどおり、一手として扱う）。
    ・質問には反応しない（「どうやって〜するの？」で動き出さない）。

外部へは一切問い合わせない。すべてこの端末の中で完結する。
"""

import re

import skills

# 頼みの切れ目になる、つなぎの言葉
# 「次にやること」「あとで」のように、言葉の一部になるもの（次に・まず・あと）は、切れ目にしない
_つなぎ = re.compile(r'(そして|それから|その後|そのあと|あとは|続けて|さらに|ついでに|最後に)')

# 「〜て」のあとに、別の頼みが始まるときだけ切る。
# 「見てください」「入れておいて」「作ってほしい」のように、
# 同じ頼みの続きになる言い方の前では切らない。
_て続き = ('ください', 'くれ', 'ほしい', 'おいて', 'おく', 'あげ', 'みて', 'みる', 'しまっ',
          'いる', 'います', 'いて', 'いい', 'も', 'は', 'ね', 'よ', 'こと', 'ほしい', 'みよう')


def 切る(text):
    """一文を、頼みごとの並びに分ける。"""
    t = (text or '').strip().rstrip('。 　')
    if not t:
        return []

    # つなぎの言葉と句読点で切る
    t = _つなぎ.sub('、', t)
    かけら = [x for x in re.split(r'[、。,，\n]+', t) if x.strip()]

    # 「在庫を見て値段を考えて」のように、読点が無い並びも、「て」の切れ目で切る
    結果 = []
    for x in かけら:
        始め = 0
        for m in re.finditer('て', x):
            位置 = m.end()
            のこり = x[位置:]
            if not のこり:
                continue
            if any(のこり.startswith(w) for w in _て続き):
                continue
            # 切れ目の直前が動詞の「〜て」でない（名前の途中の「て」）ときは切らない
            直前 = x[max(0, m.start() - 1):m.start()]
            if not 直前 or not re.match(r'[ぁ-んァ-ヴ一-龥]', 直前):
                continue
            結果.append(x[始め:位置])
            始め = 位置
        結果.append(x[始め:])
    return [x.strip(' 　、。') for x in 結果 if x.strip(' 　、。')]


# まとめての自動実行には入れない作業（学習した内容を取り除く操作）
_自動に入れない = {'forget'}

_文章の型 = [
    (('説明文', '商品説明', '説明'), '商品説明'),
    (('投稿', 'SNS', 'ＳＮＳ', 'キャプション', 'インスタ'), 'SNS'),
    (('発注メール', 'メール'), '発注メール'),
    (('注記', 'テックパック'), 'テックパック注記'),
]


def _文章の型を全部(文):
    """文の中に出てくる文章の種類を、出てくる順に全部返す。"""
    見つけた = []
    for 語たち, 名 in _文章の型:
        位置 = min((文.find(w) for w in 語たち if w in 文), default=-1)
        if 位置 >= 0:
            見つけた.append((位置, 名))
    return [名 for _, 名 in sorted(見つけた)]


_素材 = ['コットン', '綿', '麻', 'リネン', 'ウール', 'ポリエステル', 'ナイロン', 'デニム', 'スウェット', 'レザー', '革', 'シルク', '絹', 'カシミヤ', 'フリース']
_色 = ['黒', '白', 'オフホワイト', '赤', '青', '紺', 'ネイビー', '緑', 'グリーン', '黄', 'ベージュ', 'グレー', '灰色', 'ブラウン', '茶', 'ピンク', '紫', 'カーキ', 'オレンジ']


def _属性を拾う(文):
    """文の中に書いてある、素材・色・値段を拾う。書いていないものは、拾わない（作らない）。"""
    属性 = {}
    素材 = [w for w in _素材 if w in 文]
    if 素材:
        m = re.search(r'(' + '|'.join(素材) + r')\s*(\d{1,3}\s*[%％])?', 文)
        属性['material'] = (m.group(0).replace(' ', '') if m else 素材[0])
    色 = [w for w in _色 if w in 文]
    if 色:
        属性['color'] = 色[0]
    m = re.search(r'(\d[\d,]{2,6})\s*円', 文)
    if m:
        属性['price'] = m.group(1).replace(',', '')
    return 属性


def _頼みの言葉を除く(文):
    """「〜を登録して」から、頼みの言い方を取り除く。"""
    x = 文
    x = re.sub(r'(をお願い|お願い|をやって|やって|をして|して|してください|しといて|といて|しておいて|おいて|てください|て)$', '', x)
    return x.strip(' 　、。')


def _材料を拾う(技, 文, 引き継ぎ, 拾う):
    """その手に渡す中身。拾えないものは、空のまま（あとで聞く）。"""
    材料 = dict(拾う(技, 文) or {})
    名前 = 引き継ぎ.get('品')
    引き継ぎ.setdefault('属性', {}).update(_属性を拾う(文))

    if 技.name == 'add_product':
        # 「〜を」の前の言葉を商品名にする（「綿100%の黒いTシャツを4500円で登録」→「黒いTシャツ」）。
        # 素材の言い回し（綿100%の）は、商品名ではなく素材として別に拾うので、取り除く。
        m = re.match(r'(?:新しい|新作の|新商品の)?(.+?)を', 文)
        if m and re.search(r'(登録|追加)', 文):
            候補 = re.sub(r'^(?:' + '|'.join(_素材) + r')\s*(?:\d{1,3}\s*[%％])?\s*の', '', m.group(1)).strip()
            if 候補 and 候補 not in ('商品', '新商品', '新しい商品'):
                材料['name'] = 候補
        if 材料.get('name'):
            引き継ぎ['品'] = 材料['name']
        if 引き継ぎ.get('属性', {}).get('price'):
            材料['price'] = 引き継ぎ['属性']['price']

    elif 技.name == 'add_task':
        m = re.search(r'(.+?)(?:を|の)?(?:やること|タスク|予定|ToDo|todo)(?:に|として)', 文)
        title = (m.group(1) if m else '').strip()
        if '少ない' in 文 or '足りない' in 文:
            title = '在庫が少ないものの補充'
        elif not title or title in ('それ', 'これ', 'その', 'この'):
            話題 = 引き継ぎ.get('前の話題') or 名前
            title = (話題 + 'の対応') if 話題 else ''
        if title:
            材料['title'] = title
        else:
            材料.pop('title', None)    # 頼みの言葉（「入れて」など）を題にしない。あとで聞く

    elif 技.name == 'add_memo':
        本文 = _頼みの言葉を除く(re.sub(r'(メモ|記録|書いておいて|残して|を)', ' ', 文))
        if 本文:
            材料['body'] = 本文.strip()

    elif 技.name == 'write_text':
        型 = None
        for 語たち, 名 in _文章の型:
            if any(w in 文 for w in 語たち):
                型 = 名
                break
        if 型:
            材料['template'] = 型
        if 名前:
            材料['name'] = 名前
        # 前の手までに出てきた、素材・色・値段を渡す（書いていないものは入れない）
        for k, v in 引き継ぎ.get('属性', {}).items():
            材料.setdefault(k, v)

    elif 技.name == 'check_duplicate':
        if not 材料.get('text') and 名前:
            材料['text'] = 名前

    elif 技.name in ('make_pattern', 'add_inbox', 'add_production'):
        材料.setdefault('text' if 技.name == 'make_pattern' else 技.slots[0][0], 文)

    return {k: v for k, v in 材料.items() if v not in (None, '')}


def _技を決める(文):
    """
    一つの頼みが、どの技能かを決める。
    「Tシャツを登録して」は「登録」が、やること追加と商品登録の両方に当たって同点になる。
    やることを示す言葉（タスク・やること・予定）が無ければ、商品登録とみなす。
    """
    順位 = skills.ranked(文)
    if not 順位:
        return None, 0.0
    技, 点 = 順位[0]
    確か = min(点 / 2.0, 1.0)
    次点 = 順位[1][1] if len(順位) > 1 else 0.0

    名前たち = {順位[0][0].name, 順位[1][0].name} if len(順位) > 1 else set()
    if (名前たち == {'add_task', 'add_product'} and abs(点 - 次点) < 1e-9
            and not re.search(r'(タスク|やること|予定|todo|ToDo)', 文)):
        技 = skills.SKILL_BY_NAME['add_product']
        return 技, 0.6
    if 次点 >= 点 * 0.8:
        確か *= 0.5
    return 技, 確か


def 手順に直す(text, 拾う, 確かさの下限=0.5):
    """
    頼みを手順に直す。

    @param 拾う  (技, 文) → 中身 を返す関数（chat_engine の _言葉から拾う を渡す）
    @return None（一手として扱うべき）または
            {'steps': [...], '分からなかった': [...], '文たち': [...]}
    """
    文たち = 切る(text)
    if not 文たち:
        return None

    手順 = []
    分からなかった = []
    引き継ぎ = {}
    for 文 in 文たち:
        技, 確か = _技を決める(文)
        if not 技 or 確か < 確かさの下限:
            分からなかった.append(文)
            continue
        # 取り消しにくい作業は、まとめて自動では行わない（単独で頼んでもらう）
        if 技.name in _自動に入れない:
            分からなかった.append(文 + '（「忘れる」は、単独で頼んでください）')
            continue
        材料 = _材料を拾う(技, 文, 引き継ぎ, 拾う)
        m = re.match(r'(?:新しい|新作の)?([^\sをは]{1,12}?)(?:を|は)', 文)
        if m and 技.name not in ('add_task',):
            引き継ぎ['前の話題'] = m.group(1)

        # 「説明文とSNSの投稿文を作って」は、文章の頼みが二つ入っている。種類ごとに一手にする。
        if 技.name == 'write_text':
            型たち = _文章の型を全部(文)
            if len(型たち) >= 2:
                for 型 in 型たち:
                    手順.append({
                        'action': 技.action,
                        'why': f'{技.label}（{型}）',
                        'params': dict(材料, template=型),
                        'confirm': False,
                    })
                continue

        手順.append({
            'action': 技.action,
            'why': f'{技.label}（「{文}」）',
            'params': 材料,
            'confirm': False,
        })

    # 手が2つ未満なら、これまでどおり一手として扱う（誤って分けないため）
    if len(手順) < 2:
        return None
    return {'steps': 手順, '分からなかった': 分からなかった, '文たち': 文たち}
