# 会社らしくない、無料のメールで来ているか
無料のメール = re.compile(
    r'[\w.+-]+@(gmail|yahoo|outlook|hotmail|qq|163|foxmail|proton(mail)?)\.[a-z.]+',
    re.I)

# 書いてある文字と、実際の行き先が違うリンク
見た目と違うリンク = re.compile(
    r'\[([^\]]+)\]\((https?://[^)]+)\)|<a[^>]+href=["\']([^"\']+)["\'][^>]*>([^<]+)</a>',
    re.I)


def _見た目と行き先がずれているか(文):
    """
    リンクの見た目と、実際の行き先が食い違っていないか。

    「abc-factory.com」と書いてあるのに、
    まったく別のところへ飛ぶ形がある。
    """
    ずれ = []
    for m in 見た目と違うリンク.finditer(文):
        見た目 = (m.group(1) or m.group(4) or '').strip()
        行き先 = (m.group(2) or m.group(3) or '').strip()
        if not 見た目 or not 行き先:
            continue
        # 見た目がURLらしいときだけ比べる。
        # 「こちら」のような言葉なら、比べようがない。
        if not re.search(r'[a-z0-9-]+\.[a-z]{2,}', 見た目, re.I):
            continue
        見た目の元 = re.sub(r'^https?://', '', 見た目).split('/')[0].lower()
        行き先の元 = re.sub(r'^https?://', '', 行き先).split('/')[0].lower()
        if 見た目の元 and 行き先の元 and 見た目の元 not in 行き先の元:
            ずれ.append((見た目, 行き先))
    return ずれ


def 見る(文, 相手=''):
    """
    文面を読んで、引っかかる点を返す。

    @param 文    貼り付けられたメールや連絡の中身
    @param 相手  分かっていれば、取引先の名前
    @return dict
    """
    文 = (文 or '').strip()
    if not 文:
        return {
            'ok': False,
            '訳': '見る文面がありません。メールの中身をそのまま貼り付けてください。',
        }

    低 = 文.lower()
    当たり = []

    for x in 見どころ:
        見つけた = [w for w in x.語 if w.lower() in 低]
        if 見つけた:
            当たり.append({
                '名': x.名,
                '重さ': x.重さ,
                '訳': x.訳,
                '確かめ方': x.確かめ方,
                '見つけた言葉': 見つけた[:3],
            })

    # --- 会社らしくないメールから来ていないか ---
    無料 = 無料のメール.findall(文)
    if 無料:
        当たり.append({
            '名': '会社のものでないメールアドレスが使われている',
            '重さ': 2,
            '訳': '取引先の会社なのに、無料のメールから来ています。'
                  '会社のドメインに似せられないので、無料のものを使っていることがあります。',
            '確かめ方': 'これまで届いていたアドレスと、一文字ずつ見比べてください。'
                       '似せたドメイン（rn と m の入れ替えなど）にも気をつけてください。',
            '見つけた言葉': [m[0] if isinstance(m, tuple) else m for m in 無料][:3],
        })

    # --- リンクの見た目と行き先がずれていないか ---
    ずれ = _見た目と行き先がずれているか(文)
    if ずれ:
        当たり.append({
            '名': 'リンクの見た目と、実際の行き先が違う',
            '重さ': 3,
            '訳': '書かれている文字と、飛ぶ先が食い違っています。'
                  '本物そっくりの画面へ連れて行かれることがあります。',
            '確かめ方': 'そのリンクは押さないでください。'
                       'いつも使っている経路から、自分でたどってください。',
            '見つけた言葉': [f'{見た目} → {行き先}' for 見た目, 行き先 in ずれ][:3],
        })

    # --- まとめ ---
    重さの合計 = sum(x['重さ'] for x in 当たり)
    最も重い = max([x['重さ'] for x in 当たり], default=0)

    if 最も重い >= 3:
        段階 = '手を止めてください'
    elif 重さの合計 >= 4:
        段階 = '気をつけてください'
    elif 当たり:
        段階 = '念のため確かめてください'
    else:
        段階 = '引っかかる点はありませんでした'

    当たり.sort(key=lambda x: -x['重さ'])

    return {
        'ok': True,
        '段階': 段階,
        '当たり': 当たり,
        '相手': 相手,
        '文の長さ': len(文),
    }


def 文にする(結果):
    """
    見た結果を、そのまま読める文にする。

    最後の一文が、いちばん大事です。
    「見つからなかった＝安全」と受け取られたら、
    このやり方は害になります。
    """
    if not 結果.get('ok'):
        return 結果.get('訳', '見られませんでした')

    行 = [f'【{結果["段階"]}】', '']

    if not 結果['当たり']:
        行 += [
            'こちらの見方に当てはまる点は、見つかりませんでした。',
            '',
            'ただし、これは「安全だ」という意味ではありません。',
            'こちらが知っている手口に当てはまらなかった、というだけです。',
            'お金が動く話であれば、いつもの連絡先で一度確かめてください。',
        ]
        return '\n'.join(行)

    重さの印 = {3: '●', 2: '▲', 1: '・'}
    for x in 結果['当たり']:
        行.append(f'{重さの印.get(x["重さ"], "・")} {x["名"]}')
        行.append(f'　{x["訳"]}')
        行.append(f'　見つけた言葉: {"、".join(x["見つけた言葉"])}')
        行.append(f'　→ {x["確かめ方"]}')
        行.append('')

    行 += [
        '─────────────',
        'これは「詐欺だ」と決めつけるものではありません。',
        '引っかかる点を並べただけです。本物のこともあります。',
        '',
        'お金が動く話なら、次だけは守ってください。',
        '　・そのメールに書かれた連絡先は使わない',
        '　・前から知っている電話番号にかけて、担当者本人に口頭で確かめる',
        '　・確かめるまでは払わない',
        '',
        'この文面は外部へ送っていません。この端末の中だけで見ました。',
    ]
    return '\n'.join(行)
