def find(text):
    """
    雑談として受け取れるかを見る。

    仕事の話に雑談が混ざることもあるため、
    短い言葉のときだけ雑談とみなす。
    「ありがとう、ところで在庫は」を雑談で終わらせては困るから。

    @return 応答 または None
    """
    if not text:
        return None

    t = text.strip()

    # 長い文は、用件が入っているとみなして雑談にしない
    if len(t) > 25:
        return None

    low = t.lower()
    for r in 応答たち:
        for w in r.words:
            if w in low:
                return r
    return None


def reply(r, 状況=None):
    """
    返す言葉を組み立てる。

    毎回まったく同じだと機械らしくなるので、
    いくつかの言い方から選ぶ。
    ただし内容は変えない。言い回しだけを変える。
    """
    本文 = random.choice(r.replies)
    if r.follow:
        return f'{本文}\n\n{r.follow}'
    return 本文
