def _読む():
    try:
        with open(置き場, encoding='utf-8') as f:
            r = json.load(f)
        if isinstance(r, list) and r:
            return r
    except (OSError, ValueError):
        pass
    return list(はじめの係たち)


def _書く(一覧):
    場所 = os.path.dirname(os.path.abspath(置き場))
    os.makedirs(場所, exist_ok=True)
    with open(置き場, 'w', encoding='utf-8') as f:
        json.dump(一覧, f, ensure_ascii=False, indent=2)


def 一覧を出す():
    return _読む()


def 係を足す(名前, 得意, 呼ばれる言葉, 受け持つ作業, 見方):
    """
    新しい係を足す。

    <b>持っていない作業は割り当てない。</b>
    割り当てると、「やります」と言って何も起きないことになる。
    """
    import 覚えた作業
    使える = 覚えた作業.使える作業を集める()

    無い = [x for x in (受け持つ作業 or []) if x not in 使える]
    if 無い:
        return {
            'ok': False,
            '訳': f'この道具にない作業が混ざっています: {"、".join(無い)}。'
                  '動かない係を作ると、頼んでも何も起きません。',
        }

    if not 名前 or not (呼ばれる言葉 or []):
        return {'ok': False, '訳': '名前と、呼ばれる言葉が要ります'}

    一覧 = [x for x in _読む() if x['名前'] != 名前]
    一覧.append({
        '名前': 名前,
        '得意': 得意 or '',
        '呼ばれる言葉': 呼ばれる言葉,
        '受け持つ作業': 受け持つ作業 or [],
        '見方': 見方 or '',
        '足した': True,
    })
    _書く(一覧)
    return {'ok': True, '訳': f'「{名前}」を足しました。'
                             f'「{呼ばれる言葉[0]}」などで呼ばれると出てきます。'}


def 係を外す(名前):
    一覧 = _読む()
    残り = [x for x in 一覧 if x['名前'] != 名前]
    if len(残り) == len(一覧):
        return {'ok': False, '訳': f'「{名前}」は居ません'}
    _書く(残り)
    return {'ok': True, '訳': f'「{名前}」を外しました'}


