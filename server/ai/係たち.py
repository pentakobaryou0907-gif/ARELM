def 合う係を探す(text):
    """
    言われたことに、どの係が合うか。

    @return [(係, 近さ)] 近い順
    """
    t = (text or '').lower()
    出 = []

    for 係 in _読む():
        点 = 0
        当たった = []
        for 語 in 係.get('呼ばれる言葉', []):
            if 語.lower() in t:
                # 長い言葉ほど、たまたま当たる見込みが低い
                点 += 1 + len(語) * 0.1
                当たった.append(語)
        if 点 > 0:
            出.append((係, round(点, 2), 当たった))

    出.sort(key=lambda x: -x[1])
    return 出


def 働かせ方を決める(text, 合う係たち):
    """
    どう働かせるかを決める。

    決め方は単純にしてある。
    複雑にすると、なぜそうなったか説明できなくなる。
    """
    t = (text or '')

    # はっきり言われたなら、それに従う
    if any(w in t for w in ['相談', 'みんなで', 'それぞれ', '意見', 'どう思う', '見方']):
        return '相談して'
    if any(w in t for w in ['同時に', '並行', 'いっぺんに', 'まとめて']):
        return '同時に'
    if any(w in t for w in ['それから', 'そのあと', '続けて', '踏まえて']):
        return '順に'

    # 決めるのが難しそうな問い方なら、相談させる
    #
    # はじめ「合う係が2人以上いるとき」だけにしていたが、
    # 「この値段でいいか迷ってる」では、お金係しか当たらない。
    # 当たった係が一人でも、<b>迷っているなら見方は複数あったほうがよい</b>。
    # 迷いは、一つの見方では解けないから起きる。
    if any(w in t for w in ['べき', 'どちら', 'どっち', 'いいか', 'すべき',
                            '迷って', '悩んで', '判断']):
        return '相談して'

    # 別々の分野が二つ以上出てきたら、同時に
    if len(合う係たち) >= 2 and 合う係たち[0][1] - 合う係たち[1][1] < 0.6:
        return '同時に'

    return '一人で'


def 割り振る(text):
    """
    言われたことを、係に割り振る。

    @return {'働かせ方':…, '係たち':[…], '訳':…}
    """
    合う = 合う係を探す(text)
    やり方 = 働かせ方を決める(text, 合う)

    if not 合う:
        # どの言葉にも当たらなかった。
        #
        # だが「新作を出すべきか判断したい」のように、
        # <b>決めごとだと分かる言い方</b>のことがある。
        # そのときに「分かりません」で終わるのは、
        # いちばん助けが要る場面で黙るのと同じ。
        #
        # 決めごとなら、広く見方を出してもらう。
        if やり方 == '相談して':
            全部 = _読む()
            選ぶ = ['お金係', '分析係', '在庫係']
            選んだ = [(c, 0.0, ['（決めごとなので呼びました）'])
                    for 名 in 選ぶ for c in 全部 if c['名前'] == 名]
            if 選んだ:
                return {
                    '働かせ方': '相談して',
                    '係たち': [
                        {
                            '名前': c['名前'], '得意': c.get('得意', ''),
                            '見方': c.get('見方', ''),
                            '受け持つ作業': c.get('受け持つ作業', []),
                            '当たった言葉': 当, '近さ': 点,
                        }
                        for c, 点, 当 in 選んだ
                    ],
                    '訳': '決めごとのようなので、いくつかの見方を出します。',
                }

        return {
            '働かせ方': '一人で',
            '係たち': [],
            '訳': 'どの係の話か分かりませんでした。ふつうに答えます。',
        }

    if やり方 == '一人で':
        選んだ = [合う[0]]

    elif やり方 == '相談して':
        # 相談は、見方が複数あってこそ意味がある。
        #
        # 当たった係だけだと一人になることがあり、
        # それでは相談にならない。
        # <b>足りなければ、他の係にも見てもらう。</b>
        #
        # 誰でもいいわけではない。
        # 相談ごとに関わりの深い順に足す。
        選んだ = list(合う[:3])

        if len(選んだ) < 2:
            すでに = {c['名前'] for c, _, _ in 選んだ}
            # 決めごとには、この三つの見方がたいてい効く
            足す順 = ['お金係', '分析係', '在庫係', 'SNS係', '作り方係', '段取り係']
            for 名 in 足す順:
                if len(選んだ) >= 3:
                    break
                if 名 in すでに:
                    continue
                for 係 in _読む():
                    if 係['名前'] == 名:
                        選んだ.append((係, 0.0, ['（見方を足すために呼びました）']))
                        break
    else:
        選んだ = 合う[:3]

    return {
        '働かせ方': やり方,
        '係たち': [
            {
                '名前': c['名前'],
                '得意': c.get('得意', ''),
                '見方': c.get('見方', ''),
                '受け持つ作業': c.get('受け持つ作業', []),
                '当たった言葉': 当,
                '近さ': 点,
            }
            for c, 点, 当 in 選んだ
        ],
        '訳': 働かせ方たち.get(やり方, {}).get('説', ''),
    }
