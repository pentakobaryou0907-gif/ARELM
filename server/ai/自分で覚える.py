# -*- coding: utf-8 -*-
"""
自分で覚える ― 会話の中から、覚えるべきことを拾う

なぜこれが要るのか:

    いままでは、資料を取り込むか、あなたが教えるかだった。
    会話の中で「浅煎りが好き」と言われても、流れて消えていた。

    大事なことは、たいてい<b>ついでに言われる</b>。
    改まって「これを覚えて」とは言わない。
    だから、こちらが拾わなければ、貯まらない。

何を覚えるのか:

    ・<b>好み</b>（好き・嫌い・いつも・たいてい）
    ・<b>決めごと</b>（〜にする・〜でいく・やめる）
    ・<b>事実</b>（原価は◯円・納期は◯週間）
    ・<b>失敗と成功</b>（うまくいかなかった・よかった）

何を覚えないのか:

    ・<b>その場だけの話</b>（いま何時・今日の天気）
    ・<b>問いかけ</b>（〜は？ 〜って何？）
    ・<b>短すぎるもの</b>（はい・そうだね）

    覚えるほど良くなる、とは限らない。
    どうでもいいことが混ざると、大事なことが埋もれる。

正直に書いておきます:

    <b>拾い方は言葉の形で見ています。</b>
    意味を分かって判断しているわけではありません。
    だから、拾い損ねることも、余計なものを拾うこともあります。

    そのために、覚えたものは必ず見られるようにし、
    間違っていれば忘れさせられるようにしてあります。

外部へは一切問い合わせません。すべてこの端末の中で完結します。
"""

import re

# ------------------------------------------------------------------
# 覚える値打ちがあるかを見る
# ------------------------------------------------------------------

覚える手がかり = [
    # (見分ける形, 種類, どれくらい確か)
    (r'(好き|嫌い|苦手|気に入)', '好み', 0.8),
    (r'(いつも|たいてい|ふだん|毎回|基本的に)', '好み', 0.7),
    (r'(にする|でいく|に決めた|やめる|やめた)', '決めごと', 0.8),
    (r'(原価|値段|納期|在庫)[はが]?\s*\d', '事実', 0.9),
    (r'\d+\s*(円|枚|点|週間|日|か月|ヶ月)', '事実', 0.7),
    (r'(うまくいかな|失敗|だめだった|よくなかった)', '失敗', 0.85),
    (r'(うまくいった|よかった|成功|売れた)', '成功', 0.8),
    (r'(これから|今後|次から)', '決めごと', 0.7),
]

覚えないもの = [
    r'[?？]$',                    # 問いかけ
    r'^(はい|うん|そう|ええ|了解|わかった|ありがとう)',
    r'(何時|今日の天気|いま何)',   # その場だけの話
]


def 覚える値打ちがあるか(文):
    """
    この文を覚えるべきかを見る。

    @return {'覚えるか':bool, '種類':…, '確からしさ':…, '訳':…}
    """
    t = (文 or '').strip()

    if len(t) < 8:
        return {'覚えるか': False, '訳': '短すぎます'}
    if len(t) > 300:
        return {'覚えるか': False, '訳': '長すぎます（要点が絞れません）'}

    for 形 in 覚えないもの:
        if re.search(形, t):
            return {'覚えるか': False, '訳': 'その場だけの話か、問いかけです'}

    当たり = []
    for 形, 種類, 確か in 覚える手がかり:
        if re.search(形, t):
            当たり.append((種類, 確か))

    if not 当たり:
        return {'覚えるか': False, '訳': '覚えるべき手がかりが見つかりません'}

    # いちばん確からしいものを採る
    当たり.sort(key=lambda x: -x[1])
    種類, 確か = 当たり[0]

    return {
        '覚えるか': True,
        '種類': 種類,
        '確からしさ': 確か,
        '訳': f'{種類}として覚える値打ちがありそうです',
    }


def 覚える形にする(文, 種類):
    """
    そのまま覚えず、あとで引ける形に直す。

    「浅煎りが好きなんだ」→「コーヒーは浅煎りが好き」
    のように直せると良いが、
    <b>言い換えると意味が変わる危険がある</b>。

    だから、直さない。そのまま残して、種類だけ添える。
    正確さのほうが大事。
    """
    t = (文 or '').strip()
    return f'[{種類}] {t}'


def 会話から拾う(あなたの言葉, いまの知識=None):
    """
    会話の一言から、覚えるべきものを拾う。

    @param あなたの言葉  言われたこと
    @param いまの知識    すでに覚えているもの（重複を避けるため）
    @return {'覚えるか':bool, '中身':…, '訳':…}
    """
    見立て = 覚える値打ちがあるか(あなたの言葉)
    if not 見立て['覚えるか']:
        return {'覚えるか': False, '訳': 見立て['訳']}

    中身 = 覚える形にする(あなたの言葉, 見立て['種類'])

    # 同じことを二度覚えない
    if いまの知識:
        素の言葉 = (あなたの言葉 or '').strip()
        for x in いまの知識:
            文 = x if isinstance(x, str) else x.get('text', '')
            if 素の言葉 and 素の言葉 in 文:
                return {'覚えるか': False, '訳': 'すでに覚えています'}

    return {
        '覚えるか': True,
        '中身': 中身,
        '種類': 見立て['種類'],
        '確からしさ': 見立て['確からしさ'],
        '訳': f'「{見立て["種類"]}」として覚えます',
    }
