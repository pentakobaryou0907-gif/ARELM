# -*- coding: utf-8 -*-
"""
SNS文章 ― 商品情報とトーンから、投稿文を複数パターン作る

なぜこれが要るのか:

    一人で複数パターンの投稿文を考えるのは時間がかかる。
    商品名・価格・特徴と、ブランドのトーン（カジュアル／高級感／ユーモラス等）を
    渡すと、ローカルLLM（Qwen2.5・この端末の中だけ）が数パターン考える。

    最初はテキストだけ。画像生成との連携は、
    文章の精度に納得できてから、別の機能として足す
    （マスタープロンプトの進め方どおり：小さく作って、確かめてから広げる）。

外部へは一切送らない。
"""

import re

import ローカルLLM


def パターンを作る(商品情報, トーン='カジュアル', 件数=3, 型='キャプション'):
    """
    投稿文を複数パターン作る。

    @param 商品情報  商品名・価格・特徴などをまとめた自由文
                     （型によっては、ブランド情報や写真の説明を含む自由文にもなる）
    @param トーン    'カジュアル' / '高級感' / 'ユーモラス' など
    @param 件数      いくつ作るか（既定3。'トーク台本' は1本だけなので無視される）
    @param 型        'キャプション'（既定）／'トーク台本'／'工程公開'
    @return {'ok': bool, '訳': str, 'パターン': [str, ...]}
    """
    商品情報 = (商品情報 or '').strip()
    if not 商品情報:
        return {'ok': False, '訳': '商品・ブランドの情報が要ります', 'パターン': []}

    if not ローカルLLM.使えるか():
        return {
            'ok': False,
            '訳': 'ローカルAI（Ollama）が動いていません。起動してからお試しください。',
            'パターン': [],
        }

    if 型 == 'トーク台本':
        件数 = 1
        指示 = (
            f'あなたはアパレルブランド「AReGLM」の中の人です。'
            f'カメラに向かって話す、30秒程度のショート動画用トーク台本を1本、日本語で書いてください。\n'
            f'\n'
            f'トーン: {トーン}\n'
            f'\n'
            f'必ずこの3つの流れで書いてください（見出しは書かず、台詞だけを続けて書く）：\n'
            f'1. 数字か意外な事実で、最初の1文だけで惹きつける\n'
            f'2. 直面した課題・工夫したことを、実感のこもった言葉で語る\n'
            f'3. 「保存して」「フォローして」等、次の行動を促す一言で締める\n'
            f'\n'
            f'守ること:\n'
            f'・話し言葉（台詞）として書く。書き言葉の説明文にしない。\n'
            f'・実在しない実績・数字を作らない。渡された情報に書かれていないことは言わない。\n'
            f'・長すぎない（400字程度まで）。\n'
            f'・前置きや説明は書かず、台詞だけを出力する。\n'
            f'\n'
            f'【ブランド・商品・直近の状況】\n{商品情報}'
        )
    elif 型 == '工程公開':
        指示 = (
            f'あなたはアパレルブランド「AReGLM」のSNS担当です。'
            f'制作工程・素材の写真を使った投稿のキャプションを、{件数}パターン考えてください。\n'
            f'\n'
            f'トーン: {トーン}\n'
            f'\n'
            f'必ずこの3つの流れで書いてください：\n'
            f'1. 見る人への問いかけ（「〇〇って気になったことありませんか？」等）\n'
            f'2. 写真に写っている工程・素材の紹介（渡された情報の範囲で具体的に）\n'
            f'3. 保存・コメント・フォローなどを促す一言\n'
            f'\n'
            f'守ること:\n'
            f'・{件数}パターンとも、問いかけの切り口をはっきり変えてください。\n'
            f'・渡された情報に無い工程・素材を作り話しない。\n'
            f'・絵文字は使いすぎない程度に使ってよいです。\n'
            f'・ハッシュタグは各パターンの最後に2〜4個つけてください。\n'
            f'・必ず日本語で書いてください。\n'
            f'・出力は次の形式だけにしてください（前置きや説明は書かない）。\n'
            f'1. （1つ目の投稿文）\n'
            f'2. （2つ目の投稿文）\n'
            f'\n'
            f'【写真の内容・商品情報】\n{商品情報}'
        )
    else:
        指示 = (
            f'あなたはアパレルブランド「AReGLM」のSNS担当です。'
            f'次の商品について、Instagram投稿用のキャプションを、'
            f'{件数}パターン考えてください。\n'
            f'\n'
            f'トーン: {トーン}\n'
            f'\n'
            f'守ること:\n'
            f'・{件数}パターンとも、言い回し・切り口をはっきり変えてください（同じ文の言い換えにしない）。\n'
            f'・絵文字は使いすぎない程度に使ってよいです。\n'
            f'・ハッシュタグは各パターンの最後に2〜4個つけてください。\n'
            f'・必ず日本語で書いてください。\n'
            f'・出力は次の形式だけにしてください（前置きや説明は書かない）。\n'
            f'1. （1つ目の投稿文）\n'
            f'2. （2つ目の投稿文）\n'
            f'3. （3つ目の投稿文）\n'
            f'\n'
            f'【商品情報】\n{商品情報}'
        )

    # 3パターンぶんの文章を一度に作らせるため、出力が長くなる。
    # 60秒では、初回（モデルがまだ温まっていない）に間に合わないことがあった
    # （実測: 1回目は30秒超で失敗、2回目は40秒で成功）。余裕を持たせる。
    答え = ローカルLLM.聞く(指示, タイムアウト=120)
    if not 答え:
        return {'ok': False, '訳': 'ローカルAIから答えが返りませんでした', 'パターン': []}

    パターン = _番号付きの文を分ける(答え, 件数)
    if not パターン:
        # 番号の形で来なかったときは、そのまま1件として返す。
        # 何も返さないより、加工前でも見せたほうが良い。
        パターン = [答え.strip()]

    return {'ok': True, '訳': f'{len(パターン)}パターン作りました', 'パターン': パターン}


def _番号付きの文を分ける(文, 件数上限):
    """「1. ……」「2. ……」の形の文章を、パターンごとの配列に分ける。"""
    区切り = re.split(r'(?m)^\s*(\d+)[\.\)、]\s*', 文)
    # re.split で番号を捕捉すると ['前置き', '1', '本文1', '2', '本文2', ...] の形になる
    結果 = []
    for i in range(1, len(区切り), 2):
        本文 = 区切り[i + 1].strip() if i + 1 < len(区切り) else ''
        if 本文:
            結果.append(本文)
    return 結果[:件数上限]
