def カルーセル構成を作る(商品情報, トーン='カジュアル', 枚数=5):
    """
    カルーセル投稿（複数枚スライド）の構成を作る（パターンA）。

    実際の画像は作らない（Canvasでの描画は画面側の役目）。
    ここで作るのは「フックの見出し」と「各スライドの見出し・本文」という
    文章の構成だけ。文章の精度が伝わって初めて、次に画像化する意味がある
    （マスタープロンプトの進め方どおり）。

    @return {'ok': bool, '訳': str, 'フック': str, 'スライド': [{'見出し':str,'本文':str}, ...]}
    """
    商品情報 = (商品情報 or '').strip()
    if not 商品情報:
        return {'ok': False, '訳': '商品・ブランドの情報が要ります', 'フック': '', 'スライド': []}

    if not ローカルLLM.使えるか():
        return {
            'ok': False,
            '訳': 'ローカルAI（Ollama）が動いていません。起動してからお試しください。',
            'フック': '', 'スライド': [],
        }

    本数 = max(3, min(6, int(枚数 or 5))) - 1  # フック1枚を除いた本編の枚数

    指示 = (
        f'あなたはアパレルブランド「ARELM」のSNS担当です。'
        f'次の商品について、Instagramのカルーセル投稿（複数枚スライド）の構成を考えてください。\n'
        f'\n'
        f'トーン: {トーン}\n'
        f'\n'
        f'守ること:\n'
        f'・渡された情報に無い実績・数字・工程を作り話しない。\n'
        f'・1枚に書く文字は短く（見出しは10字程度、本文は1〜2文）。\n'
        f'・{本数}枚の本編スライドは、見出しの角度をそれぞれ変える（同じ話の言い換えにしない）。\n'
        f'・必ず日本語で書いてください。\n'
        f'・出力は次の形式だけにしてください（前置きや説明は書かない）。\n'
        f'【フック】\n'
        f'（1枚目に大きく出す、目を引く一言。数字や意外性のある言い方）\n'
        f'【1】\n'
        f'見出し1\n'
        f'本文1\n'
        f'【2】\n'
        f'見出し2\n'
        f'本文2\n'
        f'\n'
        f'【商品情報】\n{商品情報}'
    )

    答え = ローカルLLM.聞く(指示, タイムアウト=90)
    if not 答え:
        return {'ok': False, '訳': 'ローカルAIから答えが返りませんでした', 'フック': '', 'スライド': []}

    フック, スライド = _カルーセルを分ける(答え, 本数)
    if not スライド:
        return {'ok': False, '訳': '構成をうまく読み取れませんでした。もう一度お試しください。', 'フック': フック, 'スライド': []}

    return {'ok': True, '訳': f'フック＋{len(スライド)}枚の構成を作りました', 'フック': フック, 'スライド': スライド}


def _カルーセルを分ける(文, 枚数上限):
    """【フック】【1】見出し\n本文 の形を、フックとスライド配列に分ける。"""
    _match = re.search(r'【フック】\s*\n?(.+?)(?=【\d|\Z)', 文, re.S)
    フック = _match.group(1).strip() if _match else ''

    区切り = re.split(r'(?m)^\s*【(\d+)】\s*\n?', 文)
    スライド = []
    for i in range(1, len(区切り), 2):
        中身 = 区切り[i + 1].strip() if i + 1 < len(区切り) else ''
        if not 中身:
            continue
        行たち = [l.strip() for l in 中身.split('\n') if l.strip()]
        見出し = 行たち[0] if 行たち else ''
        本文 = ' '.join(行たち[1:]) if len(行たち) > 1 else ''
        スライド.append({'見出し': 見出し, '本文': 本文})
    return フック, スライド[:枚数上限]


def _番号付きの文を分ける(文, 件数上限):
    """「1. ……」「2. ……」の形の文章を、パターンごとの配列に分ける。"""
    区切り = re.split(r'(?m)^\s*(\d+)[\.\)、]\s*', 文)
    # re.split で番号を捕捉すると ['前置き', '1', '本文1', '2', '本文2', ...] の形になる
    結果 = []
    for i in range(1, len(区切り), 2):
        本文 = 区切り[i + 1].strip() if i + 1 < len(区切り) else ''
        if 本文:
            結果.append(本文)
    return 結果[:件数上限]
