            f'トーン: {トーン}\n'
            f'\n'
            f'必ずこの3つの流れで書いてください：\n'
            f'1. 見る人への問いかけ（「〇〇って気になったことありませんか？」等）\n'
            f'2. 写真に写っている工程・素材の紹介（渡された情報の範囲で具体的に）\n'
            f'3. 保存・コメント・フォローなどを促す一言\n'
