            f'\n'
            f'守ること:\n'
            f'・各カットは「画面に映すもの＋一言（テロップ・話す内容）」を、\n'
            f'  「（映すもの）／（一言）」の形で具体的に書く。\n'
            f'・渡された情報に無い実績・数字・工程を作り話しない。\n'
            f'・1カットは短く（40字程度まで）。\n'
            f'・必ず日本語で書いてください。\n'
