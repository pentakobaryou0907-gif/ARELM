def 学習を見る(learner, semantic):
    """
    覚えたことの質を見る。

    落ちていたら、それは何かを間違えて覚えた印。
    黙って進めると、そのまま濁っていく。
    """
    出 = []

    try:
        import 学習の質を測る as 測る
        結果 = 測る.測る(learner, semantic) if hasattr(測る, '測る') else None
    except Exception:
        結果 = None

    総数 = getattr(learner, 'total_docs', 0)
    語彙 = len(getattr(learner, 'vocabulary', {}) or {})

    # 語彙の汚れ（意味を成さない断片）
    汚れ = 0
    語たち = list((getattr(learner, 'doc_freq', {}) or {}).keys())
    for 語 in 語たち[:5000]:
        if len(語) == 2 and all('゠' <= c <= 'ヿ' for c in 語):
            汚れ += 1
    汚れの割合 = 汚れ / max(1, min(5000, len(語たち)))

    if 汚れの割合 > 0.05:
        出.append({
            '重さ': 2,
            '件': f'語彙に、意味を成さない断片が {汚れの割合*100:.1f}% あります',
            '訳': '切り出しに失敗した跡が貯まっています。'
                  '多くなると、言葉のつながりが濁ります。',
            '直せるか': '人に聞く',
            '直し方': '取り込みの仕方を見直す必要があります。',
        })

    # 分類の偏り
    分類 = getattr(learner, 'category_counts', None) or {}
    if 分類:
        多い = Counter(分類).most_common(1)
        if 多い and 多い[0][1] / max(1, 総数) > 0.6:
            出.append({
                '重さ': 2,
                '件': f'「{多い[0][0]}」に {多い[0][1]/max(1,総数)*100:.0f}% が偏っています',
                '訳': '一つの分類に寄りすぎると、'
                      '他の話題を聞かれたときに当たらなくなります。',
                '直せるか': '人に聞く',
                '直し方': '他の分類の資料を足すと、釣り合いが取れます。',
            })

    出.append({
        '重さ': 0,
        '件': f'覚えた文 {総数}件 / 語彙 {語彙}語',
        '訳': '',
        '直せるか': '',
        '直し方': '',
    })

    return 出


def 技能の使われ方を見る(使われ方):
    """
    どの作業がよく使われ、どれが使われていないかを見る。

    使われていないものは、見つけにくいか、要らないか。
    どちらにせよ、そのままにしておく理由がない。
    """
    出 = []
    if not 使われ方:
        return 出

    import skills
    全部 = {s.action for s in skills.SKILLS}
    使った = set(使われ方.keys())
    使われていない = 全部 - 使った

    if len(使われていない) > len(全部) * 0.5:
        出.append({
            '重さ': 1,
            '件': f'{len(使われていない)}種類の作業が、一度も使われていません',
            '訳': '見つけられていないか、要らないかのどちらかです。',
            '直せるか': '人に聞く',
            '直し方': '「何ができるの」と聞くと、一覧が出ます。',
        })

    多い = Counter(使われ方).most_common(3)
    if 多い:
        出.append({
            '重さ': 0,
            '件': 'よく使う作業: ' + '、'.join(f'{k}（{v}回）' for k, v in 多い),
            '訳': '',
            '直せるか': '',
            '直し方': '',
        })

    return 出


def 繰り返しを見つける(履歴):
    """
    同じ並びを何度もやっているなら、それは手順になる。

    毎回同じ順で三つの作業をしているなら、
    それは一つの作業として覚えたほうが早い。
    こちらから「覚えさせますか」と聞く。
    """
    出 = []
    if not 履歴 or len(履歴) < 6:
        return 出

    # 三つ続きの並びを数える
    並び = Counter()
    for i in range(len(履歴) - 2):
        三つ = tuple(履歴[i:i + 3])
        if len(set(三つ)) == 3:      # 同じ作業の繰り返しは除く
            並び[三つ] += 1

    for 組, 回数 in 並び.most_common(2):
        if 回数 >= 3:
            出.append({
                '重さ': 1,
                '件': f'この順で {回数}回 繰り返しています: {" → ".join(組)}',
                '訳': '毎回同じ順で行っているなら、'
                      '一つの作業として覚えたほうが早く済みます。',
                '直せるか': '人に聞く',
                '直し方': 'エージェント →「新しい作業を覚えさせる」で、この順に並べられます。',
                '手順の案': list(組),
            })

    return 出


def 見立てる(learner, semantic, 使われ方=None, 履歴=None):
    """
    自分を一通り見て、気づいたことを返す。

    @return {'気づき': [...], 'まとめ': str}
    """
    気づき = []
    気づき += 学習を見る(learner, semantic)
    気づき += 技能の使われ方を見る(使われ方 or {})
    気づき += 繰り返しを見つける(履歴 or [])

    気づき.sort(key=lambda x: -x['重さ'])

    直すべき = [x for x in 気づき if x['重さ'] >= 2]
    提案 = [x for x in 気づき if x['重さ'] == 1]

    if 直すべき:
        まとめ = f'見直したほうがよい点が {len(直すべき)}件 あります。'
    elif 提案:
        まとめ = f'こうするともっと楽になる、という点が {len(提案)}件 あります。'
    else:
        まとめ = 'いまのところ、直したほうがよい点は見つかりませんでした。'

    _記録を残す({
        '見た': len(気づき),
        'まとめ': まとめ,
    })

    return {'気づき': 気づき, 'まとめ': まとめ}


def 記録を出す():
    return _記録を読む()
