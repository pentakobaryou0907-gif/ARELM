"""
自分を分析して、自分を良くしていく

なぜこれが要るのか:
    ここまでで「言われたことをやる」「決めておけば勝手に動く」までは出来た。
    だが、良くなっていくのは私が手を入れたときだけ。
    それでは、私がいなくなれば止まる。

    自分で自分を見て、自分で良くしていけるようにする。

やらないこと:

    <b>自分のコードを書き換えて実行することは、しません。</b>
    誰も見ていないところで自分を書き換える仕組みは、
    一度おかしくなったら止められなくなる。
    危険が利益を上回る。

    代わりに、
      ・自分のふるまいを測る
      ・良くする案を出す
      ・安全なものは自分で直す
      ・危ないものは、必ず人に聞く
    という形にする。

    直せるのは「覚えたこと」と「決めた数字」まで。
    仕組みそのものには手を出さない。

外部へは一切問い合わせません。すべてこの端末の中で完結します。
"""

import json
import os
from collections import Counter

置き場 = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                    '..', 'data', '自分を良くした記録.json')


def _記録を読む():
    try:
        with open(置き場, encoding='utf-8') as f:
            r = json.load(f)
        return r if isinstance(r, list) else []
    except (OSError, ValueError):
        return []


def _記録を残す(中身):
    記録 = _記録を読む()
    記録.append(dict(中身, とき=__import__('datetime').datetime.now().isoformat()))
    場所 = os.path.dirname(os.path.abspath(置き場))
    os.makedirs(場所, exist_ok=True)
    with open(置き場, 'w', encoding='utf-8') as f:
        json.dump(記録[-200:], f, ensure_ascii=False, indent=2)


