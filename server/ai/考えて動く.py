# -*- coding: utf-8 -*-
"""
考えて動く ― 結果を見て、次を決める

なぜこれが要るのか:

    いまの段取りは、決まった順に進むだけ。
    手順1 → 手順2 → 手順3 →（終わり）

    だが実際の仕事は、そうならない。
    在庫を見て、少なければ発注を考える。
    十分なら、そこで止める。
    <b>結果を見てから、次を決める</b>のが本当のやり方。

    ジャービスのような働き方の中身は、これ。
    難しい仕組みではない。
    「やる → 見る → 決める」を繰り返すだけ。

外部のライブラリは使いません:

    LangGraph のようなものを入れれば早い。
    だが、それは他人が書いたコードを取り込むこと。
    この道具は全部自作で通してきたので、ここも通す。

    それに、必要なのは繰り返しと分岐だけ。
    そのために何万行も取り込むのは、割に合わない。

止まらなくならないために:

    ・<b>回数に上限を置く</b>（既定8回）
      考え続けて止まらないのが、いちばん困る。

    ・<b>同じことを繰り返したら止める</b>
      前と同じ手を選んだなら、それは進んでいない。

    ・<b>何を考えたかを全部残す</b>
      勝手に動くものほど、後から追えないと怖い。

外部へは一切問い合わせません。すべてこの端末の中で完結します。
"""

import json
import os

置き場 = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                    '..', 'data', '考えた記録.json')

# 何回まで考えるか。これを超えたら、そこで止めて人に返す。
考える上限 = 8


def _記録を読む():
    try:
        with open(置き場, encoding='utf-8') as f:
            r = json.load(f)
        return r if isinstance(r, list) else []
    except (OSError, ValueError):
        return []


def _記録を残す(中身):
    記録 = _記録を読む()
    記録.append(dict(中身, とき=__import__('datetime').datetime.now().isoformat()))
    場所 = os.path.dirname(os.path.abspath(置き場))
    os.makedirs(場所, exist_ok=True)
    with open(置き場, 'w', encoding='utf-8') as f:
        json.dump(記録[-100:], f, ensure_ascii=False, indent=2)


def 記録を出す():
    return _記録を読む()


# ------------------------------------------------------------------
# 次に何をするかを決める
# ------------------------------------------------------------------

def 次を決める(頼まれたこと, これまで, 使える作業):
    """
    いままでの結果を見て、次に何をするかを決める。

    決め方は単純にしてある。
    複雑にすると、なぜそう決まったか説明できなくなる。
    説明できない判断は、信じられない。

    @param 頼まれたこと  最初に言われたこと
    @param これまで      [{'作業':…, '結果':…}]
    @param 使える作業    動かせる作業の名前
    @return {'する':bool, '作業':…, '訳':…}
    """
    # --- もう十分やったか ---
    if len(これまで) >= 考える上限:
        return {
            'する': False,
            '訳': f'{考える上限}回 考えたので、ここで止めます。'
                  '考え続けて止まらないほうが困るためです。',
            '止めた訳': '回数の上限',
        }

    # --- 同じことを繰り返していないか ---
    if len(これまで) >= 2:
        直前 = これまで[-1].get('作業')
        その前 = これまで[-2].get('作業')
        if 直前 and 直前 == その前:
            return {
                'する': False,
                '訳': f'「{直前}」を続けて2回行いました。'
                      '同じ手を繰り返しているので、ここで止めます。',
                '止めた訳': '同じことの繰り返し',
            }

    # --- 直前の結果から、次を決める ---
    直前の結果 = (これまで[-1].get('結果') if これまで else '') or ''

    # 結果の中に「次にすべきこと」が書かれていることがある。
    # 分析や点検は、そういう答え方をする。
    次の手がかり = [
        (['在庫が少な', '残り', '切れ', '補充'], 'add_task', '発注をやることに入れる'),
        (['原価を割', '赤字', '粗利'], 'price_advice', '値段を考え直す'),
        (['期限を過ぎ', '遅れ'], 'next_steps', '次に手を付けるものを選ぶ'),
        (['似ている', '重複'], 'check_duplicate', '似ている商品を確かめる'),
    ]

    for 語たち, 作業, 訳 in 次の手がかり:
        if any(語 in 直前の結果 for 語 in 語たち):
            if 作業 in 使える作業 and not any(x.get('作業') == 作業 for x in これまで):
                return {'する': True, '作業': 作業, '訳': 訳}

    # --- 手がかりが無ければ、そこで終える ---
    #
    # 分からないのに何かを続けるのは、当てずっぽうになる。
    # 「次にすることが見つからない」と言うほうが正直。
    return {
        'する': False,
        '訳': '結果から、次にすべきことが見つかりませんでした。',
        '止めた訳': '次が見つからない',
    }


def 考える流れを作る(頼まれたこと, 最初の作業, 使える作業):
    """
    考えながら進む流れを、はじめの一手だけ決めて返す。

    残りは、結果を見てから決める。
    先に全部決めてしまうと、結果を見る意味が無くなる。
    """
    _記録を残す({
        '頼まれたこと': (頼まれたこと or '')[:80],
        '最初の作業': 最初の作業,
        '様子': '始めました',
    })

    return {
        'ok': True,
        '考えながら進む': True,
        '最初の作業': 最初の作業,
        '上限': 考える上限,
        '訳': '一手ずつ進めて、結果を見てから次を決めます。'
              f'考えるのは{考える上限}回までにしてあります。',
    }


def 一手ぶんを考える(頼まれたこと, これまで, 使える作業):
    """
    一手ぶんだけ考える。画面側から繰り返し呼ばれる。
    """
    決めた = 次を決める(頼まれたこと, これまで, 使える作業)

    _記録を残す({
        '頼まれたこと': (頼まれたこと or '')[:60],
        '何手目': len(これまで) + 1,
        '決めた': 決めた.get('作業', '（終わり）'),
        '訳': 決めた.get('訳', '')[:80],
    })

    return 決めた
