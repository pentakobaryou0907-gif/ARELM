# -*- coding: utf-8 -*-
"""
権利のあるものを見分ける

なぜこれが要るのか:
    資料を学ばせるとき、他人の権利がかかっているものまで
    そのまま覚えてしまうと、あとで問題になる。
    トラブルに巻き込まれたくない、という方針に反する。

ここでの考え方:
    権利のあるものは「覚えない」。
    ただし「見なかったこと」にもしない。

    そういうものが在るという事実だけは残し、
    どこに何があったかを控えておく。
    そうすれば、
      - 必要になったとき自分で原典を確認できる
      - 誤って学んでいないことを、あとから確かめられる

    中身を覚えないので引用もできない。
    これは制限ではなく、そのための設計。

見分けるもの:
    1. はっきりした表示 … ©、All rights reserved、無断転載禁止 など
    2. 使用条件の文言   … ライセンス、利用規約、特許 など
    3. 他社の資料の形   … 提供元の明記された配布物

見分けられないものは通す。
疑わしいものを全部止めると、自分の資料まで学べなくなるため。
"""

import os
import re

# --- はっきりした権利の表示 ---
#
# これらが書かれている資料は、書いた人が明確に権利を主張している。
# 迷う余地が無いので、中身は覚えない。
権利の表示 = [
    (r'©|\(c\)\s*\d{4}|Copyright\s*(\(c\)|©)?\s*\d{4}', '著作権表示'),
    (r'All\s+Rights?\s+Reserved', '権利の留保'),
    (r'無断転載\s*(を)?\s*(禁|きん)', '無断転載の禁止'),
    (r'無断複製|複製\s*を?\s*禁', '複製の禁止'),
    (r'転載\s*・?\s*複製\s*を?\s*禁', '転載複製の禁止'),
]

# --- 使用に条件が付いているもの ---
使用条件 = [
    (r'ライセンス契約|使用許諾|利用規約|Terms\s+of\s+(Use|Service)', '使用条件あり'),
    (r'End\s+User\s+License|EULA', '使用許諾契約'),
    (r'特許\s*(第|出願|番号|権)|Patent\s+(No|Pending)', '特許'),
    (r'実用新案|意匠登録|商標登録', '産業財産権'),
    (r'GPL|LGPL|AGPL|MIT\s+License|Apache\s+License|BSD\s+License', 'ソフトウェアの使用条件'),
]

# --- 他社が作った配布物の形 ---
#
# ファイル名や冒頭に、提供元がはっきり書かれているもの。
他社の資料 = [
    (r'株式会社[^\s、。]{1,20}\s*(提供|作成|発行|制作)', '他社の発行物'),
    (r'(発行|編集|監修)\s*[:：]\s*[^\s、。]{2,30}', '発行元の明記'),
    (r'教科書|参考書|問題集|テキスト\s*(第|Vol)', '市販の教材'),
]


def 調べる(text, path=''):
    """
    権利がかかっているかを見る。

    @return dict
        学ばせてよいか … True なら中身を覚えてよい
        種類           … 何にあたるか。無ければ None
        根拠           … そう判断した理由（実際に見つかった文字）
    """
    if not text:
        return {'学ばせてよいか': True, '種類': None, '根拠': None}

    頭 = text[:6000]

    for 組 in (権利の表示, 使用条件, 他社の資料):
        for 型, 名 in 組:
            m = re.search(型, 頭, re.IGNORECASE)
            if m:
                return {
                    '学ばせてよいか': False,
                    '種類': 名,
                    '根拠': m.group(0)[:60],
                }

    return {'学ばせてよいか': True, '種類': None, '根拠': None}


def 控えを作る(path, 判定, text=''):
    """
    覚えない代わりに残す控え。

    中身は入れない。入れたら「覚えない」と言った意味が無くなる。
    残すのは、どこに何があったか、それだけ。

    @return dict 控えの中身
    """
    return {
        '場所': path,
        '名前': os.path.basename(path),
        '種類': 判定['種類'],
        '根拠': 判定['根拠'],
        '大きさ': len(text),
        '覚えたか': False,
        '備考': '権利がかかっているため、中身は覚えていません。'
                '必要なときは、この場所の原典をご自身で確認してください。',
    }


def まとめ(控えたち):
    """
    どんなものが在ったかを、読める形にまとめる。

    「学ばなかった」ことを黙っていると、
    学んだつもりでいる、という食い違いが起きる。
    それを避けるために出す。
    """
    if not 控えたち:
        return '権利がかかっている資料は見つかりませんでした。'

    種類ごと = {}
    for c in 控えたち:
        種類ごと.setdefault(c['種類'] or '不明', []).append(c['名前'])

    行 = [f'権利がかかっているため、{len(控えたち)}件は中身を覚えていません。', '']
    for 種, 名たち in sorted(種類ごと.items(), key=lambda x: -len(x[1])):
        行.append(f'・{種}: {len(名たち)}件')
        for n in 名たち[:3]:
            行.append(f'　　{n}')
        if len(名たち) > 3:
            行.append(f'　　ほか {len(名たち) - 3}件')
        行.append('')

    行.append('在ることは控えてあります。必要なときは原典をご確認ください。')
    return '\n'.join(行)
