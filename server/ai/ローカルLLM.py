"""
ローカルLLM ― この端末の中だけで動く、広い知識を持つAI

なぜ要るのか:
    このツールの自作AI（chat_engine.py・knowledge.py など）は、
    教えたこと・入れた資料からしか答えられない。
    それ以外は「分かりません」と正直に言うしかなかった。

    「ChatGPT（GPT）の学習データを入れてほしい」と頼まれたが、
    それはできない。GPTの中身は取り出せないし、
    学習データの多くは他人の著作物で、複製して配ってよいものでもない。

    代わりに、同じ狙い（広い知識で答えられるようにする）を、
    正しいやり方で叶える。Ollama（無料・オープンソース）を使い、
    公開されている学習済みモデルを、この端末の中だけで動かす。
    外部のサーバーには一切送らない。GPTなどの他社サービスも使わない。

使うモデル:
    qwen2.5:7b
    ・Apache 2.0 ライセンス（無料・商用利用可）
    ・日本語の会話に比較的強い
    ・7B（量子化後 約4.7GB）で、この端末でも現実的に動く大きさ

このAIが「分かりません」と言ったときだけ、ここに聞きにいく。
在庫・価格・記録した知識など、このツール固有のことは
これまで通り自作AIが直接答える（ここは通らない）。

安全のために:
    ・システム指示で、違法行為・犯罪の具体的な手順には答えないよう明記する。
    ・127.0.0.1（この端末の中）以外には接続しない。
    ・失敗しても、呼び出し側の会話を止めない（None を返すだけ）。
"""

import json
import urllib.error
import urllib.request

OLLAMA_の場所 = 'http://127.0.0.1:11434'
モデル = 'qwen2.5:7b'

指示 = (
    'あなたは「アレラム」という名前で、ARELM というアパレルブランド運営ツールの'
    '中で動くAIアシスタントです。次を必ず守ってください。\n'
    '・違法行為や犯罪につながる具体的な方法、他人を傷つける内容には答えないでください。\n'
    '・分からないことは、知ったかぶりせず「分かりません」と言ってください。\n'
    '・日本語で、簡潔に、丁寧に答えてください。\n'
    '・あなたはこの端末の中だけで動作しており、外部にデータを送信しません。\n'
    '\n'
    '【最重要】質問の中に「【過去の記録】」「【質問】」という見出しが含まれている場合、\n'
    'それはこのユーザー自身が記録した事実です。その記録に書かれている内容は、\n'
    '事実として自信を持って使い、記録の内容にもとづいて答えてください。\n'
    '\n'
    'それ以外の場合、つまりユーザーのブランド・商品・在庫・価格・定休日・売上・\n'
    '仕入れ先など、<b>このユーザー個人や事業に関する具体的な事実で、かつ記録が\n'
    '一緒に渡されていないとき</b>は、想像や一般論で「〜だと思います」「通常は〜です」\n'
    'と答えず、必ず「そのことはこのツールに記録されていないようです」と正直に返してください。\n'
    '一般知識（地理・歴史・科学・言葉の意味など）には、いつも通り自信を持って答えてください。'
)


def 使えるか(タイムアウト=2):
    """Ollama が起動していて、応答できる状態か確かめる。"""
    try:
        with urllib.request.urlopen(
                f'{OLLAMA_の場所}/api/version', timeout=タイムアウト) as 応答:
            return 応答.status == 200
    except (urllib.error.URLError, OSError, TimeoutError):
        return False


def 聞く(質問, タイムアウト=None, 最大出力=None):
    """
    ローカルLLMに聞く。

    失敗したら None を返すだけにする。
    ここで例外を投げると、会話全体が止まってしまう。
    自作AIの「分かりません」に落ち着けるほうが、まだ良い。

    タイムアウトは既定で付けない（いつまでも待つ）。
    呼び出し箇所ごとに30秒・60秒・90秒…と数字を変えて対策していたが、
    「操作一覧つきの本番の指示文だと31秒かかるのに、制限は30秒だった」
    のように、実測とずれていて正しく判定できているのに毎回時間切れで
    捨てられる、ということが繰り返し起きていた（SNS文章.py の
    2回目コメント参照）。この端末の中だけで動くモデルなので、待った分だけ
    ちゃんと答えが返ってくる。外部サービスのように待たせて料金がかさむ
    ものでもないので、急いで切る理由が無い。
    呼び出し側がどうしても上限を付けたい場合だけ、タイムアウトを指定する。

    @param 最大出力  生成する最大トークン数。
        操作の判定のような「短いJSONで十分」な用途では、
        小さくするとその分だけ答えが速く返る
        （長い雑談の答えでは None のまま、上限を付けない）。
    """
    if not (質問 or '').strip():
        return None

    try:
        中身 = {
            'model': モデル,
            'prompt': 質問,
            'system': 指示,
            'stream': False,
            # 呼ぶたびにモデルを読み直すと、それだけで数秒〜十数秒かかる。
            # 一定時間はメモリ（GPU）に乗せたままにして、続けて聞かれた
            # ときに読み直しの時間を無くす（エージェントの返事が遅い、
            # の主因）。ただし乗せている間はこの端末のGPUメモリを
            # 約5GB占有し続けるので、「速さ」と「この端末への負担」は
            # 綱引きになる。使っている間だけ乗せておき、しばらく話しかけ
            # られなければ自分から手放す、という折衷にして20分にした
            # （4時間乗せっぱなしにしたことがあったが、使っていない間まで
            # PCに負担をかけ続けるのは望まれていなかった）。
            'keep_alive': '20m',
            # 指定しないと Ollama は既定で 4096 トークンに切り詰める
            # （qwen2.5:7b 自体は 32768 まで扱えるのに、である）。
            # 会話の履歴・話し方の指示・ブランドの記憶・質問文を
            # 全部積むと、長い会話ほどこの既定値で古い部分から
            # 切り捨てられ、話し方の指示や文脈を忘れたように見えていた。
            # 8192まで広げ、まだ速度に余裕がある範囲で質を上げる。
            #
            # repeat_penalty は既定値（1.1）から動かさない。
            # 「同じ返事を繰り返す」という報告を受けて一度1.3まで強めて
            # 試したが、JSON形式の「操作id」「材料」「会話の返事」という
            # 決まった言葉自体まで「繰り返し」とみなして避けようとし、
            # 簡体字（会话的回复）や存在しない項目名（materials）
            # ・でたらめな数値（"操作id": 1234567890）を生成するようになり、
            # かえって遅く・不正確になった（実測: 220トークン中52まで生成し
            # 18.3秒、既定値なら34トークン・12.6秒で正しいJSONが返った）。
            # 「繰り返し」の報告には、別の原因（呼び出し側の表示の重複等）
            # を先に疑うこと。
            'options': {'num_ctx': 8192},
        }
        if 最大出力:
            中身['options']['num_predict'] = 最大出力
        本文 = json.dumps(中身).encode('utf-8')

        要求 = urllib.request.Request(
            f'{OLLAMA_の場所}/api/generate',
            data=本文,
            headers={'Content-Type': 'application/json'},
            method='POST',
        )
        with urllib.request.urlopen(要求, timeout=タイムアウト) as 応答:
            結果 = json.loads(応答.read().decode('utf-8'))
            答え = (結果.get('response') or '').strip()
            return 答え or None
    except (urllib.error.URLError, OSError, TimeoutError, ValueError, json.JSONDecodeError):
        return None


def 温めておく():
    """
    モデルを、実際に聞かれる前にメモリ（GPU）へ乗せておく。

    以前は起動時（アプリを開いた瞬間）に温めていたが、実際に話しかける
    かどうかに関わらずPCへ負担をかけることになり撤去した。ところが
    それだけだと、話しかけてから読み込みが始まるため、最初の一言が
    30〜90秒近く掛かることがあり、「指示しても何も動かない」ように
    見えてしまっていた。

    そこでいまは「これから話しかけそうだ」という合図（入力欄に
    カーソルを置いた・JARVISモードを開いた等）を受けたときにだけ、
    ここを呼んでもらう形にしている。実際に打ち終わる数秒〜十数秒の間に
    読み込みを済ませておければ、待たされている感覚を大きく減らせる。
    話しかけずに離れれば、20分の keep_alive で自然に手放される。

    options（num_ctx等）は 聞く() が実際に使う値と必ず揃えること。
    ここが食い違うと、後の呼び出しでOllamaが読み込み直しになり、
    温めた意味が無いどころかかえって遅くなる（過去に実測済み）。
    """
    try:
        中身 = json.dumps({
            'model': モデル,
            'keep_alive': '20m',
            'options': {'num_ctx': 8192},
        }).encode('utf-8')
        要求 = urllib.request.Request(
            f'{OLLAMA_の場所}/api/generate',
            data=中身,
            headers={'Content-Type': 'application/json'},
            method='POST',
        )
        urllib.request.urlopen(要求, timeout=120)
    except (urllib.error.URLError, OSError, TimeoutError, ValueError):
        pass
