# -*- coding: utf-8 -*-
"""
ブランドの記憶 ― ブランドごとの「前にやったこと・結果」を覚えておく

なぜこれが要るのか:

    「このブランド、前にどんな施策をやって、結果どうだったか」と聞いても、
    このAIは会話が終わると忘れる（30分で会話そのものが切れる）。

    最小版として、ブランドごとに短い記録を積み重ね、
    そのブランドの話が出たときだけ、直近の記録を会話に混ぜ込む。

    凝った構造にはしない。1件は「いつ・何のブランド・何を・どんな種類か」の
    4つだけ。件数が増えてから、検索や要約を良くしていく。

種類の例:
    決定   … 何かを決めた（例: 値下げした、新色を出した）
    結果   … 決めたことがどうなったか（例: 売上が伸びた）
    気づき … ふと分かったこと（例: 若い層に人気だった）

保存先は server/data/ブランドの記憶.json。
外部へは一切送らない。
"""

import json
import os
import time
import uuid

import 永久の記憶

置き場 = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'ブランドの記憶.json')

# 一つのブランドにつき、これより増えたら古いものから消す。
# 増えすぎると、会話に混ぜたときにプロンプトが長くなりすぎて、
# 答えが散漫になる（RAGでもよくある問題）。
ブランドごとの上限 = 200

# 会話に混ぜ込むとき、直近何件までにするか。
差し込む件数 = 5


def _全部読む():
    try:
        with open(置き場, encoding='utf-8') as f:
            r = json.load(f)
        return r if isinstance(r, list) else []
    except (OSError, ValueError):
        return []


def _全部書く(一覧):
    場所 = os.path.dirname(os.path.abspath(置き場))
    os.makedirs(場所, exist_ok=True)
    with open(置き場, 'w', encoding='utf-8') as f:
        json.dump(一覧, f, ensure_ascii=False, indent=1)


def 記録する(ブランド, 内容, 種類='気づき'):
    """1件、ブランドの記録を足す。"""
    ブランド = (ブランド or '').strip()
    内容 = (内容 or '').strip()
    if not ブランド or not 内容:
        return {'ok': False, '訳': 'ブランド名と内容の両方が要ります'}

    一覧 = _全部読む()
    一覧.append({
        'id': uuid.uuid4().hex[:12],
        'ブランド': ブランド,
        '内容': 内容,
        '種類': 種類 or '気づき',
        'とき': time.time(),
    })

    # このブランドの分だけ、多すぎたら古いものから落とす。
    同じブランド = [x for x in 一覧 if x['ブランド'] == ブランド]
    if len(同じブランド) > ブランドごとの上限:
        消す数 = len(同じブランド) - ブランドごとの上限
        消す対象 = {x['id'] for x in 同じブランド[:消す数]}
        # 本体の記録から外すだけ。外れたものは、永久の記憶に残る。
        for x in 同じブランド[:消す数]:
            永久の記憶.残す('ブランドの記憶', x, '1ブランドあたりの上限を超えたため、本体の記録から外れた')
        一覧 = [x for x in 一覧 if x['id'] not in 消す対象]

    _全部書く(一覧)
    return {'ok': True, '訳': f'「{ブランド}」の記録に足しました'}


def 読む(ブランド, 件数=None):
    """あるブランドの記録を、新しい順に返す。"""
    ブランド = (ブランド or '').strip()
    if not ブランド:
        return []
    件数 = 件数 or 差し込む件数
    一覧 = [x for x in _全部読む() if x['ブランド'] == ブランド]
    一覧.sort(key=lambda x: x.get('とき', 0), reverse=True)
    return 一覧[:件数]


def 記録を消す(id):
    一覧 = _全部読む()
    残す = [x for x in 一覧 if x.get('id') != id]
    if len(残す) == len(一覧):
        return {'ok': False, '訳': '見つかりませんでした'}
    _全部書く(残す)
    return {'ok': True}


def 既知のブランド一覧():
    """
    一度でも記録したことがあるブランド名の一覧。

    会話の中に、この一覧のどれかが出てきたら
    「このブランドの話をしている」とみなす手がかりに使う。
    フロント側からブランド一覧をもらわなくても、
    自分の記録から育っていくようにするため。
    """
    名たち = {x['ブランド'] for x in _全部読む()}
    return sorted(名たち, key=len, reverse=True)   # 長い名前を先に見る（部分一致の誤りを減らす）


def 文中のブランドを探す(text):
    """文の中に、記録のあるブランド名が含まれていれば、それを返す。"""
    t = text or ''
    for 名 in 既知のブランド一覧():
        if 名 and 名 in t:
            return 名
    return None


def プロンプトへ差し込む文(ブランド):
    """
    会話・ローカルLLMへの指示に、そのまま足せる形の文を作る。

    記録が無ければ、空文字を返す（無理に「記録はありません」と
    毎回書かない。無いときは、そもそも触れないほうが自然）。
    """
    記録たち = 読む(ブランド)
    if not 記録たち:
        return ''

    行 = [f'【{ブランド} についての過去の記録（新しい順）】']
    for x in 記録たち:
        日付 = time.strftime('%Y-%m-%d', time.localtime(x.get('とき', 0)))
        行.append(f'・[{日付}/{x.get("種類", "")}] {x.get("内容", "")}')
    return '\n'.join(行)
