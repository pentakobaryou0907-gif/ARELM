# -*- coding: utf-8 -*-
"""
話し方の調子を読む

なぜこれが要るのか:
    「？」も「！」も「…」も、ただの記号として捨てていた。
    そのため「これ違うよ！」も「これ違うの？」も同じ扱いになり、
    急いでいるのか、困っているのか、確かめたいだけなのかが
    まったく区別できていなかった。

    記号は、書き言葉における声の調子そのものにあたる。
    ここを読まないと、話が噛み合わない。

読み取るもの:
    種類   … 質問／依頼／指摘／同意／独り言
    強さ   … どれくらい強く言われているか（0.0〜1.0）
    気持ち … 困っている／急いでいる／不満／喜び／ためらい

嘘をつかないための線引き:
    ここで読むのは「書かれた形」だけ。
    書かれていない気持ちを推し量って、
    分かったふりをすることはしない。
    自信が無いときは「読み取れない」と返す。

外部へは一切問い合わせない。すべてこの端末の中で完結する。
"""

import re

# 記号は全角・半角の両方が来る。どちらも同じものとして扱う。
_全角から半角 = str.maketrans('？！．，、。〜ー…', '?!.,,.~~.')


def _そろえる(text):
    """記号の表記ゆれをそろえる。数を正しく数えるため。"""
    return (text or '').translate(_全角から半角)


# 困っている・行き詰まっていることを示す言い方
困りの語 = [
    'できない', 'できません', 'わからない', 'わかりません', '分からない',
    '動かない', '動きません', 'ダメ', 'だめ', '無理', 'エラー', '失敗',
    '直らない', '出ない', '消えた', '壊れ', 'おかしい', 'なぜ', 'なんで', 'どうして',
]

# 急いでいることを示す言い方
急ぎの語 = ['すぐ', '早く', 'はやく', '急い', '至急', '今すぐ', 'とにかく', '直ちに']

# 不満・強い指摘を示す言い方
不満の語 = [
    'まだ', 'ずっと', '何回', 'なんかい', '何度', 'いつまで',
    'ちゃんと', 'きちんと', '問題', 'おかしい', '違う', 'ちがう',
]

# 喜び・満足を示す言い方
喜びの語 = ['ありがとう', 'ありがと', 'よかった', 'いいね', 'すごい', '助かった', 'できた', '直った']

# ためらい・自信の無さを示す言い方
ためらいの語 = ['たぶん', 'かも', 'かな', 'と思う', 'だろうか', 'ちょっと', 'できれば', 'もし']


def read(text):
    """
    書かれた形から、話し方の調子を読む。

    @return dict
        種類   … 'question'（質問）/'request'（依頼）/'point'（指摘）
                 /'agree'（同意）/'statement'（ふつうの言い方）
        強さ   … 0.0〜1.0。記号の重なりと言葉づかいから出す
        気持ち … 読み取れたものの並び。無ければ空
        根拠   … なぜそう読んだか。説明できないものは出さない
    """
    生 = text or ''
    t = _そろえる(生).strip()
    if not t:
        return {'種類': 'statement', '強さ': 0.0, '気持ち': [], '根拠': []}

    低 = t.lower()
    根拠 = []
    気持ち = []

    # --- 記号を数える ---
    # 「!!!」のように重ねるほど強い。これは書き言葉の共通のならわし。
    疑問符 = t.count('?')
    感嘆符 = t.count('!')
    三点 = len(re.findall(r'\.{2,}|・{2,}', t))

    # --- 種類を決める ---
    種類 = 'statement'
    if 疑問符 and 感嘆符:
        # 「なんで動かないの！？」— 問いかけの形をした指摘
        種類 = 'point'
        根拠.append('「?」と「!」が同時に使われている')
    elif 疑問符:
        種類 = 'question'
        根拠.append('「?」で終わっている')
    elif 感嘆符:
        種類 = 'point'
        根拠.append('「!」が使われている')
    elif re.search(r'(して|ください|ほしい|したい|お願い)$', t):
        種類 = 'request'
        根拠.append('依頼の言い方で終わっている')
    elif re.search(r'(か|かな|かね|の)$', t) and len(t) > 2:
        種類 = 'question'
        根拠.append('問いかけの形で終わっている')

    # --- 強さを出す ---
    #
    # 記号の重なりが最も分かりやすい手がかり。
    # 「!」1つと「!!!」3つでは、明らかに調子が違う。
    強さ = 0.0
    if 感嘆符:
        強さ += min(感嘆符, 3) * 0.22
        if 感嘆符 >= 2:
            根拠.append(f'「!」が{感嘆符}つ重ねられている')
    if 疑問符 >= 2:
        強さ += 0.2
        根拠.append(f'「?」が{疑問符}つ重ねられている')

    # 大文字だけの英字や、同じ字の繰り返しも強さを示す
    if re.search(r'(.)\1{2,}', t):
        強さ += 0.1
        根拠.append('同じ字が繰り返されている')

    # --- 気持ちを読む ---
    if any(w in 低 for w in 困りの語):
        気持ち.append('困っている')
        強さ += 0.2
        根拠.append('うまくいっていないことを表す言葉がある')

    if any(w in 低 for w in 急ぎの語):
        気持ち.append('急いでいる')
        強さ += 0.2
        根拠.append('急ぎを表す言葉がある')

    if any(w in 低 for w in 不満の語):
        気持ち.append('納得していない')
        強さ += 0.15
        根拠.append('繰り返しや不足を指す言葉がある')

    if any(w in 低 for w in 喜びの語):
        気持ち.append('よろこんでいる')
        根拠.append('肯定的な言葉がある')

    if any(w in 低 for w in ためらいの語) or 三点:
        気持ち.append('決めかねている')
        if 三点:
            根拠.append('「…」が使われている')
        else:
            根拠.append('ぼかす言い方がある')

    # 「困っている」と「よろこんでいる」が同時に出たら、読み違えている。
    # どちらとも言えないので、両方下ろす。
    if '困っている' in 気持ち and 'よろこんでいる' in 気持ち:
        気持ち = [g for g in 気持ち if g not in ('困っている', 'よろこんでいる')]
        根拠.append('相反する言葉が混ざっており、気持ちは読み取れなかった')

    return {
        '種類': 種類,
        '強さ': round(min(強さ, 1.0), 2),
        '気持ち': 気持ち,
        '根拠': 根拠,
    }


def 応じ方(調子):
    """
    読み取った調子に、どう応じるべきかを返す。

    ここで返すのは「態度」だけで、内容は変えない。
    急かされたからといって、確認を省いて雑にやることはしない。
    それは相手のためにならないため。

    @return dict
        前置き   … 返事の頭に付ける一言。要らなければ空
        手短に   … True なら説明を削って要点だけにする
        先に謝る … True なら、まず受け止める言葉を置く
    """
    気持ち = 調子.get('気持ち') or []
    強さ = 調子.get('強さ') or 0.0

    if '困っている' in 気持ち and 強さ >= 0.3:
        return {
            '前置き': 'うまくいっていない状態ですね。原因から確かめます。',
            '手短に': True,
            '先に謝る': True,
        }

    if '納得していない' in 気持ち and 強さ >= 0.3:
        return {
            '前置き': '同じことが続いていますね。今度は原因を突き止めてから直します。',
            '手短に': True,
            '先に謝る': True,
        }

    if '急いでいる' in 気持ち:
        return {'前置き': '', '手短に': True, '先に謝る': False}

    if '決めかねている' in 気持ち:
        return {
            '前置き': '決めかねている場合は、分かっていることだけ先にお伝えします。',
            '手短に': False,
            '先に謝る': False,
        }

    if 'よろこんでいる' in 気持ち:
        return {'前置き': '', '手短に': False, '先に謝る': False}

    return {'前置き': '', '手短に': False, '先に謝る': False}
