def チーム言葉を除く(text):
    """「チームで〜して」から、頼み言葉だけを取り除いて、本来の頼みにする。"""
    t = _チーム言葉.sub(' ', text or '')
    return re.sub(r'\s+', ' ', t).strip(' 、,　')


_持ち主 = {作業: 名 for 名, 作業たち in 専任の表.items() for 作業 in 作業たち}


def 担当を決める(作業):
    """この作業を専任で受け持つ係の名前。いなければ None。"""
    return _持ち主.get(作業)


def _値たち(材料):
    """手に渡す中身のうち、別の手と「同じものを指している」かを見るための値。"""
    出 = set()
    for v in (材料 or {}).values():
        s = str(v).strip()
        if len(s) >= 2:
            出.add(s)
    return 出


def 待ち先を決める(steps):
    """
    手ごとに、「この手が終わるのを待つ手」の番号（0始まり）を決める。
    同じ係の手どうしの順番は、実行する側が守る（ここには入れない）。
    """
    待ち = []
    前の画面手 = None
    for j, 手 in enumerate(steps):
        作業 = 手.get('action')
        担当 = 担当を決める(作業)
        待つ = set()
        値 = _値たち(手.get('params'))

        for i in range(j):
            前 = steps[i]
            if 担当を決める(前.get('action')) == 担当:
                continue    # 同じ係の順番は、係の中で守る
            # 同じ名前・同じ中身を使う手は、前の手が終わってから（前の結果に頼っているため）
            if 値 & _値たち(前.get('params')):
                待つ.add(i)

        # 画面を切り替える手は、前の画面の手が終わってから（最後に見せるものを、頼まれた順にするため）
        if 作業 in 画面へ移る:
            if 前の画面手 is not None:
                待つ.add(前の画面手)
            前の画面手 = j

        # 戻しにくい手は、前の手がすべて終わってから
        if 手.get('confirm'):
            待つ |= set(range(j))

        待ち.append(sorted(待つ - {j}))
    return 待ち


def 並べる(steps):
    """
    手を、同時に進められる段（波）に並べる。人に見せる「第何波」の元。
    波 = 待つ手の最も遅い波の次。同じ係の手は、前の手の次の波以降。
    """
    待ち = 待ち先を決める(steps)
    波 = []
    最後の波 = {}      # 係の名前 → その係の、直前の手の波
    for j, 手 in enumerate(steps):
        係名 = 担当を決める(手.get('action')) or '?'
        基 = max([波[i] for i in 待ち[j]] + [最後の波.get(係名, -1)] + [-1]) + 1
        波.append(基)
        最後の波[係名] = 基
    return 波, 待ち


def チームにする(段):
    """
    ふつうの段取り（手の並び）に、担当と待ち先を付けて、チームの段取りにする。

    @param 段   {'label', 'summary', 'steps': [...]}
    @return    同じ形に 'team' を足したもの。担当のいない手があるときは None（チームにしない）。
    """
    steps = [dict(h) for h in (段 or {}).get('steps', [])]
    if not steps:
        return None

    担当たち = []
    for h in steps:
        c = 担当を決める(h.get('action'))
        if not c:
            return None    # 受け持ち手のいない作業は、チームでは動かさない（これまでどおり一人で）
        担当たち.append(c)

    波たち, 待ち = 並べる(steps)
    for j, h in enumerate(steps):
        h['agent'] = 担当たち[j]
        h['agent_name'] = 担当たち[j]
        h['wait'] = 待ち[j]
        h['wave'] = 波たち[j]

    使う = []
    for c in 担当たち:
        if c not in 使う:
            使う.append(c)
    同時に動く = len(使う) >= 2 and max(波たち) < len(steps) - 1

    絵の表 = {x['名前']: x for x in 一覧()}
    new = dict(段)
    new['steps'] = steps
    new['team'] = {
        'agents': [{'名前': n, '絵': 絵の表.get(n, {}).get('絵', '🙂'), '得意': 絵の表.get(n, {}).get('得意', '')} for n in 使う],
        'commander': 司令,
        'checker': '点検係',
        '波の数': (max(波たち) + 1) if 波たち else 0,
        '同時に動く': bool(同時に動く),
    }
    return new


def 受け持ちの文(段):
    """人に見せる、担当の一覧（会話の返事に足す）。"""
    if not 段 or 'team' not in 段:
        return []
    文 = ['チームで手分けします:']
    for i, h in enumerate(段['steps'], 1):
        文.append(f'{i}. {h["agent_name"]}　{h["why"]}')
    t = 段['team']
    if t['同時に動く']:
        文.append(f'（{len(t["agents"])}つの係が同時に進みます。前の結果に頼る手は、その手が終わるのを待ちます）')
    文.append('点検係が、できた結果を実際に確かめます。')
    return 文


def 一手だけの段取り(text, 拾う):
    """
    「チームで在庫を見て」のように、チームを名指しされた一つの頼み。
    頼みを分ける.py は二つ未満だと動かないので、ここで一手の段取りにする。
    決まらなければ None。
    """
    import 頼みを分ける as K
    文 = チーム言葉を除く(text)
    if not 文:
        return None
    技, 確か = K._技を決める(文)
    if not 技 or 確か < 0.5 or 技.name in K._自動に入れない:
        return None
    材料 = K._材料を拾う(技, 文, {}, 拾う)
    return {
        'name': 'team-one', 'label': f'チームの作業（{技.label}）',
        'summary': 'チームの係に、この頼みを任せます。',
        'steps': [{'action': 技.action, 'why': f'{技.label}（「{文}」）', 'params': 材料, 'confirm': False}],
    }
