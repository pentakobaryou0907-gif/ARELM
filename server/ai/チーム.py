"""
チーム ― 一つの頼みを、係ごとに手分けして進める（マルチエージェントの「実際に動かす」部分）

なぜこれが要るのか:
    係たち.py は、頼みを「どの係が、どう働くか」まで決められる（一人で・同時に・相談して・順に）。
    だが実際に動くのは「相談して」だけで、「同時に」「順に」は、決めるだけで動かす先が無かった。
    つまり、マルチエージェントは途中まで作ってあって、手分けして作業することは、まだできなかった。

    ここで、その先を作る。
      ・司令    … 頼みを分け、係に割り振り、結果を一つの報告にまとめる（自分では作業しない）
      ・係たち  … 係たち.py の係が、それぞれ専任の作業を、同時に進める
      ・点検係  … ほかの係の結果を、あとから実際に確かめる（言った通りに、データが残っているか）

ここでの決まり:
  1. 係が受け持てるのは、skills.py にある、実際に動く作業だけ。
     受け持ち手のいない技能が出たら、テストが落ちる（作ったのに誰も使えない、を防ぐ）。
  2. 同じ係の手は、頼まれた順に一つずつ。違う係の手だけが、同時に進む。
  3. 前の手の結果に頼る手（同じ商品名を使う等）は、その手が終わるのを待つ。
     待たずに進めて、まだ無いものを探すと、嘘の結果になるため。
  4. 画面を切り替える手は、一つずつ、頼まれた順に。同時に切り替えると、どこを見せたのか分からなくなる。
  5. 失敗が出たら、どの係も新しい手を始めない。残りを飛ばして「終わりました」とは言わない。
  6. 消す・外へ送る・公開する、は、チームでも行わない（頼みを分ける.py と同じ決まり）。

外部へは一切問い合わせない。すべてこの端末の中で完結する。
"""

