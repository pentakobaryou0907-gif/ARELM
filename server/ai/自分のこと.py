def find(text):
    """
    このツール自身について聞かれているかを見る。

    「なんで〜できないの」「〜は使えるの」のような、
    こちらの作りを尋ねる形かどうかで判断する。
    ただの単語だけでは反応しない。
    「画像」と言われただけで説明を始めたら、話が進まないため。

    @return (説明, 確信) または (None, 0.0)
    """
    if not text:
        return None, 0.0

    低 = text.lower()

    # こちらの作りを尋ねている形かを見る。
    #
    # 最初は「なんで」「どうして」だけを見ていたが、
    # 「動画は作れる？」「透かしは入る？」のような
    # ふつうの聞き方に反応できなかった。
    #
    # そこで、疑問符と、問いかけの語尾も手がかりに加えてある。
    尋ねる形 = [
        'なんで', 'なぜ', 'どうして', 'できない', 'できる', 'できます',
        '使える', '使えます', '対応', 'ある', 'あります', '入る', '入り',
        '仕組み', 'について', 'どうなって', '教えて', '分かる', 'わかる',
        'なの', 'のか', 'ですか', 'かな',
    ]

    尋ねている = (
        text.strip().endswith(('？', '?'))
        or any(w in 低 for w in 尋ねる形)
    )
    if not 尋ねている:
        return None, 0.0

    for s in 説明たち:
        if s.答え is None:
            continue
        当たり = [w for w in s.語 if w in 低]
        if 当たり:
            return s, min(1.0, 0.6 + len(当たり) * 0.15)

    return None, 0.0
