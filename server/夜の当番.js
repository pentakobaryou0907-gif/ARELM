/**
 * 夜の当番 ― 寝ている間も、決まった点検を進めて、朝に報告する
 *
 * なぜこれが作れるのか:
 *   「毎日の自動チェック」（js/modules/毎日の自動チェック.js）は、こう書いてある。
 *   「商品のデータは、いまこのブラウザの中にしか無い。サーバー側で動かしても、商品を見られず
 *    意味が無い。だから、画面が開いている間だけ効く。閉じているときは鳴らない」
 *   いまは、端末間の同期（js/core/sync.js）で、同じデータがサーバー側（sync_store.json）にもある。
 *   だから、画面を閉じた夜でも、サーバーが自分でデータを見て、点検できる。
 *
 * やること（係ごと。チームの係たち.py と同じ顔ぶれ）:
 *   在庫係   … 要補充・値段の入っていない商品・同じ名前の商品
 *   段取り係 … 期限の過ぎたやること・今日の分
 *   作り方係 … 制作の進捗（公開前チェック済みで、あなたの「公開」待ちのもの）
 *   記録係   … バックアップの新しさ（古ければ取る）・永久の記憶の状況
 *   点検係   … AIエンジンの応答・空き容量・合言葉・許した端末の期限・「どこでも」の公開
 *   司令     … まとめて、「要確認」だけを先頭に出す
 *
 * 決まり:
 *   ・読むだけ。直さない・消さない・外へ送らない。書くのは、朝の報告（追記のみ）と、バックアップだけ。
 *   ・異常が無いときは、静かにする（毎日「異常なし」を出し続けると、見なくなる）。
 *   ・SUZURIの「商品を公開する」は押さない。公開待ちのものは、「あなたの操作待ち」と書くだけ。
 *   ・Macが眠っていて時刻を過ぎたときは、起きてから実行する（実行した時刻と、遅れたことを書く）。
 *
 * 外部へは一切問い合わせない。
 */

const fs = require('fs');
const path = require('path');

const 既定の設定 = { 有効: true, 時刻: '03:30', 通知: true, 通知の時刻: '08:00' };
const 見張りの間隔 = 5 * 60 * 1000;
const 遅れと見なす分 = 30;

/* ==========================================================
   読み書き
   ========================================================== */

function 設定を読む(置き場) {
    try {
        const s = JSON.parse(fs.readFileSync(path.join(置き場, '夜の当番.json'), 'utf8'));
        return {
            有効: s.有効 !== false,
            時刻: /^\d{2}:\d{2}$/.test(s.時刻 || '') ? s.時刻 : 既定の設定.時刻,
            通知: s.通知 !== false,
            通知の時刻: /^\d{2}:\d{2}$/.test(s.通知の時刻 || '') ? s.通知の時刻 : 既定の設定.通知の時刻,
        };
    } catch { return { ...既定の設定 }; }
}

function 設定を書く(置き場, 新) {
    const 今 = 設定を読む(置き場);
    const 次 = {
        有効: 新.有効 === undefined ? 今.有効 : 新.有効 === true,
        時刻: /^\d{2}:\d{2}$/.test(新.時刻 || '') ? 新.時刻 : 今.時刻,
        通知: 新.通知 === undefined ? 今.通知 : 新.通知 === true,
        通知の時刻: /^\d{2}:\d{2}$/.test(新.通知の時刻 || '') ? 新.通知の時刻 : 今.通知の時刻,
    };
    fs.mkdirSync(置き場, { recursive: true });
    fs.writeFileSync(path.join(置き場, '夜の当番.json'), JSON.stringify(次, null, 2));
    return 次;
}

/** 報告は追記だけ（消さない）。読むのは、新しい方から数件。 */
function 報告を読む(置き場, 件数 = 7) {
    try {
        const 行 = fs.readFileSync(path.join(置き場, '朝の報告.jsonl'), 'utf8').split('\n').filter(Boolean);
        return 行.slice(-件数).map((x) => { try { return JSON.parse(x); } catch { return null; } }).filter(Boolean).reverse();
    } catch { return []; }
}

function 報告を足す(置き場, 報告) {
    fs.mkdirSync(置き場, { recursive: true });
    fs.appendFileSync(path.join(置き場, '朝の報告.jsonl'), JSON.stringify(報告) + '\n');
}

function 状態を読む(置き場) {
    try { return JSON.parse(fs.readFileSync(path.join(置き場, '夜の当番の状態.json'), 'utf8')); } catch { return {}; }
}
function 状態を書く(置き場, 差分) {
    fs.mkdirSync(置き場, { recursive: true });
    fs.writeFileSync(path.join(置き場, '夜の当番の状態.json'), JSON.stringify({ ...状態を読む(置き場), ...差分 }, null, 2));
}

/* ==========================================================
   点検（純粋な関数。データを渡すと、係ごとの結果を返す）
   ========================================================== */

function 同期の配列(同期, 鍵) {
    try {
        const v = 同期 && 同期[鍵] && JSON.parse(同期[鍵].value);
        return Array.isArray(v) ? v : null;
    } catch { return null; }
}

const 要確認 = (文) => ({ 重さ: '要確認', 文 });
const お知らせ = (文) => ({ 重さ: 'お知らせ', 文 });
const 良好 = (文) => ({ 重さ: '良好', 文 });

function 名前を並べる(一覧, 最大 = 5) {
    const 名 = 一覧.slice(0, 最大).map((p) => p.name || p.title || '（名前なし）');
    return 名.join('、') + (一覧.length > 最大 ? ` ほか${一覧.length - 最大}件` : '');
}

function 在庫係の点検(同期) {
    const 商品 = 同期の配列(同期, 'products');
    if (!商品) return [お知らせ('商品のデータを、まだ読み込んでいません')];
    const 結果 = [];
    const 少ない = 商品.filter((p) => (Number(p.quantity ?? p.stock ?? 0) || 0) <= (Number(p.reorderLevel) || 5));
    if (少ない.length) 結果.push(要確認(`在庫が少ない商品が${少ない.length}件あります: ${名前を並べる(少ない)}`));
    const 値なし = 商品.filter((p) => !(Number(p.price) > 0));
    if (値なし.length) 結果.push(お知らせ(`値段が入っていない商品が${値なし.length}件あります: ${名前を並べる(値なし)}`));
    const 数 = new Map();
    商品.forEach((p) => { const k = String(p.name || '').trim(); if (k) 数.set(k, (数.get(k) || 0) + 1); });
    const 同名 = [...数].filter(([, n]) => n > 1).map(([k]) => ({ name: k }));
    if (同名.length) 結果.push(お知らせ(`同じ名前の商品があります: ${名前を並べる(同名)}（重複していないか見てください）`));
    if (!結果.length) 結果.push(良好(`商品${商品.length}件、補充が要るものはありません`));
    return 結果;
}

function 段取り係の点検(同期, 今日) {
    const やること = 同期の配列(同期, 'areglm_tasks');
    if (!やること) return [お知らせ('やることのデータを、まだ読み込んでいません')];
    const 未 = やること.filter((t) => !t.done);
    const 過ぎた = 未.filter((t) => t.due && String(t.due).slice(0, 10) < 今日);
    const 今日の = 未.filter((t) => t.due && String(t.due).slice(0, 10) === 今日);
    const 結果 = [];
    if (過ぎた.length) 結果.push(要確認(`期限が過ぎたやることが${過ぎた.length}件あります: ${名前を並べる(過ぎた)}`));
    if (今日の.length) 結果.push(お知らせ(`今日のやること${今日の.length}件: ${名前を並べる(今日の)}`));
    if (!結果.length) 結果.push(良好(`未完了のやること${未.length}件、期限の過ぎたものはありません`));
    return 結果;
}

function 作り方係の点検(同期) {
    const 記録 = 同期の配列(同期, 'areglm_production_log');
    if (!記録) return [良好('制作の進捗は、まだ記録がありません')];
    const 公開可 = 記録.filter((x) => x.状態 === '公開可');
    const 案 = 記録.filter((x) => x.状態 === '案');
    const 結果 = [];
    if (公開可.length) {
        結果.push(お知らせ(`公開前チェック済みで、あなたの「公開」操作を待っているものが${公開可.length}件あります: ${名前を並べる(公開可)}（SUZURIの公開ボタンは、あなたが押します）`));
    }
    if (案.length) 結果.push(お知らせ(`制作の「案」が${案.length}件あります`));
    if (!結果.length) 結果.push(良好('制作の進捗に、待っているものはありません'));
    return 結果;
}

function 記録係の点検(入力) {
    const { バックアップの状態, 夜に取った, 永久の記憶の状況 } = 入力;
    const 結果 = [];
    if (夜に取った && 夜に取った.ok) 結果.push(お知らせ(`バックアップを取りました（${夜に取った.ファイル数 ?? '?'}ファイル）`));
    else if (夜に取った && !夜に取った.ok) 結果.push(要確認(`バックアップを取れませんでした: ${夜に取った.訳 || '理由は分かりません'}`));
    else if (バックアップの状態 && バックアップの状態.ok && バックアップの状態.古すぎる) 結果.push(要確認('2日以上、バックアップが取れていません'));
    else if (バックアップの状態 && バックアップの状態.最新) 結果.push(良好('バックアップは新しいです'));
    if (永久の記憶の状況 && 永久の記憶の状況.ok === false) 結果.push(要確認('永久の記憶の状況を読めません'));
    return 結果.length ? 結果 : [お知らせ('バックアップの状況を読めませんでした')];
}

function 点検係の点検(入力) {
    const { AIは動いているか, 空きGB, 合言葉で入れる, 近く切れる端末, どこでも, 同期を読めるか, 入場の知らせ, 倉庫の最後 } = 入力;
    const 結果 = [];
    if (AIは動いているか === false) 結果.push(要確認('自作AIエンジンが応答していません'));
    if (同期を読めるか === false) 結果.push(要確認('端末間の同期のデータ（sync_store.json）を読めません'));
    if (typeof 空きGB === 'number' && 空きGB < 5) 結果.push(要確認(`ディスクの空きが少なくなっています（約${空きGB.toFixed(1)}GB）`));
    // 合言葉はやめた（2026-10-09。入れるのは、Macで許可した端末だけ）。前の合言葉の道が開いたままなら、知らせる
    if (合言葉で入れる) 結果.push(要確認('前の合言葉でも入れる設定が残っています（合言葉を知っている人は、Macの許可なしで入れます）'));
    if ((近く切れる端末 || []).length) 結果.push(お知らせ(`7日以内に、入る許可が切れる端末があります: ${近く切れる端末.join('、')}（切れたら、もう一度許可します）`));
    if (どこでも && どこでも.許している && !どこでも.公開中) 結果.push(要確認('「どこでも使う」を入にしていますが、いま外から開けない状態です（設定で、もう一度「使えるようにする」）'));
    // だれかが入ろうとした跡（間違いが続く・締め出し・見慣れない住所）。本人の要望「知らないログインはすぐ知らせて」
    (入場の知らせ || []).forEach((文) => 結果.push(要確認(`入場の記録: ${文}（設定の「入場の記録」で、いつ・どこからかを見られます）`)));
    if (倉庫の最後 && 倉庫の最後.ok === false) 結果.push(要確認(`同期の倉庫（GitHub）と混ぜられませんでした: ${倉庫の最後.訳 || '理由は分かりません'}`));
    if (!結果.length) 結果.push(良好('動作は正常です（AIエンジン・空き容量・入口・同期）'));
    return 結果;
}

const 係たちの絵 = { 在庫係: '📦', 段取り係: '🗓', 作り方係: '🎨', 記録係: '📒', 点検係: '🛡' };

/**
 * 点検して、係ごとの結果と、司令のまとめを返す。
 * @param {object} 入力 { 同期, 今日, バックアップの状態, 夜に取った, 永久の記憶の状況,
 *                        AIは動いているか, 空きGB, 合言葉で入れる, 近く切れる端末, どこでも, 同期を読めるか,
 *                        入場の知らせ, 倉庫の最後 }
 */
function 点検する(入力) {
    const 係ごと = [
        ['在庫係', 在庫係の点検(入力.同期)],
        ['段取り係', 段取り係の点検(入力.同期, 入力.今日)],
        ['作り方係', 作り方係の点検(入力.同期)],
        ['記録係', 記録係の点検(入力)],
        ['点検係', 点検係の点検(入力)],
    ].map(([係, 件]) => ({ 係, 絵: 係たちの絵[係] || '🙂', 件 }));

    const 要確認たち = [];
    係ごと.forEach((k) => k.件.filter((x) => x.重さ === '要確認').forEach((x) => 要確認たち.push({ 係: k.係, 文: x.文 })));

    let 要約;
    if (要確認たち.length) {
        const 係名 = [...new Set(要確認たち.map((x) => x.係))].join('・');
        要約 = `要確認 ${要確認たち.length}件（${係名}）`;
    } else {
        要約 = '要確認はありません。異常は見つかりませんでした';
    }
    return { 係ごと, 要確認: 要確認たち, 要約 };
}

/* ==========================================================
   実行（データを集めて、点検して、報告を残す）
   ========================================================== */

/**
 * @param {object} 道具  index.js から渡される、読む・取るための関数たち
 *   置き場, 同期の場所, バックアップ, 永久の記憶, AIは動いているか(), 門番の設定(), 他の端末を許しているか(), どこでも()
 */
async function 実行する(道具, 理由 = '予定どおり', 予定の時刻 = null) {
    const 始め = Date.now();
    const 今日 = new Date().toISOString().slice(0, 10);

    // 同期のデータが「まだ無い」（導入直後）のは異常ではない。「あるのに壊れている」ときだけ、読めないと報告する。
    let 同期 = {}; let 同期を読めるか = true;
    try {
        if (fs.existsSync(道具.同期の場所)) 同期 = JSON.parse(fs.readFileSync(道具.同期の場所, 'utf8'));
    } catch { 同期を読めるか = false; }

    // バックアップは、古いときだけ取る（毎日の控えが動いていれば、取らない）
    let バックアップの状態 = null; let 夜に取った = null;
    try {
        バックアップの状態 = 道具.バックアップ.状態();
        if (バックアップの状態.ok && (バックアップの状態.古すぎる || !バックアップの状態.最新
            || (Date.now() - new Date(バックアップの状態.最新.作成).getTime()) > 24 * 3600000)) {
            夜に取った = 道具.バックアップ.控えを取る('夜の当番');
        }
    } catch (e) { 夜に取った = { ok: false, 訳: e.message }; }

    let 永久の記憶の状況 = null;
    try { 永久の記憶の状況 = 道具.永久の記憶.状況(); } catch { 永久の記憶の状況 = { ok: false }; }

    let AIは動いているか = null;
    try { AIは動いているか = await 道具.AIは動いているか(); } catch { AIは動いているか = false; }

    let 空きGB = null;
    try { const s = fs.statfsSync(道具.置き場); 空きGB = (s.bavail * s.bsize) / 1e9; } catch { /* 取れなければ、見ない */ }

    let 門 = {};
    try { 門 = 道具.門番の設定() || {}; } catch { /* 読めなければ、空 */ }
    const 合言葉で入れる = !!(道具.他の端末を許しているか() && 門.合言葉で入れる === true && 門.合言葉);
    const 近く切れる端末 = (門.端末 || [])
        .filter((d) => { const 残り = new Date(d.期限).getTime() - Date.now(); return 残り > 0 && 残り < 7 * 86400000; })
        .map((d) => d.名前);

    let どこでも = null;
    try { どこでも = await 道具.どこでも(); } catch { /* 読めなければ、見ない */ }

    let 入場の知らせ = [];
    try { 入場の知らせ = (道具.入場の知らせ && 道具.入場の知らせ()) || []; } catch { /* 読めなければ、見ない */ }
    let 倉庫の最後 = null;
    try { 倉庫の最後 = 道具.倉庫の最後 ? 道具.倉庫の最後() : null; } catch { /* 読めなければ、見ない */ }

    const 結果 = 点検する({
        同期, 今日, バックアップの状態, 夜に取った, 永久の記憶の状況,
        AIは動いているか, 空きGB, 合言葉で入れる, 近く切れる端末, どこでも, 同期を読めるか,
        入場の知らせ, 倉庫の最後,
    });

    const 報告 = {
        id: `n_${始め}`,
        実行時刻: new Date(始め).toISOString(),
        予定の時刻: 予定の時刻,
        理由,
        遅れて実行した: 理由 === '遅れて（眠っていたため）',
        所要ms: Date.now() - 始め,
        ...結果,
    };
    報告を足す(道具.置き場, 報告);
    return 報告;
}

/* ==========================================================
   見張り（予定の時刻に実行・朝に知らせる）
   ========================================================== */

function その日の時刻(時刻, 基準 = new Date()) {
    const [h, m] = 時刻.split(':').map(Number);
    const d = new Date(基準);
    d.setHours(h, m, 0, 0);
    return d;
}

/** いま、実行すべきか。予定を過ぎていて、その予定の分がまだ実行されていなければ、実行する。 */
function 実行すべきか(設定, 最後の報告, いま = new Date()) {
    if (!設定.有効) return null;
    const 予定 = その日の時刻(設定.時刻, いま);
    if (いま < 予定) return null;
    const 最後 = 最後の報告 ? new Date(最後の報告.実行時刻) : null;
    if (最後 && 最後 >= 予定) return null;
    const 遅れ分 = (いま - 予定) / 60000;
    return { 予定の時刻: 予定.toISOString(), 理由: 遅れ分 > 遅れと見なす分 ? '遅れて（眠っていたため）' : '予定どおり' };
}

/** 朝の通知をするか。要確認があり、予定の通知時刻を過ぎ、まだその報告で知らせていないとき。 */
function 通知すべきか(設定, 最後の報告, 状態, いま = new Date()) {
    if (!設定.有効 || !設定.通知 || !最後の報告) return false;
    if (!最後の報告.要確認 || !最後の報告.要確認.length) return false;
    if (状態.最後に知らせた報告 === 最後の報告.id) return false;
    // その日の通知時刻を過ぎていて、報告が今日（朝の通知時刻より前）に作られたものか、昨夜〜今朝のもの
    if (いま < その日の時刻(設定.通知の時刻, いま)) return false;
    const 経過時間 = (いま - new Date(最後の報告.実行時刻)) / 3600000;
    return 経過時間 < 20;
}

function macに知らせる(文) {
    if (process.platform !== 'darwin') return false;
    try {
        const 安全 = String(文).replace(/[\\"]/g, ' ').replace(/[\r\n]+/g, ' ').slice(0, 200);
        require('child_process').execFile('/usr/bin/osascript',
            ['-e', `display notification "${安全}" with title "ARELM 朝の報告"`], () => { /* 出せなくても、報告は残っている */ });
        return true;
    } catch { return false; }
}

function 見張りを始める(道具) {
    let 実行中 = false;
    const 一回 = async () => {
        if (実行中) return;
        try {
            実行中 = true;
            const 設定 = 設定を読む(道具.置き場);
            const 最後 = 報告を読む(道具.置き場, 1)[0] || null;
            const 時 = 実行すべきか(設定, 最後);
            if (時) {
                const 報告 = await 実行する(道具, 時.理由, 時.予定の時刻);
                console.log(`[夜の当番] ${報告.要約}（${報告.理由}）`);
            }
            const 今の最後 = 報告を読む(道具.置き場, 1)[0] || null;
            if (通知すべきか(設定, 今の最後, 状態を読む(道具.置き場))) {
                macに知らせる(`${今の最後.要約}。ARELMのホームで確かめてください`);
                状態を書く(道具.置き場, { 最後に知らせた報告: 今の最後.id });
            }
        } catch (e) {
            console.warn('[夜の当番] 失敗しました:', e.message);
        } finally { 実行中 = false; }
    };
    const 札 = setInterval(一回, 見張りの間隔);
    札.unref?.();
    setTimeout(一回, 20000).unref?.();   // 起動の少しあとにも、一度見る（眠りから覚めた直後の取りこぼし防止）
    return 札;
}

