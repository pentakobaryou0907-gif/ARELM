/** フォルダを再帰的にたどり、対象ファイルを集める */
function ファイルを集める(ROOT) {
    const 集めた = [];

    function 潜る(道) {
        let 中身;
        try {
            中身 = fs.readdirSync(道, { withFileTypes: true });
        } catch {
            return;
        }
        for (const x of 中身) {
            if (見ないフォルダ.has(x.name)) continue;
            const 次 = path.join(道, x.name);
            if (x.isDirectory()) { 潜る(次); continue; }
            if (見る拡張子.has(path.extname(x.name))) 集めた.push(次);
        }
    }

    見るフォルダ.forEach((f) => 潜る(path.join(ROOT, f)));
    return 集めた;
}

/** 1ファイルを、決めた項目ぜんぶで当たるか見る */
function ファイルを点検する(道, 中身) {
    const 見つかった = [];
    const 行たち = 中身.split('\n');

    行たち.forEach((行, i) => {
        // コメント行は誤検出のもとになりやすいので、明らかな行コメントは飛ばす
        const 見る行 = 行.replace(/^\s*\/\/.*/, '');
        if (!見る行.trim()) return;

        点検の項目.forEach((項目) => {
            if (項目.当たり.test(見る行)) {
                見つかった.push({
                    ルール: 項目.id,
                    名: 項目.名,
                    重さ: 項目.重さ,
                    説: 項目.説,
                    直し方: 項目.直し方,
                    行番号: i + 1,
                    行の中身: 行.trim().slice(0, 160),
                });
            }
        });
    });

    return 見つかった;
}

/**
 * このツール自身のコードを点検する。
 *
 * @param {string} ROOT このツールのルートフォルダ
 * @returns {{ok:true, 見た数:number, 見つかった数:number, ファイルごと:object[]}}
 */
function 点検を行う(ROOT) {
    const 対象 = ファイルを集める(ROOT);
    const ファイルごと = [];
    let 見つかった数 = 0;

    対象.forEach((道) => {
        let 中身;
        try {
            中身 = fs.readFileSync(道, 'utf-8');
        } catch {
            return;
        }
        const 見つかった = ファイルを点検する(道, 中身);
        if (見つかった.length) {
            見つかった数 += 見つかった.length;
            ファイルごと.push({
                道: path.relative(ROOT, 道),
                件数: 見つかった.length,
                見つかった,
            });
        }
    });

    // 重い方から見えるように並べる
    const 重さ順 = { 高: 0, 中: 1, 低: 2 };
    ファイルごと.sort((a, b) => a.道.localeCompare(b.道));
    ファイルごと.forEach((f) => {
        f.見つかった.sort((a, b) => (重さ順[a.重さ] - 重さ順[b.重さ]) || (a.行番号 - b.行番号));
    });

    return {
        ok: true,
        見た数: 対象.length,
        見つかった数,
        ファイルごと,
        点検した日: new Date().toISOString(),
    };
}

module.exports = { 点検を行う, 点検の項目 };
