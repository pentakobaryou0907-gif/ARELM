/**
 * コードの安全点検（自分のコードだけを見る、防御専用の静的解析）
 *
 * なぜこれが要るのか:
 *
 *   「攻撃コードを作れるAI」ではなく、
 *   <b>このツール自身のコードに危ういところがないか</b>を見つけて知らせる、
 *   守り専用の仕組みが欲しいという話だった。
 *
 *   外部のサービスへコードを送るような仕組み（GoogleColabやHuggingFace等）は使わない。
 *   このNodeサーバーには、もともとこのツール自身のファイルを読む権限がある。
 *   その範囲内だけで完結させれば、外へ何も出さずに済む。
 *
 * 見るもの・見ないもの:
 *
 *   ・<b>見るのは、このツール自身のフォルダの中だけ。</b>
 *     ROOT の外には出ない。外部URLも、他人のIPアドレスも扱わない。
 *
 *   ・<b>やるのは「見つけて知らせる」まで。</b>
 *     自動で書き換えたりはしない。直すかどうかは人が決める。
 *
 *   ・<b>攻撃コードは作らない。</b>
 *     見つけた弱点をどう直すかの<b>提案</b>はするが、
 *     それを悪用する手順は書かない。
 *
 * 正直に書いておく:
 *   これは正規表現によるパターン一致であって、
 *   本格的な静的解析ツール（Semgrep等）ほどの精度はない。
 *   見つかったものは<b>疑わしい候補</b>であって、確定した欠陥ではない。
 *   誤検出（本当は問題ない箇所を拾う）もありうる。
 */

