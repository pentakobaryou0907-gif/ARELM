/**
 * 保存したものを読み書きする、共通の入口
 *
 * なぜこれを作ったのか:
 *   同じ「読む」という関数が、二つのファイルに別々に書かれていた。
 *   中身は同じだが、後から読み込まれたほうが前を上書きしていた。
 *
 *   いまは中身が同じなので害は出ていない。
 *   だが片方だけを直したとき、直したはずの側が
 *   もう片方に上書きされて元に戻る——という起き方をする。
 *   気づきにくい壊れ方なので、一か所にまとめる。
 *
 * 名前の衝突は、検査（tools/static-check.js）で見つけた。
 * 日本語を含む名前を検査が途中で切っていたため、
 * それまで見逃されていた。
 *
 * 「一覧を読む」ではなく「蓄えを読む」にしてあるのは、
 * 保管庫（library.js）に先に「一覧を読む」があったため。
 * 同じ名前にしたら、あちらを黙って上書きして、
 * 保管庫が壊れていた。実際に一度そうなった。
 */

/**
 * 並びとして読む。
 * 壊れていたり、並びでなかったら、空の並びを返す。
 */
function 蓄えを読む(鍵) {
    try {
        const r = JSON.parse(localStorage.getItem(鍵) || '[]');
        return Array.isArray(r) ? r : [];
    } catch {
        return [];
    }
}

/** 並びとして書く */
function 蓄えを書く(鍵, 中身) {
    localStorage.setItem(鍵, JSON.stringify(中身));
}

window.蓄えを読む = 蓄えを読む;
window.蓄えを書く = 蓄えを書く;
