/**
 * ブランドの歴史と理念を、資料からまとめる
 *
 * なぜ作り直すのか:
 *
 *   前の仕組みは「説得力のあるブランドヒストリーを考えて」と頼み、
 *   <b>創業年まで推定させていた</b>。
 *
 *   それは、ありもしない歴史を作ることになる。
 *   あなたの決まりに「事実でないことを、事実のように言わない」がある。
 *   真正面から反していた。
 *
 *   さらに、ロゴの絵を外から取ってきていた。
 *   「外へ送らない」という決まりにも反していた。
 *
 * どう変えるのか:
 *
 *   <b>作らない。まとめる。</b>
 *
 *   ・自分のブランドなら、あなたが入れた資料から組み立てる。
 *     どの資料から取ったかを、必ず添える。
 *
 *   ・よそのブランドなら、事実だけを記録する。
 *     創業年は、分かっているものだけ。
 *     分からないものは空のままにする。埋めると嘘になる。
 *
 *   まとめたものは、そのまま使える下書きになる。
 *   作り話より、自分の資料から出てきた言葉のほうが、
 *   あとで読み返したときに使える。
 *
 * すべてこの端末の中だけで動きます。外部へは一切送りません。
 */

/**
 * 資料から、そのブランドについて書かれたところを集める。
 */
async function 資料から集める(名前) {
    if (!名前) return { ok: false, 訳: 'ブランド名が要ります' };

    try {
        const r = await fetch('/api/ai-local/chat', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                text: `${名前}について`,
                session_id: 'brand-' + Date.now(),
            }),
        });
        const d = await r.json();

        // 答えの中に、そのブランド名が出てくるかを見る。
        //
        // 「存在しないブランドXYZ」に対して、
        // SNSの利用者数の話が返っていた。
        // 資料の中で、たまたま近いと判断された文が出たため。
        //
        // <b>そのブランドについて書かれていない文を、
        // そのブランドの歴史として出すのは、作り話と変わらない。</b>
        //
        // 名前が一度も出てこないなら、それは別の話。
        const 素の名 = String(名前).split(/[（(]/)[0].trim();
        const 名前が出てくる = (d.answer || '').includes(素の名)
            || (d.answer || '').toLowerCase().includes(素の名.toLowerCase());

        if (!d.ok || !名前が出てくる
            || /まだ分かりません|見つかりません/.test(d.answer || '')) {
            return {
                ok: false,
                訳: `「${名前}」について書かれた資料が見つかりませんでした。`,
                資料なし: true,
            };
        }

        return { ok: true, 中身: d.answer, 出どころ: d.sources || [] };
    } catch (e) {
        return { ok: false, 訳: '資料を読めませんでした: ' + e.message };
    }
}

/**
 * 集めた文から、理念らしいところと歴史らしいところを分ける。
 *
 * 分ける手がかりは、書かれている言葉そのもの。
 * <b>無い部分は、無いままにする。</b>
 * それらしく埋めると、それは作り話になる。
 */
function 理念と歴史に分ける(文) {
    const 行たち = String(文 || '')
        .split('\n')
        .map((x) => x.replace(/^[\s・]*(\[[^\]]*\])?\s*/, '').trim())
        .filter((x) => x.length > 8);

    const 理念の手がかり = /理念|想い|思い|大切|信じ|めざ|目指|ありたい|たい$|価値|なぜ/;
    const 歴史の手がかり = /年|創業|設立|始ま|きっかけ|もともと|当時|以来|経緯/;

    const 理念 = 行たち.filter((x) => 理念の手がかり.test(x));
    const 歴史 = 行たち.filter((x) => 歴史の手がかり.test(x) && !理念.includes(x));

    return {
        理念: 理念.length ? 理念[0] : '',
        歴史: 歴史.length ? 歴史.slice(0, 3).join(' ') : '',
        そのほか: 行たち.filter((x) => !理念.includes(x) && !歴史.includes(x)).slice(0, 2),
    };
}

/**
 * 文の中から、はっきり書かれている年だけを拾う。
 *
 * <b>推定しない。</b>
 * 「たぶん2020年ごろ」を「2020」と書けば、それは嘘になる。
 */
function 年を拾う(文) {
    const 当たり = String(文 || '').match(/(19|20)\d{2}\s*年/g);
    if (!当たり || !当たり.length) return '';

    // 創業・設立と一緒に書かれているものを優先する
    const 文字 = String(文);
    for (const 年 of 当たり) {
        const 位置 = 文字.indexOf(年);
        const あたり = 文字.slice(Math.max(0, 位置 - 30), 位置 + 30);
        if (/創業|設立|始ま|できた|作った/.test(あたり)) {
            return 年.replace(/[^\d]/g, '');
        }
    }
    return '';
}

/**
 * 文の中から、代表者・創業者らしい人名を拾う。
 *
 * <b>推定しない。</b>年を拾うときと同じ考え方で、
 * 「〇〇が始めた」「デザイナー〇〇によって」のように、
 * はっきりそう書かれているものだけを拾う。
 * 無ければ空のまま返す（それらしい名を作らない）。
 *
 * 以前は「設立年」のパターン（年を拾う）しか無く、
 * 同じ文に書かれている代表者名を毎回取りこぼしていた。
 */
function 代表者を拾う(文) {
    const s = String(文 || '');
    const パターンたち = [
        // 「デザイナー高橋盾（たかはし じゅん）によって」
        /デザイナー([^\s、。（(]{1,14})(?:\s*[（(][^）)]*[）)])?\s*(?:によって|が)/,
        // 「創業者は〇〇」「創業者：〇〇」
        /創業者(?:は|:|：)\s*([^\s、。]{1,14})/,
        // 「代表は〇〇」「代表者：〇〇」
        /代表(?:者)?(?:は|:|：)\s*([^\s、。]{1,14})/,
        // 「〇〇によって1990年に設立」
        /([^\s、。]{1,14})によって(?:19|20)\d{2}年[にへ]?\s*(?:設立|創業)/,
        // 「1990年、高橋盾が始めた」「1993年、NIGO が東京・裏原宿で始めた」
        // 「が」の直後に動詞が来るとは限らない（「NIGOが東京で始めた」のように
        // 場所などを挟むことがある）ので、名前の直後に「が」が来ることだけを見る。
        /(?:19|20)\d{2}\s*年[、,]\s*([^\s、。]{1,14})\s*が/,
    ];
    for (const re of パターンたち) {
        const m = s.match(re);
        if (m && m[1]) {
            // 「創業者は山田太郎です」のように、名前の後ろに
            // 敬称・語尾が続けて拾われることがあるので、そこは落とす。
            return m[1].trim().replace(/(です|でした|氏|さん|により)$/, '').trim();
        }
    }
    return '';
}

/**
 * ブランドの下書きをまとめる。
 *
 * @param {string} 名前
 * @returns {{ok, 理念, 歴史, 創業年, 代表者, 出どころ, 訳}}
 */
async function 下書きをまとめる(名前) {
    // 先に、書き起こしてある歴史を見る。
    //
    // 参考ブランドについては、事実だけを書き起こしてある。
    // そちらのほうが確かなので、資料より先に見る。
    if (typeof ブランドの歴史を引く === 'function') {
        const 書いたもの = ブランドの歴史を引く(名前);
        if (書いたもの) {
            return {
                ok: true,
                理念: 書いたもの.理念 || '',
                歴史: 書いたもの.歴史 || '',
                創業年: (書いたもの.歴史.match(/(1[89]|20)\d{2}年/) || [''])[0]
                    .replace('年', ''),
                代表者: 代表者を拾う(書いたもの.歴史),
                出どころ: ['書き起こした事実'],
                訳: 書いたもの.理念
                    ? '書き起こしてある事実から出しました。'
                    : '書き起こしてある事実から出しました。'
                        + '理念は公にされているものが見つからなかったので、空にしてあります。',
                学べる点: 書いたもの.学べる点 || '',
            };
        }
    }

    const 集めた = await 資料から集める(名前);

    if (!集めた.ok) {
        return {
            ok: false,
            訳: 集めた.資料なし
                ? `「${名前}」について書かれた資料が、この道具の中にありません。\n\n`
                  + '作り話で埋めることはしません。\n'
                  + '資料を入れるか、ご自身の言葉で書いてください。\n'
                  + '書いたものは、そのまま覚えさせられます。'
                : 集めた.訳,
            資料なし: !!集めた.資料なし,
        };
    }

    const 分けた = 理念と歴史に分ける(集めた.中身);
    const 年 = 年を拾い直す(集めた.中身);

    return {
        ok: true,
        理念: 分けた.理念,
        歴史: 分けた.歴史 || 分けた.そのほか.join(' '),
        創業年: 年,
        代表者: 代表者を拾う(集めた.中身),
        出どころ: 集めた.出どころ,
        訳: 年
            ? `資料からまとめました（創業年も見つかりました）`
            : `資料からまとめました。創業年は資料に書かれていなかったので、空にしてあります。`,
    };
}

function 年を拾い直す(文) {
    return 年を拾う(文);
}

window.ブランドの下書きをまとめる = 下書きをまとめる;
window.ブランドの理念と歴史に分ける = 理念と歴史に分ける;
window.ブランドの代表者を拾う = 代表者を拾う;
