/** 対数ガンマ関数（ランチョス近似）。階乗が大きくなりすぎて溢れるのを防ぐため対数で持つ。 */
function 対数ガンマ(x) {
    const g = [
        676.5203681218851, -1259.1392167224028, 771.32342877765313,
        -176.61502916214059, 12.507343278686905, -0.13857109526572012,
        9.9843695780195716e-6, 1.5056327351493116e-7,
    ];
    if (x < 0.5) {
        // 反射公式。0以下でも計算できるようにする。
        return Math.log(Math.PI / Math.sin(Math.PI * x)) - 対数ガンマ(1 - x);
    }
    x -= 1;
    let a = 0.99999999999980993;
    const t = x + 7.5;
    for (let i = 0; i < g.length; i++) a += g[i] / (x + i + 1);
    return 0.5 * Math.log(2 * Math.PI) + (x + 0.5) * Math.log(t) - t + Math.log(a);
}

/** 正則化不完全ベータ関数 I_x(a,b)。t分布とF分布に使う。 */
function 不完全ベータ(x, a, b) {
    if (x <= 0) return 0;
    if (x >= 1) return 1;

    const 前 = Math.exp(
        対数ガンマ(a + b) - 対数ガンマ(a) - 対数ガンマ(b)
        + a * Math.log(x) + b * Math.log(1 - x));

    // 収束が速いほうの側で計算する。遅い側で回すと桁が落ちる。
    if (x < (a + 1) / (a + b + 2)) return 前 * ベータ連分数(x, a, b) / a;
    return 1 - 前 * ベータ連分数(1 - x, b, a) / b;
}

/** 不完全ベータの連分数展開（Lentz法） */
function ベータ連分数(x, a, b) {
    const 極小 = 1e-30;
    const 許容 = 3e-12;
    const qab = a + b;
    const qap = a + 1;
    const qam = a - 1;

    let c = 1;
    let d = 1 - (qab * x) / qap;
    if (Math.abs(d) < 極小) d = 極小;
    d = 1 / d;
    let h = d;

    for (let m = 1; m <= 300; m++) {
        const m2 = 2 * m;

        // 偶数番目の項
        let aa = (m * (b - m) * x) / ((qam + m2) * (a + m2));
        d = 1 + aa * d;
        if (Math.abs(d) < 極小) d = 極小;
        c = 1 + aa / c;
        if (Math.abs(c) < 極小) c = 極小;
        d = 1 / d;
        h *= d * c;

        // 奇数番目の項
        aa = (-(a + m) * (qab + m) * x) / ((a + m2) * (qap + m2));
        d = 1 + aa * d;
        if (Math.abs(d) < 極小) d = 極小;
        c = 1 + aa / c;
        if (Math.abs(c) < 極小) c = 極小;
        d = 1 / d;
        const 差 = d * c;
        h *= 差;

        if (Math.abs(差 - 1) < 許容) break;
    }
    return h;
}

/** 正則化不完全ガンマ関数 P(a,x)。カイ二乗分布に使う。 */
function 不完全ガンマ(a, x) {
    if (x <= 0) return 0;
    if (x < a + 1) {
        // 級数展開のほうが速い側
        let 項 = 1 / a;
        let 和 = 項;
        for (let n = 1; n <= 500; n++) {
            項 *= x / (a + n);
            和 += 項;
            if (Math.abs(項) < Math.abs(和) * 1e-14) break;
        }
        return 和 * Math.exp(-x + a * Math.log(x) - 対数ガンマ(a));
    }

    // 連分数展開のほうが速い側
    const 極小 = 1e-30;
    let b = x + 1 - a;
    let c = 1 / 極小;
    let d = 1 / b;
    let h = d;
    for (let i = 1; i <= 500; i++) {
        const an = -i * (i - a);
        b += 2;
        d = an * d + b;
        if (Math.abs(d) < 極小) d = 極小;
        c = b + an / c;
        if (Math.abs(c) < 極小) c = 極小;
        d = 1 / d;
        const 差 = d * c;
        h *= 差;
        if (Math.abs(差 - 1) < 1e-14) break;
    }
    return 1 - Math.exp(-x + a * Math.log(x) - 対数ガンマ(a)) * h;
}

