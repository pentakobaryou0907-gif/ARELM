/** 母平均の区間推定（母分散が分からないとき＝t分布を使う） */
function 母平均の推定(値たち, 信頼度 = 0.95) {
    const k = 記述統計(値たち, true);
    if (!k.ok) return k;
    if (k.n < 2) return { ok: false, 訳: '区間推定には2件以上が要ります' };

    const 自由度 = k.n - 1;
    const 両側 = 1 - (1 - 信頼度) / 2;
    const t = 統().t分布の点(両側, 自由度);
    const 幅 = t * k.標準誤差;

    return {
        ok: true, n: k.n, 平均: k.平均, 標準偏差: k.標準偏差,
        自由度, t, 信頼度,
        下限: k.平均 - 幅, 上限: k.平均 + 幅, 幅,
        読み方: `同じやり方で何度も調べれば、そのうち${Math.round(信頼度 * 100)}%が`
            + `この範囲に本当の平均を含む、という意味です。`
            + `「この範囲に入る確率が${Math.round(信頼度 * 100)}%」ではありません。`,
    };
}

/** 母比率の区間推定（正規近似） */
function 母比率の推定(成功数, 全体数, 信頼度 = 0.95) {
    const x = Number(成功数);
    const n = Number(全体数);
    if (!Number.isFinite(x) || !Number.isFinite(n) || n <= 0 || x < 0 || x > n) {
        return { ok: false, 訳: '成功数は0以上、全体数以下にしてください' };
    }

    const p = x / n;

    // 正規近似が使える目安。外れると答えが当てにならない。
    const 近似できるか = n * p >= 5 && n * (1 - p) >= 5;

    const z = 統().正規分布の点(1 - (1 - 信頼度) / 2);
    const 幅 = z * Math.sqrt((p * (1 - p)) / n);

    return {
        ok: true, n, 成功数: x, 比率: p, z, 信頼度,
        下限: Math.max(0, p - 幅), 上限: Math.min(1, p + 幅), 幅,
        注意: 近似できるか ? '' :
            'np と n(1-p) のどちらかが5未満です。正規近似が当てにならないため、'
            + 'この区間は目安として扱ってください。',
    };
}

/** 母分散の区間推定（カイ二乗分布を使う） */
function 母分散の推定(値たち, 信頼度 = 0.95) {
    const k = 記述統計(値たち, true);
    if (!k.ok) return k;
    if (k.n < 2) return { ok: false, 訳: '区間推定には2件以上が要ります' };

    const 自由度 = k.n - 1;
    const 片側 = (1 - 信頼度) / 2;

    // 上側の点で割ると下限、下側の点で割ると上限。逆にしやすいので注意。
    const χ上 = 統().カイ二乗の点(1 - 片側, 自由度);
    const χ下 = 統().カイ二乗の点(片側, 自由度);

    const 二乗和 = 自由度 * k.分散;

    return {
        ok: true, n: k.n, 不偏分散: k.分散, 自由度, 信頼度,
        下限: 二乗和 / χ上, 上限: 二乗和 / χ下,
        標準偏差の下限: Math.sqrt(二乗和 / χ上),
        標準偏差の上限: Math.sqrt(二乗和 / χ下),
        注意: '母集団が正規分布に従うことを前提にしています。'
            + '大きく外れた値が混ざっていると、当てになりません。',
    };
}

