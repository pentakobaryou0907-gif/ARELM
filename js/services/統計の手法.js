/**
 * ピアソンの相関係数と、その無相関検定。
 *
 * 「相関がある」は「原因と結果の関係がある」ではない。
 * その断りを、結果の中に必ず入れて返す。
 */
function 相関(xたち, yたち) {
    const 組 = [];
    const n0 = Math.min((xたち || []).length, (yたち || []).length);
    for (let i = 0; i < n0; i++) {
        const a = Number(xたち[i]);
        const b = Number(yたち[i]);
        if (Number.isFinite(a) && Number.isFinite(b)) 組.push([a, b]);
    }

    const n = 組.length;
    if (n < 3) return { ok: false, 訳: '相関を出すには、そろった組が3つ以上要ります' };

    const xs = 組.map((p) => p[0]);
    const ys = 組.map((p) => p[1]);
    const mx = xs.reduce((s, v) => s + v, 0) / n;
    const my = ys.reduce((s, v) => s + v, 0) / n;

    let Sxy = 0;
    let Sxx = 0;
    let Syy = 0;
    for (let i = 0; i < n; i++) {
        Sxy += (xs[i] - mx) * (ys[i] - my);
        Sxx += (xs[i] - mx) ** 2;
        Syy += (ys[i] - my) ** 2;
    }

    if (Sxx === 0 || Syy === 0) {
        return { ok: false, 訳: 'どちらかが全部同じ値なので、相関を出せません' };
    }

    const r = Sxy / Math.sqrt(Sxx * Syy);

    // 無相関の検定（母相関が0かどうか）
    const 自由度 = n - 2;
    const t = r * Math.sqrt(自由度 / (1 - r * r));
    const p = 2 * (1 - 統().t分布の下側(Math.abs(t), 自由度));

    return {
        ok: true, n, r,
        決定係数: r * r,
        t, 自由度, p値: p,
        有意か: p < 0.05,
        強さ: 強さの言葉(Math.abs(r)),
        断り: '相関があっても、原因と結果の関係があるとは限りません。'
            + '第三の要因が両方を動かしていることがあります。',
    };
}

function 強さの言葉(絶対値のr) {
    if (絶対値のr >= 0.7) return '強い';
    if (絶対値のr >= 0.4) return '中くらい';
    if (絶対値のr >= 0.2) return '弱い';
    return 'ほとんどない';
}

