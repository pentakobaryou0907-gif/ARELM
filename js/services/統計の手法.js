/** 1標本のt検定（平均が、ある値と違うといえるか） */
function t検定(値たち, 比べる値, 有意水準 = 0.05) {
    const k = 記述統計(値たち, true);
    if (!k.ok) return k;
    if (k.n < 2) return { ok: false, 訳: '検定には2件以上が要ります' };
    if (!k.標準偏差) return { ok: false, 訳: 'ばらつきが0なので検定できません' };

    const μ = Number(比べる値);
    const 自由度 = k.n - 1;
    const t = (k.平均 - μ) / k.標準誤差;
    const p = 2 * (1 - 統().t分布の下側(Math.abs(t), 自由度));
    const 棄却値 = 統().t分布の点(1 - 有意水準 / 2, 自由度);

    return {
        ok: true, n: k.n, 平均: k.平均, 比べる値: μ,
        t, 自由度, p値: p, 棄却値, 有意水準,
        棄却できるか: p < 有意水準,
        読み方: p < 有意水準
            ? `平均は ${μ} とは違うといえます（p = ${p.toFixed(4)}）。`
              + 'ただし「違いに意味がある大きさか」は、別に考えてください。'
            : `平均が ${μ} と違うとは、この件数では言い切れません（p = ${p.toFixed(4)}）。`
              + '「同じだと分かった」ではなく「違うとは言えなかった」だけです。',
    };
}

/**
 * 独立性の検定（カイ二乗検定）。
 *
 * @param {number[][]} 表 行×列の観測度数
 */
function 独立性の検定(表, 有意水準 = 0.05) {
    const 行数 = (表 || []).length;
    const 列数 = 行数 ? 表[0].length : 0;
    if (行数 < 2 || 列数 < 2) {
        return { ok: false, 訳: '2行2列以上の表が要ります' };
    }

    const 観測 = 表.map((r) => r.map((v) => Number(v) || 0));
    const 行合計 = 観測.map((r) => r.reduce((s, v) => s + v, 0));
    const 列合計 = [];
    for (let j = 0; j < 列数; j++) {
        列合計.push(観測.reduce((s, r) => s + r[j], 0));
    }
    const 総計 = 行合計.reduce((s, v) => s + v, 0);
    if (総計 <= 0) return { ok: false, 訳: '数字が入っていません' };

    const 期待 = [];
    let χ2 = 0;
    let 期待5未満 = 0;

    for (let i = 0; i < 行数; i++) {
        期待.push([]);
        for (let j = 0; j < 列数; j++) {
            const e = (行合計[i] * 列合計[j]) / 総計;
            期待[i].push(e);
            if (e < 5) 期待5未満++;
            if (e > 0) χ2 += (観測[i][j] - e) ** 2 / e;
        }
    }

    const 自由度 = (行数 - 1) * (列数 - 1);
    const p = 1 - 統().カイ二乗の下側(χ2, 自由度);
    const 棄却値 = 統().カイ二乗の点(1 - 有意水準, 自由度);

    return {
        ok: true, 観測, 期待, 行合計, 列合計, 総計,
        χ2, 自由度, p値: p, 棄却値, 有意水準,
        棄却できるか: p < 有意水準,
        注意: 期待5未満
            ? `期待度数が5未満のマスが${期待5未満}個あります。`
              + 'カイ二乗検定の前提から外れるため、この結果は当てになりません。'
            : '',
        読み方: p < 有意水準
            ? `2つの項目は無関係とはいえません（p = ${p.toFixed(4)}）。`
              + 'ただし、どちらが原因かまでは分かりません。'
            : `この件数では、2つの項目に関係があるとはいえません（p = ${p.toFixed(4)}）。`,
    };
}

