/**
 * 統計の手法（記述統計・推定・検定・回帰）
 *
 * 分布の計算は 統計の計算.js に置き、ここでは手法だけを書く。
 * 分けておくと、数表と合わせる確認が分布側だけで済む。
 *
 * 気をつけていること:
 *
 *   ・<b>標本と母集団を混ぜない。</b>
 *     分散には「標本分散（nで割る）」と「不偏分散（n-1で割る）」がある。
 *     どちらを使ったかを必ず返す。混ぜると答えが静かにずれる。
 *
 *   ・<b>「有意」を「正しい」と言い換えない。</b>
 *     検定で分かるのは「偶然ではなさそう」までで、
 *     因果があるとも、実務で意味がある差だとも言っていない。
 *     そう読めるような言葉にしない。
 *
 *   ・<b>数が足りなければ、やらない。</b>
 *     2件や3件で検定しても、出た数字に意味がない。
 *     足りないときは、足りないと言って止める。
 *
 * すべてこの端末の中だけで動きます。外部へは一切送りません。
 */

const 統 = () => window.AReGLM_統計;

/* ==========================================================
   記述統計
   ========================================================== */

/**
 * 基本の統計量を出す。
 *
 * @param {number[]} 値たち
 * @param {boolean} 不偏 true なら n-1 で割る（標本から母集団を推し量るとき）
 */
function 記述統計(値たち, 不偏 = true) {
    const x = (値たち || []).map(Number).filter((v) => Number.isFinite(v));
    const n = x.length;
    if (n === 0) return { ok: false, 訳: '数字が一つもありません' };

    const 合計 = x.reduce((s, v) => s + v, 0);
    const 平均 = 合計 / n;

    const 偏差の二乗和 = x.reduce((s, v) => s + (v - 平均) ** 2, 0);
    // n=1 のときは、ばらつきを測りようがない。0ではなく「無い」を返す。
    const 割る数 = 不偏 ? n - 1 : n;
    const 分散 = 割る数 > 0 ? 偏差の二乗和 / 割る数 : null;
    const 標準偏差 = 分散 === null ? null : Math.sqrt(分散);

    const 並べ = [...x].sort((a, b) => a - b);
    const 中央値 = n % 2
        ? 並べ[(n - 1) / 2]
        : (並べ[n / 2 - 1] + 並べ[n / 2]) / 2;

    // 歪度・尖度は、ばらつきが0だと割れない
    let 歪度 = null;
    let 尖度 = null;
    if (標準偏差 && 標準偏差 > 0) {
        歪度 = x.reduce((s, v) => s + ((v - 平均) / 標準偏差) ** 3, 0) / n;
        // 正規分布を0とする「超過尖度」で返す
        尖度 = x.reduce((s, v) => s + ((v - 平均) / 標準偏差) ** 4, 0) / n - 3;
    }

    return {
        ok: true,
        n, 合計, 平均, 中央値,
        最小: 並べ[0], 最大: 並べ[n - 1],
        範囲: 並べ[n - 1] - 並べ[0],
        分散, 標準偏差, 歪度, 尖度,
        分散の種類: 不偏 ? '不偏分散（n-1で割る）' : '標本分散（nで割る）',
        標準誤差: 標準偏差 === null ? null : 標準偏差 / Math.sqrt(n),
    };
}

/**
 * ヒストグラムの階級を作る。
 *
 * 階級数はスタージェスの公式（1 + log2(n)）を目安にする。
 * 決め方には他にもあるが、手計算の教科書ではこれが標準。
 */
function ヒストグラム(値たち, 階級数 = null) {
    const x = (値たち || []).map(Number).filter((v) => Number.isFinite(v));
    const n = x.length;
    if (n < 2) return { ok: false, 訳: 'ヒストグラムには2件以上が要ります' };

    const 最小 = Math.min(...x);
    const 最大 = Math.max(...x);

    if (最小 === 最大) {
        return { ok: false, 訳: '全部が同じ値なので、階級に分けられません' };
    }

    const k = 階級数 || Math.max(1, Math.ceil(1 + Math.log2(n)));
    const 幅 = (最大 - 最小) / k;

    const 階級たち = [];
    for (let i = 0; i < k; i++) {
        const 下 = 最小 + 幅 * i;
        const 上 = i === k - 1 ? 最大 : 下 + 幅;
        階級たち.push({
            下, 上,
            階級値: (下 + 上) / 2,
            度数: 0,
        });
    }

    x.forEach((v) => {
        // 最大値だけは最後の階級に入れる（上端は含む扱い）
        let i = Math.floor((v - 最小) / 幅);
        if (i >= k) i = k - 1;
        階級たち[i].度数++;
    });

    階級たち.forEach((c) => { c.相対度数 = c.度数 / n; });

    return { ok: true, n, 階級数: k, 階級幅: 幅, 最小, 最大, 階級たち };
}

