/**
 * 単回帰分析。y = a + bx を当てはめる。
 *
 * 回帰式と決定係数だけでなく、
 * <b>傾きが0と違うといえるか</b>（回帰係数の検定）まで出す。
 * 決定係数が高くても、傾きが偶然の範囲なら使えないため。
 */
function 単回帰(xたち, yたち, 有意水準 = 0.05) {
    const 組 = [];
    const n0 = Math.min((xたち || []).length, (yたち || []).length);
    for (let i = 0; i < n0; i++) {
        const a = Number(xたち[i]);
        const b = Number(yたち[i]);
        if (Number.isFinite(a) && Number.isFinite(b)) 組.push([a, b]);
    }

    const n = 組.length;
    if (n < 3) return { ok: false, 訳: '回帰には、そろった組が3つ以上要ります' };

    const xs = 組.map((p) => p[0]);
    const ys = 組.map((p) => p[1]);
    const mx = xs.reduce((s, v) => s + v, 0) / n;
    const my = ys.reduce((s, v) => s + v, 0) / n;

    let Sxx = 0;
    let Sxy = 0;
    let Syy = 0;
    for (let i = 0; i < n; i++) {
        Sxx += (xs[i] - mx) ** 2;
        Sxy += (xs[i] - mx) * (ys[i] - my);
        Syy += (ys[i] - my) ** 2;
    }
    if (Sxx === 0) return { ok: false, 訳: 'xが全部同じ値なので、傾きを出せません' };

    const 傾き = Sxy / Sxx;
    const 切片 = my - 傾き * mx;

    // 残差から、当てはまりの悪さを測る
    const 残差平方和 = ys.reduce((s, y, i) => s + (y - (切片 + 傾き * xs[i])) ** 2, 0);
    const 回帰平方和 = Syy - 残差平方和;
    const 決定係数 = Syy === 0 ? 0 : 回帰平方和 / Syy;

    const 自由度 = n - 2;
    const 残差分散 = 残差平方和 / 自由度;
    const 標準誤差 = Math.sqrt(残差分散);

    // 傾きの検定
    const 傾きの標準誤差 = Math.sqrt(残差分散 / Sxx);
    const t = 傾きの標準誤差 === 0 ? Infinity : 傾き / 傾きの標準誤差;
    const p = 2 * (1 - 統().t分布の下側(Math.abs(t), 自由度));

    // 回帰全体の検定（単回帰では t² = F になる）
    const F = 残差分散 === 0 ? Infinity : 回帰平方和 / 残差分散;
    const Fのp = 1 - 統().F分布の下側(F, 1, 自由度);

    const t境界 = 統().t分布の点(1 - 有意水準 / 2, 自由度);

    return {
        ok: true, n,
        傾き, 切片,
        式: `y = ${切片.toFixed(3)} ${傾き >= 0 ? '+' : '−'} ${Math.abs(傾き).toFixed(3)}x`,
        決定係数,
        自由相関: Math.sqrt(Math.max(0, 決定係数)) * (傾き < 0 ? -1 : 1),
        残差平方和, 回帰平方和, 全平方和: Syy,
        残差分散, 標準誤差,
        傾きの標準誤差,
        傾きのt: t, 傾きのp値: p, 自由度, t境界,
        傾きは有意か: p < 有意水準,
        F, Fのp値: Fのp,
        予測: (x) => 切片 + 傾き * Number(x),
        読み方: p < 有意水準
            ? `xが1増えると、yはおよそ ${傾き.toFixed(3)} 変わります。`
              + `この傾きは偶然とは考えにくい（p = ${p.toFixed(4)}）。`
              + `ただし、当てはまりの良さ（決定係数 ${(決定係数 * 100).toFixed(1)}%）とは別の話です。`
            : `傾きが0と違うとは、この件数では言い切れません（p = ${p.toFixed(4)}）。`
              + 'xでyを説明できるとは言えない状態です。',
        断り: '当てはめただけで、xがyの原因だとは言っていません。'
            + 'また、データの範囲の外へ延ばした予測は当てになりません。',
    };
}

