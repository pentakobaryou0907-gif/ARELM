/**
 * 自作の音声認識（覚えながら増える）
 *
 * 考え方:
 *   最初から何でも聞き取れるものは作れない。
 *   代わりに「教われば、その言葉を覚える」形にする。
 *
 *   聞き取れなかったときは、素直に聞き返す。
 *   「何と言いましたか」と尋ね、文字で教えてもらえば、
 *   次から同じ言い方で通る。
 *
 *   使うほど、あなたの言い方に合っていく。
 *   最初は不便だが、増えるほど楽になる。
 *
 * なぜこの形なのか:
 *   何でも聞き取る認識には、何千時間もの音声で学習したモデルが要る。
 *   それは作れない。「作れます」とは言わない。
 *
 *   だが、あなたが実際に使う言葉は、そう多くない。
 *   使う言葉だけ覚えれば、実用にはなる。
 *
 * 音声はこの端末の中だけで扱う。外部へは一切送らない。
 * 覚えるのは「音の特徴」で、音声そのものは残さない。
 */

const 覚えた声の鍵 = 'areglm_voice_templates';

/** 同じ言葉として認めるずれの上限。これを超えたら「分からない」と言う。 */
// 認める上限。
//
// 常駐側と揃える。
// 揃えないと、画面では通るのに常駐では通らない、
// といった食い違いが起きて、原因を追いにくくなる。
//
// 無音を取り除いたので、ずれの意味が変わった。
// 「呼んでいないのに動く」は会話を邪魔するので、厳しい側に倒す。
const 認める上限 = 26;

/** 迷う範囲。この間なら、確かめてから使う。 */
const 迷う上限 = 45;

/** 同じ言葉について持つ「言い方」の数 */
const 言い方の上限 = 5;

/** 一度の発話から拾う言葉の数。これ以上は探さない。 */
const 一度に拾う上限 = 4;

function 覚えた声を読む() {
    try {
        const r = JSON.parse(localStorage.getItem(覚えた声の鍵) || '[]');
        return Array.isArray(r) ? r : [];
    } catch {
        return [];
    }
}

function 覚えた声を保存(一覧) {
    localStorage.setItem(覚えた声の鍵, JSON.stringify(一覧));
}

/**
 * 音の特徴を、保存できる形にする。
 *
 * そのままだと大きいので、小数を丸めて縮める。
 * 細かい桁は聞き分けに効かないため、落としても困らない。
 */
function 縮める(特徴) {
    return 特徴.map((f) => Array.from(f).map((v) => Math.round(v * 100) / 100));
}

function 戻す(縮めたもの) {
    return 縮めたもの.map((a) => Float32Array.from(a));
}

/**
 * 言葉を覚える。
 *
 * 同じ言葉を何度か言ってもらうほど、確かになる。
 * 一度だけだと、たまたまの言い方に引きずられるため。
 *
 * @param {string} 言葉  何と言ったか
 * @param {Float32Array} 波形
 * @param {number} 周波数
 */
function 声を覚える(言葉, 波形, 周波数) {
    言葉 = (言葉 || '').trim();
    if (!言葉) return { ok: false, 訳: '何と言ったか教えてください' };

    const 芯 = window.AReGLM_VOICE_CORE;
    const 声 = 芯.声の部分を切り出す(波形);
    if (!声) return { ok: false, 訳: '声が聞き取れませんでした。もう一度お願いします。' };

    const 特徴 = 芯.MFCCにする(声, 周波数);
    if (特徴.length < 4) return { ok: false, 訳: '短すぎます。もう少しはっきり話してください。' };

    // 拍としてもためる。
    //
    // 言葉まるごとだけを覚えていると、
    // 教えていない言葉は永久に聞き取れない。
    // 同じ音から拍も取り出しておけば、
    // その組み合わせで、教えていない言葉にも届くようになる。
    //
    // わざわざ別に録らせない。覚えるついでにためる。
    if (typeof 拍をためる === 'function') {
        try {
            拍をためる(言葉, 特徴);
        } catch (e) {
            // 拍がためられなくても、言葉として覚えることはできる。
            // ここで止まると、覚える手立てが無くなる。
            console.warn('拍をためられませんでした:', e.message);
        }
    }

    const 一覧 = 覚えた声を読む();
    一覧.push({
        id: 'v_' + Date.now(),
        言葉,
        特徴: 縮める(特徴),
        覚えた日: new Date().toISOString(),
    });

    // 同じ言葉は、言い方を5つまで持つ。
    //
    // ここを1つにしていたら、その日の言い方に縛られていた。
    // 早口のとき、疲れているとき、語尾を伸ばしたとき——
    // 同じ言葉でも音は違う。複数持てば、そのどれかに当たる。
    //
    // 増やしすぎると、比べる回数だけ増えて遅くなる。5つで足りる。
    const 同じ言葉 = 一覧.filter((x) => x.言葉 === 言葉);
    if (同じ言葉.length > 言い方の上限) {
        const 捨てる = 同じ言葉.slice(0, 同じ言葉.length - 言い方の上限).map((x) => x.id);
        for (let i = 一覧.length - 1; i >= 0; i--) {
            if (捨てる.includes(一覧[i].id)) 一覧.splice(i, 1);
        }
    }

    // 全体としても増えすぎると重くなるので、古いものから落とす。
    覚えた声を保存(一覧.slice(-300));

    const 同じ = 一覧.filter((x) => x.言葉 === 言葉).length;
    return {
        ok: true,
        訳: `「${言葉}」を覚えました（${同じ}回目）`
            + (同じ < 2 ? '。もう一度言っていただけると、より確かになります。' : ''),
        回数: 同じ,
    };
}

/**
 * 覚えたものの中から、いちばん近いものを一つ探す。
 *
 * 全体どうしではなく「長い声の中のどこか」として探す。
 * 前置きや言い淀み、語尾の違いを許すため。
 */
function _一つ探す(特徴, 一覧, 使わない) {
    const 芯 = window.AReGLM_VOICE_CORE;
    let 最良 = null;
    let 最小 = Infinity;
    let 場所 = null;

    一覧.forEach((t) => {
        if (使わない && 使わない.has(t.言葉)) return;
        const r = 芯.中から探す(特徴, 戻す(t.特徴));
        if (r.ずれ < 最小) {
            最小 = r.ずれ;
            最良 = t;
            場所 = r;
        }
    });

    if (!最良) return null;
    return { 言葉: 最良.言葉, ずれ: 最小, 始まり: 場所.始まり, 終わり: 場所.終わり };
}

function _判定(ずれ) {
    if (ずれ <= 認める上限) return 'わかった';
    if (ずれ <= 迷う上限) return 'たぶん';
    return 'わからない';
}

/**
 * 聞き取る。
 *
 * 覚えたものの中から、近いものを探す。
 * 近いものが無ければ「分からない」と正直に言う。
 * 無理に近いものを当てると、違う作業をしてしまうため。
 *
 * 一度に複数の言葉を言われることがある。
 * 「在庫を見せて、それから点検して」のように。
 * だから、当たった部分を除いて、残りからも探す。
 *
 * @returns {{結果:'わかった'|'たぶん'|'わからない', 言葉:string, ずれ:number, 言葉たち:string[]}}
 */
function 声を聞き取る(波形, 周波数) {
    const 芯 = window.AReGLM_VOICE_CORE;
    const 声 = 芯.声の部分を切り出す(波形);
    if (!声) return { 結果: 'わからない', 言葉: '', ずれ: Infinity, 言葉たち: [], 訳: '声が入っていませんでした' };

    const 特徴 = 芯.MFCCにする(声, 周波数);
    if (特徴.length < 4) return { 結果: 'わからない', 言葉: '', ずれ: Infinity, 言葉たち: [], 訳: '短すぎました' };

    const 一覧 = 覚えた声を読む();
    if (!一覧.length) {
        return { 結果: 'わからない', 言葉: '', ずれ: Infinity, 言葉たち: [], 訳: 'まだ何も覚えていません' };
    }

    const 一番 = _一つ探す(特徴, 一覧);
    const 結果 = _判定(一番.ずれ);

    if (結果 === 'わからない') {
        return {
            結果: 'わからない',
            言葉: '',
            ずれ: Math.round(一番.ずれ * 10) / 10,
            言葉たち: [],
            訳: '覚えている言葉の中に、近いものがありませんでした',
        };
    }

    // --- 残りの部分からも探す ---
    //
    // 当たったところを取り除いた、前と後ろを見る。
    // 一つ当たったら終わり、にしていたら
    // 「在庫を見せて、それから点検して」の後半が落ちていた。
    const 言葉たち = [{ 言葉: 一番.言葉, 位置: 一番.始まり }];
    const 済み = new Set([一番.言葉]);
    const 残り = [
        特徴.slice(0, 一番.始まり),
        特徴.slice(一番.終わり),
    ];
    const 位置の元 = [0, 一番.終わり];

    残り.forEach((断片, k) => {
        if (断片.length < 8) return;                        // 短すぎる切れ端は雑音
        if (言葉たち.length >= 一度に拾う上限) return;
        const r = _一つ探す(断片, 一覧, 済み);
        if (r && _判定(r.ずれ) === 'わかった') {
            言葉たち.push({ 言葉: r.言葉, 位置: 位置の元[k] + r.始まり });
            済み.add(r.言葉);
        }
    });

    // 言われた順に並べ直す
    言葉たち.sort((a, b) => a.位置 - b.位置);

    return {
        結果,
        言葉: 一番.言葉,
        ずれ: Math.round(一番.ずれ * 10) / 10,
        言葉たち: 言葉たち.map((x) => x.言葉),
    };
}

/** 覚えた言葉の一覧（同じ言葉はまとめる） */
function 覚えた言葉たち() {
    const 数え = {};
    覚えた声を読む().forEach((t) => {
        数え[t.言葉] = (数え[t.言葉] || 0) + 1;
    });
    return Object.entries(数え)
        .map(([言葉, 回数]) => ({ 言葉, 回数 }))
        .sort((a, b) => b.回数 - a.回数);
}

/** 覚えた言葉を忘れる */
function 声を忘れる(言葉) {
    const 一覧 = 覚えた声を読む();
    覚えた声を保存(一覧.filter((x) => x.言葉 !== 言葉));
}

/**
 * 通った聞き取りを、材料として足す。
 *
 * 「作業しながら覚える」の中心。
 *
 * 呼びかけが通ったなら、その声は本物の呼びかけ。
 * 聞き返して文字で教わったなら、その音と文字は正しい組。
 * どちらも、わざわざ録らなくても手に入る材料。
 *
 * 使うほど、あなたの言い方に馴染んでいく。
 * 朝の声、疲れた声、早口——全部が材料になる。
 *
 * @param {string} 言葉
 * @param {Float32Array} 波形
 * @param {number} 周波数
 * @param {number} ずれ  そのときの一致の良さ。良すぎるものは足さない。
 */
function 使いながら覚える(言葉, 波形, 周波数, ずれ) {
    if (!言葉 || !波形) return { 足した: false, 訳: '材料がありません' };

    // すでに十分近いものは足さない。
    // 同じような手本ばかり増えても、幅は広がらない。
    // ずれが少しある＝新しい言い方、のときだけ足す価値がある。
    // はっきり合ったときだけ覚える。
    //
    // ぎりぎりで通ったものまで覚えると、
    // 濁ったものが混ざって、かえって当たらなくなる。
    // 実際、試している間に12件まで膨れ、
    // そのほとんどが呼びかけではなかった。
    if (typeof ずれ === 'number') {
        if (ずれ < 8) {
            return { 足した: false, 訳: 'すでに近い言い方を覚えています' };
        }
        if (ずれ > 認める上限 * 0.7) {
            return { 足した: false, 訳: 'ぎりぎりの一致なので、覚えずにおきます' };
        }
    }

    const 芯 = window.AReGLM_VOICE_CORE;
    const 声 = 芯.声の部分を切り出す(波形);
    if (!声) return { 足した: false, 訳: '声が入っていませんでした' };

    const 特徴 = 芯.MFCCにする(声, 周波数);
    if (特徴.length < 4) return { 足した: false, 訳: '短すぎます' };

    // 拍としてためる
    let 拍 = null;
    if (typeof 拍をためる === 'function') {
        try { 拍 = 拍をためる(言葉, 特徴); } catch { /* 続ける */ }
    }

    // 言葉としてもためる（上限まで）
    const 一覧 = 覚えた声を読む();
    const 同じ = 一覧.filter((x) => x.言葉 === 言葉);
    if (同じ.length < 言い方の上限) {
        一覧.push({
            id: 'v_' + Date.now(),
            言葉,
            特徴: 縮める(特徴),
            覚えた日: new Date().toISOString(),
            使いながら: true,
        });
        覚えた声を保存(一覧.slice(-300));
    }

    return {
        足した: true,
        訳: `「${言葉}」の言い方を一つ覚えました`,
        拍: 拍 ? 拍.蓄えた拍 : 0,
    };
}

window.AReGLM_VOICE_LEARN = {
    声を覚える,
    使いながら覚える,
    声を聞き取る,
    覚えた言葉たち,
    声を忘れる,
    覚えた声を読む,
};
