/**
 * 自分のデータを、本気で分析する
 *
 * なぜこれが要るのか:
 *
 *   「リサーチや分析が出てこない」と言われた。そのとおりだった。
 *   これまでは、数を並べるだけで「分析」と呼んでいた。
 *   数を見せられても、次に何をすればよいかは分からない。
 *
 *   分析とは、<b>数から、次にすることを導く</b>こと。
 *   「Tシャツが16点あります」ではなく、
 *   「Tシャツに寄りすぎています。他の品目を出すと客単価が上がります」まで言う。
 *
 * 正直に書いておきます:
 *
 *   <b>世の中の流行は分かりません。</b>外を見に行かない決まりだからです。
 *   分かるのは「あなたのデータが何を言っているか」だけです。
 *   そこは言い換えません。
 *
 *   ただ、それは弱い材料ではありません。
 *   よそのブランドが何をしていようと、
 *   <b>あなたの商品がどう売れたか</b>のほうが、あなたには効きます。
 *
 * 使っている考え方:
 *   資料にある「マーケティングリサーチ手法」「UXデザイン手法」から、
 *   売上分析・市場シェア分析・ペルソナの考え方を借りています。
 *
 * すべてこの端末の中だけで動きます。外部へは一切送りません。
 */

function 分析で読む(鍵) {
    try {
        const r = JSON.parse(localStorage.getItem(鍵) || '[]');
        return Array.isArray(r) ? r : [];
    } catch {
        return [];
    }
}

function 分析の今日() {
    return typeof 日付文字 === 'function'
        ? 日付文字(new Date()) : new Date().toISOString().slice(0, 10);
}

/* ==========================================================
   商品の分析
   ========================================================== */

function 商品を分析する() {
    const 品 = 分析で読む('products');
    if (!品.length) {
        return { ある: false, 見出し: '商品', 訳: 'まだ商品が登録されていません。' };
    }

    const 気づき = [];

    /* --- 品目の偏り --- */
    //
    // 品目が偏ると、客単価も伸びず、季節にも弱くなる。
    // Tシャツだけでは、冬に売るものが無い。
    const 品目 = {};
    品.forEach((p) => {
        const 型 = 品目を読む(p);
        品目[型] = (品目[型] || 0) + 1;
    });
    const 品目順 = Object.entries(品目).sort((a, b) => b[1] - a[1]);
    const 最多 = 品目順[0];

    if (最多 && 最多[1] / 品.length >= 0.6 && 品.length >= 3) {
        気づき.push({
            重さ: 2,
            件: `${最多[0]}に ${Math.round(最多[1] / 品.length * 100)}% 寄っています`,
            数: `${品.length}点中 ${最多[1]}点`,
            意味: '一つの品目に寄ると、季節に弱くなり、客単価も伸びにくくなります。'
                + 'Tシャツだけでは、冬に売るものがありません。',
            次に: '単価の高い品目（パーカー・アウター）を足すと、'
                + '同じ客数でも売上が上がります。',
        });
    }

    /* --- 値段の帯 --- */
    const 値たち = 品.map((p) => Number(p.price)).filter((n) => n > 0);
    if (値たち.length >= 3) {
        const 平均 = 値たち.reduce((a, b) => a + b, 0) / 値たち.length;
        const 最高 = Math.max(...値たち);
        const 最低 = Math.min(...値たち);
        const 幅 = 最高 / Math.max(1, 最低);

        気づき.push({
            重さ: 0,
            件: `値段の帯: ¥${最低.toLocaleString('ja-JP')} 〜 ¥${最高.toLocaleString('ja-JP')}`,
            数: `平均 ¥${Math.round(平均).toLocaleString('ja-JP')}`,
            意味: 幅 < 2
                ? '値段の幅が狭いので、「入門」と「本命」の差が付いていません。'
                : '入門から本命まで、幅が取れています。',
            次に: 幅 < 2
                ? '安い入り口を一つ作ると、初めての人が手を出しやすくなります。'
                : '',
        });
    }

    /* --- 利益 --- */
    const 原価あり = 品.filter((p) => Number(p.cost) > 0 && Number(p.price) > 0);
    if (原価あり.length) {
        const 率たち = 原価あり.map((p) => (Number(p.price) - Number(p.cost)) / Number(p.price));
        const 平均率 = 率たち.reduce((a, b) => a + b, 0) / 率たち.length;
        const 薄い = 原価あり.filter((p) =>
            (Number(p.price) - Number(p.cost)) / Number(p.price) < 0.3);

        気づき.push({
            重さ: 平均率 < 0.4 ? 2 : 0,
            件: `粗利率は平均 ${Math.round(平均率 * 100)}%`,
            数: `${原価あり.length}点から`,
            意味: 平均率 < 0.4
                ? 'アパレルは在庫・返品・送料が乗るので、' +
                  '粗利40%を切ると、売れても手元に残りません。'
                : '在庫や送料を吸収できる水準です。',
            次に: 薄い.length
                ? `特に薄いのは ${薄い.slice(0, 3).map((p) => p.name).join('、')}。`
                  + '値段を上げるか、原価を下げるか、扱いをやめるかです。'
                : '',
        });
    } else {
        気づき.push({
            重さ: 1,
            件: '原価が入っていないので、儲かっているか分かりません',
            数: `${品.length}点中 0点に原価あり`,
            意味: '売値だけでは、売れても利益が出ているか判断できません。',
            次に: '原価を入れると、粗利率と赤字商品がすぐ分かります。',
        });
    }

    /* --- 在庫の寝かせ方 --- */
    const 在庫額 = 品.reduce((a, p) =>
        a + (Number(p.quantity) || 0) * (Number(p.cost) || Number(p.price) || 0), 0);
    if (在庫額 > 0) {
        const 多い = 品.filter((p) => Number(p.quantity) >= 20);
        気づき.push({
            重さ: 多い.length ? 1 : 0,
            件: `在庫に ¥${Math.round(在庫額).toLocaleString('ja-JP')} 寝ています`,
            数: `${品.reduce((a, p) => a + (Number(p.quantity) || 0), 0)}点`,
            意味: '在庫は、売れるまで動かないお金です。'
                + '多く持つほど、次の商品を作る資金が減ります。',
            次に: 多い.length
                ? `${多い.slice(0, 3).map((p) => p.name).join('、')} が20点以上あります。`
                  + '動きが鈍いなら、値下げか、まとめ売りを考えてください。'
                : '',
        });
    }

    return {
        ある: true,
        見出し: '商品',
        数: `${品.length}点`,
        気づき: 気づき.sort((a, b) => b.重さ - a.重さ),
    };
}

function 品目を読む(p) {
    const 文 = `${p.sku || ''} ${p.name || ''} ${p.category || ''}`.toUpperCase();
    if (/TEE|Tシャツ|カットソー/.test(文)) return 'Tシャツ';
    if (/HOODIE|パーカー|フーディ/.test(文)) return 'パーカー';
    if (/SWEAT|スウェット|トレーナー/.test(文)) return 'スウェット';
    if (/SHORTS|パンツ|ボトム/.test(文)) return 'ボトム';
    if (/BAG|バッグ/.test(文)) return 'バッグ';
    if (/CAP|HAT|帽子/.test(文)) return '帽子';
    return p.category || 'その他';
}

/* ==========================================================
   SNSの分析
   ========================================================== */

function SNSを分析する() {
    const 投稿 = 分析で読む('areglm_sns_posts').concat(分析で読む('areglm_sns_queue'));
    if (!投稿.length) {
        return {
            ある: false,
            見出し: 'SNS',
            訳: 'まだ投稿の記録がありません。'
                + '投稿を作って残していくと、どの出し方が効いたかが見えてきます。',
        };
    }

    const 気づき = [];

    /* --- どこに出しているか --- */
    const 場所 = {};
    投稿.forEach((x) => {
        const p = x.platform || x.場所 || '未設定';
        場所[p] = (場所[p] || 0) + 1;
    });
    const 場所順 = Object.entries(場所).sort((a, b) => b[1] - a[1]);

    気づき.push({
        重さ: 場所順.length === 1 ? 1 : 0,
        件: '出している場所: ' + 場所順.map(([k, v]) => `${k}（${v}件）`).join('、'),
        数: `${投稿.length}件`,
        意味: 場所順.length === 1
            ? '一か所だけだと、そこの調子が悪いときに打つ手がありません。'
            : '複数に出せています。',
        次に: 場所順.length === 1
            ? '同じ内容でも、もう一か所に出すだけで届く人が増えます。'
            : '',
    });

    /* --- 出す間隔 --- */
    const 日付 = 投稿.map((x) => (x.date || x.createdAt || '').slice(0, 10))
        .filter(Boolean).sort();
    if (日付.length >= 3) {
        const 最初 = new Date(日付[0]);
        const 最後 = new Date(日付[日付.length - 1]);
        const 日数 = Math.max(1, Math.round((最後 - 最初) / 86400000));
        const 間隔 = 日数 / 投稿.length;

        const 空き = 日数の差を数える(日付);

        気づき.push({
            重さ: 間隔 > 7 ? 2 : 0,
            件: `平均 ${間隔.toFixed(1)}日に1回 出しています`,
            数: `${日数}日で ${投稿.length}件`,
            意味: 間隔 > 7
                ? '間隔が空くと、見る人の頭から消えます。' +
                  'SNSは、覚えてもらうまで続けるものです。'
                : '続けられています。',
            次に: 間隔 > 7
                ? '週に2回でも、決めて続けるほうが効きます。' +
                  '「自動で動く決まり」に入れると、こちらから知らせます。'
                : (空き.最長 > 14
                    ? `いちばん空いたのは ${空き.最長}日です。そこで一度切れています。`
                    : ''),
        });
    }

    /* --- 何を書いているか --- */
    const 文字数 = 投稿.map((x) => String(x.caption || x.text || x.本文 || '').length)
        .filter((n) => n > 0);
    if (文字数.length) {
        const 平均 = 文字数.reduce((a, b) => a + b, 0) / 文字数.length;
        気づき.push({
            重さ: 0,
            件: `本文は平均 ${Math.round(平均)}文字`,
            数: `${文字数.length}件から`,
            意味: 平均 < 30
                ? '短すぎると、何のための投稿か伝わりません。'
                : (平均 > 300 ? '長いと最後まで読まれません。' : '読みやすい長さです。'),
            次に: '',
        });
    }

    return {
        ある: true,
        見出し: 'SNS',
        数: `${投稿.length}件`,
        気づき: 気づき.sort((a, b) => b.重さ - a.重さ),
    };
}

function 日数の差を数える(日付たち) {
    let 最長 = 0;
    for (let i = 1; i < 日付たち.length; i++) {
        const 差 = Math.round((new Date(日付たち[i]) - new Date(日付たち[i - 1])) / 86400000);
        if (差 > 最長) 最長 = 差;
    }
    return { 最長 };
}

/* ==========================================================
   売上の分析
   ========================================================== */

function 売上を分析する() {
    const 売 = 分析で読む('areglm_sales').concat(分析で読む('sales'));
    if (!売.length) {
        return {
            ある: false,
            見出し: '売上',
            訳: 'まだ売上の記録がありません。'
                + '記録すると、何が・いつ・いくらで売れたかが分析できます。',
        };
    }

    const 気づき = [];

    const 合計 = 売.reduce((a, s) => a + (Number(s.total) || Number(s.amount) || 0), 0);
    気づき.push({
        重さ: 0,
        件: `売上の合計 ¥${Math.round(合計).toLocaleString('ja-JP')}`,
        数: `${売.length}件`,
        意味: '',
        次に: '',
    });

    /* --- 何が売れているか（浸透市場） --- */
    const 商品別 = {};
    売.forEach((s) => {
        const 名 = s.product || s.name || s.商品 || '不明';
        商品別[名] = (商品別[名] || 0) + (Number(s.total) || Number(s.amount) || 0);
    });
    const 順 = Object.entries(商品別).sort((a, b) => b[1] - a[1]);

    if (順.length >= 2) {
        const 上位 = 順[0];
        const 割合 = 上位[1] / Math.max(1, 合計);
        気づき.push({
            重さ: 割合 > 0.6 ? 2 : 0,
            件: `いちばん売れているのは「${上位[0]}」（全体の ${Math.round(割合 * 100)}%）`,
            数: `¥${Math.round(上位[1]).toLocaleString('ja-JP')}`,
            意味: 割合 > 0.6
                ? '一つの商品に頼りすぎています。' +
                  'それが飽きられたとき、売上がまとめて落ちます。'
                : '偏りすぎてはいません。',
            次に: 割合 > 0.6
                ? `「${上位[0]}」の色違い・形違いを出すと、`
                  + '同じ良さのまま、支えを増やせます。'
                : '',
        });

        const 売れていない = 分析で読む('products')
            .filter((p) => !商品別[p.name])
            .slice(0, 3);
        if (売れていない.length) {
            気づき.push({
                重さ: 1,
                件: `一度も売れていない商品が ${売れていない.length}点`,
                数: 売れていない.map((p) => p.name).join('、'),
                意味: '作ったが動いていないものです。'
                    + '原因は、値段・見せ方・そもそもの需要のどれかです。',
                次に: '写真を撮り直すか、値段を見直すか、扱いをやめるかを決めてください。',
            });
        }
    }

    return {
        ある: true,
        見出し: '売上',
        数: `${売.length}件 / ¥${Math.round(合計).toLocaleString('ja-JP')}`,
        気づき: 気づき.sort((a, b) => b.重さ - a.重さ),
    };
}

/* ==========================================================
   まとめて分析する
   ========================================================== */

function すべて分析する() {
    const 結果 = [商品を分析する(), SNSを分析する(), 売上を分析する()];

    const 全部の気づき = [];
    結果.forEach((r) => {
        (r.気づき || []).forEach((x) => 全部の気づき.push(Object.assign({ どこ: r.見出し }, x)));
    });

    const 手を打つ = 全部の気づき.filter((x) => x.重さ >= 2);

    return {
        まとめ: 手を打つ.length
            ? `手を打ったほうがよい点が ${手を打つ.length}件 あります。`
            : (全部の気づき.length
                ? '大きく崩れているところはありません。'
                : 'まだ分析できるだけのデータがありません。'),
        区分: 結果,
        手を打つ,
    };
}

window.商品を分析する = 商品を分析する;
window.SNSを分析する = SNSを分析する;
window.売上を分析する = 売上を分析する;
window.すべて分析する = すべて分析する;
