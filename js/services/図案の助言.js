/**
 * 図案について、こちらから助言する
 *
 * なぜこれを作るのか:
 *   図案を出すだけなら、ただの道具でしかない。
 *   聞かれるまで黙っているのでは、助けたことにならない。
 *
 *   服の柄は、印刷の現場に渡した時点で制約にぶつかる。
 *   色数が多ければ版代が上がり、線が細ければ潰れ、
 *   継ぎ目が合わなければ生地の上で柄がずれる。
 *
 *   それを、渡してから言われるのでは遅い。
 *   作った瞬間に、こちらから言う。
 *
 * ここで見るもの:
 *   ・色数（版代に効く）
 *   ・いちばん細い線（潰れる）
 *   ・繰り返しの継ぎ目（生地でずれる）
 *   ・印刷に足りる大きさか
 *
 * これは「たぶん」の話ではなく、絵から数えて出しています。
 * 数えられないことは言いません。
 */

/** シルクスクリーンで、これを超えると版代がはっきり上がる */
const 色数の目安 = 4;

/** これより細い線は、プリントで潰れやすい（ピクセル） */
const 潰れる細さ = 3;

/** 服のプリントで、ふつうに使える解像度（1インチあたりの点） */
const 印刷の細かさ = 300;

/**
 * 絵の中の色を数える。
 *
 * まったく同じ色だけを数えると、
 * にじみで1つの色が何十色にも見えてしまう。
 * 近い色はまとめて数える。
 */
function 色を数える(canvas) {
    const g = canvas.getContext('2d');
    const 幅 = Math.min(canvas.width, 256);
    const 高 = Math.min(canvas.height, 256);

    // 小さく写し取ってから数える。元のまま数えると重い。
    const 小 = document.createElement('canvas');
    小.width = 幅;
    小.height = 高;
    小.getContext('2d').drawImage(canvas, 0, 0, 幅, 高);

    const 点 = 小.getContext('2d').getImageData(0, 0, 幅, 高).data;
    const 数え = new Map();

    for (let i = 0; i < 点.length; i += 4) {
        if (点[i + 3] < 20) continue;                 // 透明なところは数えない
        // 16段階に丸めてから数える（にじみをまとめる）
        const 鍵 = ((点[i] >> 4) << 8) | ((点[i + 1] >> 4) << 4) | (点[i + 2] >> 4);
        数え.set(鍵, (数え.get(鍵) || 0) + 1);
    }

    const 全 = [...数え.values()].reduce((a, b) => a + b, 0) || 1;

    // 全体の0.5%に満たない色は、にじみとみなして数えない
    return [...数え.values()].filter((n) => n / 全 >= 0.005).length;
}

/**
 * いちばん細い線を探す。
 *
 * 横一列ずつ見て、色が変わってから次に変わるまでの長さを測る。
 * その最小が、いちばん細いところ。
 */
function 細さを測る(canvas) {
    const 幅 = Math.min(canvas.width, 512);
    const 小 = document.createElement('canvas');
    小.width = 幅;
    小.height = 幅;
    小.getContext('2d').drawImage(canvas, 0, 0, 幅, 幅);
    const 点 = 小.getContext('2d').getImageData(0, 0, 幅, 幅).data;

    let 最小 = Infinity;

    // 全部の行を見ると重いので、間引いて見る
    for (let y = 0; y < 幅; y += 8) {
        let 続き = 0;
        let 前 = -1;
        for (let x = 0; x < 幅; x++) {
            const i = (y * 幅 + x) * 4;
            const 今 = (点[i] >> 5) << 10 | (点[i + 1] >> 5) << 5 | (点[i + 2] >> 5);
            if (今 === 前) {
                続き += 1;
            } else {
                // 1点だけの変化は、にじみなので数えない
                if (前 >= 0 && 続き >= 2) 最小 = Math.min(最小, 続き);
                前 = 今;
                続き = 1;
            }
        }
    }
    return 最小 === Infinity ? 幅 : 最小;
}

/**
 * 繰り返したときに継ぎ目が出ないかを見る。
 *
 * 左端と右端、上端と下端を突き合わせて、
 * どれだけ食い違うかを測る。
 * 継ぎ目のない柄なら、ここがほぼ揃う。
 */
function 継ぎ目を測る(canvas) {
    const n = Math.min(canvas.width, 256);
    const 小 = document.createElement('canvas');
    小.width = n;
    小.height = n;
    小.getContext('2d').drawImage(canvas, 0, 0, n, n);
    const 点 = 小.getContext('2d').getImageData(0, 0, n, n).data;

    const 色 = (x, y) => {
        const i = (y * n + x) * 4;
        return [点[i], 点[i + 1], 点[i + 2]];
    };
    const 差 = (a, b) =>
        (Math.abs(a[0] - b[0]) + Math.abs(a[1] - b[1]) + Math.abs(a[2] - b[2])) / 3;

    let 横 = 0;
    let 縦 = 0;
    for (let i = 0; i < n; i++) {
        横 += 差(色(0, i), 色(n - 1, i));
        縦 += 差(色(i, 0), 色(i, n - 1));
    }
    // 0に近いほど、継ぎ目が目立たない
    return { 横: 横 / n, 縦: 縦 / n };
}

/**
 * 図案を見て、こちらから言うべきことをまとめる。
 *
 * @param {HTMLCanvasElement} canvas
 * @param {object} 情報 { 柄, 用途 }
 * @returns {{助言: Array, 数字: object}}
 */
function 図案を見て助言する(canvas, 情報 = {}) {
    const 色数 = 色を数える(canvas);
    const 細さ = 細さを測る(canvas);
    const 継ぎ目 = 継ぎ目を測る(canvas);
    const 辺 = canvas.width;

    const 助言 = [];

    /* --- 色数 --- */
    if (色数 > 色数の目安) {
        助言.push({
            重さ: 2,
            件: `色が ${色数}色 あります`,
            訳: `シルクスクリーンは色ごとに版を作るので、${色数}色だと版代が${色数}倍近くかかります。`
                + `${色数の目安}色までに抑えると、小ロットでも現実的な値段になります。`,
            手: 'DTG（インクジェット）で刷るなら色数は効きません。',
            // こちらで直せるもの。言うだけで終わらせない。
            直す: { 種類: '色を減らす', 目標: 色数の目安 },
        });
    } else {
        助言.push({
            重さ: 0,
            件: `色は ${色数}色`,
            訳: 'シルクスクリーンでも版代が抑えられる色数です。',
            手: '',
        });
    }

    /* --- 線の細さ --- */
    const 実寸mm = (細さ / 辺) * 250;     // 25cm幅にプリントした場合のmm
    if (細さ < 潰れる細さ) {
        助言.push({
            重さ: 3,
            件: `いちばん細いところが ${細さ}点しかありません`,
            訳: `25cm幅で刷ると約 ${実寸mm.toFixed(2)}mm になります。`
                + 'この細さはインクがつながらず、途切れるか消えます。',
            手: '柄を大きくすれば、線も太くなります。',
            直す: { 種類: '柄を大きく' },
        });
    } else if (実寸mm < 0.5) {
        助言.push({
            重さ: 2,
            件: `細い線があります（約 ${実寸mm.toFixed(2)}mm）`,
            訳: '生地の織り目に負けて、かすれることがあります。',
            手: '0.5mm 以上にするか、試し刷りで確かめてください。',
        });
    }

    /* --- 継ぎ目 --- */
    const 目立つ = Math.max(継ぎ目.横, 継ぎ目.縦);
    if (目立つ > 30) {
        助言.push({
            重さ: 2,
            件: '繰り返すと継ぎ目が出ます',
            訳: '左右・上下の端が揃っていません。生地に敷き詰めると、そこに線が見えます。',
            手: '端が揃う描き方で作り直します。',
            直す: { 種類: '継ぎ目なしにする' },
        });
    } else if (目立つ < 8) {
        助言.push({
            重さ: 0,
            件: '継ぎ目が出ません',
            訳: '端が揃っているので、生地に敷き詰めても線が見えません。',
            手: '',
        });
    }

    /* --- 大きさ --- */
    const 刷れる幅cm = (辺 / 印刷の細かさ) * 2.54;
    if (刷れる幅cm < 20) {
        助言.push({
            重さ: 2,
            件: `この大きさでは ${刷れる幅cm.toFixed(1)}cm 幅までです`,
            訳: `${印刷の細かさ}dpi で刷る前提だと、これ以上に伸ばすと粗くなります。`,
            手: '前身頃いっぱいに使うなら、もっと大きく作り直します。',
            直す: { 種類: '大きく作り直す', 目標: 2048 },
        });
    } else {
        助言.push({
            重さ: 0,
            件: `${刷れる幅cm.toFixed(0)}cm 幅まで刷れます`,
            訳: `${印刷の細かさ}dpi 換算。前身頃いっぱいでも足ります。`,
            手: '',
        });
    }

    助言.sort((a, b) => b.重さ - a.重さ);

    return {
        助言,
        数字: {
            色数,
            いちばん細い点: 細さ,
            '25cm幅でのmm': Number(実寸mm.toFixed(2)),
            継ぎ目の食い違い: Number(目立つ.toFixed(1)),
            '刷れる幅cm': Number(刷れる幅cm.toFixed(1)),
        },
    };
}

window.図案を見て助言する = 図案を見て助言する;
window.図案の色を数える = 色を数える;
