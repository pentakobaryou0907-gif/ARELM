/**
 * SNSの成績を残して、何が効いたかを見る
 *
 * なぜこれを作るのか:
 *
 *   noimos AI のようなことをしたい、と言われた。
 *   実際に見に行った。月 $99〜499 の有料サービスで、
 *   売りは「トレンド分析」「投稿作成」「DM管理」だった。
 *
 *   このうち<b>分析とグラフ化は、外へつながなくても作れる</b>。
 *   そして、そこがいちばん効く部分でもある。
 *
 *   よそのトレンドを追うより、
 *   <b>自分の投稿がどう効いたか</b>のほうが、自分には効く。
 *   同じ服を、同じ人たちに売っているのだから。
 *
 * 何をするのか:
 *
 *   投稿ごとに「いつ・どこに・何を出して・どう反応があったか」を残す。
 *   貯まってくると、こういうことが分かる:
 *     ・どの曜日・時間帯が効くか
 *     ・写真と文章、どちらの型が効くか
 *     ・長い文と短い文、どちらが読まれるか
 *     ・伸びが落ちてきていないか
 *
 * 正直に書いておきます:
 *
 *   <b>数字は自分で入れる必要があります。</b>
 *   各SNSから自動で取ってくるには、公式APIにつなぐ必要があり、
 *   それは「外へ送らない」という決まりに反します。
 *
 *   ただ、入れるのは投稿1件につき3つの数字だけです。
 *   その手間で、何が効いたかが分かるようになります。
 *
 * すべてこの端末の中だけで動きます。外部へは一切送りません。
 */

const 成績の鍵 = 'areglm_sns_metrics';

/** 見ている数字 */
const 数字の種類 = [
    { 鍵: '表示', 題: '見られた数', 説: 'インプレッション／再生数' },
    { 鍵: '反応', 題: 'いいね等', 説: 'いいね・保存・コメントの合計' },
    { 鍵: '流入', 題: 'プロフィール流入', 説: 'そこから見に来た数' },
];

function 成績を読む() {
    try {
        const r = JSON.parse(localStorage.getItem(成績の鍵) || '[]');
        return Array.isArray(r) ? r : [];
    } catch {
        return [];
    }
}

function 成績を書く(一覧) {
    localStorage.setItem(成績の鍵, JSON.stringify(一覧.slice(-500)));
}

/**
 * 一件を残す。
 *
 * 同じ投稿の数字を後から直せるようにしてある。
 * 投稿直後と1週間後では、数字が違うため。
 */
function 成績を残す(中身) {
    const 一覧 = 成績を読む();
    // 目印は、時刻だけでは足りない。
    //
    // はじめ Date.now() だけにしていたところ、
    // まとめて入れたときに同じミリ秒になり、
    // 12件入れたのに3件しか残らなかった。
    // 同じ目印は「後から直した」とみなされ、上書きされるため。
    const 目印 = 中身.id
        || ('m_' + Date.now() + '_' + Math.random().toString(36).slice(2, 7));

    const 既に = 一覧.findIndex((x) => x.id === 目印);
    const 一件 = {
        id: 目印,
        場所: 中身.場所 || 'Instagram',
        日: 中身.日 || (typeof 日付文字 === 'function'
            ? 日付文字(new Date()) : new Date().toISOString().slice(0, 10)),
        時: 中身.時 != null ? Number(中身.時) : new Date().getHours(),
        本文: String(中身.本文 || '').slice(0, 500),
        型: 中身.型 || '写真',
        表示: Number(中身.表示) || 0,
        反応: Number(中身.反応) || 0,
        流入: Number(中身.流入) || 0,
        商品: 中身.商品 || '',
        直した日: new Date().toISOString(),
    };

    if (既に >= 0) 一覧[既に] = 一件;
    else 一覧.push(一件);

    成績を書く(一覧);
    return 一件;
}

/* ==========================================================
   分析

   数を出すだけにしない。
   「その数が何を意味し、次に何をすればよいか」まで出す。
   ========================================================== */

/** 反応率（見られたうち、どれだけ反応したか） */
function 反応率(x) {
    return x.表示 > 0 ? x.反応 / x.表示 : 0;
}

function 平均(数たち) {
    const 有効 = 数たち.filter((n) => !Number.isNaN(n));
    return 有効.length ? 有効.reduce((a, b) => a + b, 0) / 有効.length : 0;
}

/**
 * どの時間帯が効くか。
 *
 * 出す時間で反応がまるで違うのに、
 * 何となく出していると気づけない。
 */
function 時間帯を見る(一覧) {
    if (一覧.length < 6) return null;

    const 帯 = {
        '朝（5-10時）': [5, 10],
        '昼（11-14時）': [11, 14],
        '夕（15-18時）': [15, 18],
        '夜（19-23時）': [19, 23],
        '深夜（0-4時）': [0, 4],
    };

    const 結果 = [];
    Object.entries(帯).forEach(([名, [始, 終]]) => {
        const 該当 = 一覧.filter((x) => x.時 >= 始 && x.時 <= 終 && x.表示 > 0);
        if (該当.length >= 2) {
            結果.push({
                名,
                件数: 該当.length,
                反応率: 平均(該当.map(反応率)),
                表示: 平均(該当.map((x) => x.表示)),
            });
        }
    });

    if (結果.length < 2) return null;
    結果.sort((a, b) => b.反応率 - a.反応率);

    const 良 = 結果[0];
    const 悪 = 結果[結果.length - 1];
    const 差 = 悪.反応率 > 0 ? 良.反応率 / 悪.反応率 : 0;

    return {
        件: `${良.名}がいちばん効いています`,
        数: `反応率 ${(良.反応率 * 100).toFixed(1)}%（${良.件数}件）`,
        意味: 差 >= 1.5
            ? `${悪.名}の ${差.toFixed(1)}倍 です。出す時間で、これだけ違います。`
            : '時間帯による差は、それほど大きくありません。',
        次に: 差 >= 1.5
            ? `${良.名}に寄せると、同じ手間で反応が増えます。`
                + '「自動で動く決まり」に入れると、その時間に知らせます。'
            : '',
        重さ: 差 >= 1.5 ? 2 : 0,
        並び: 結果,
    };
}

/** どの曜日が効くか */
function 曜日を見る(一覧) {
    if (一覧.length < 7) return null;

    const 曜日名 = ['日', '月', '火', '水', '木', '金', '土'];
    const 結果 = [];

    曜日名.forEach((名, i) => {
        const 該当 = 一覧.filter((x) => new Date(x.日).getDay() === i && x.表示 > 0);
        if (該当.length >= 1) {
            結果.push({ 名, 件数: 該当.length, 反応率: 平均(該当.map(反応率)) });
        }
    });

    if (結果.length < 3) return null;
    const 並び = [...結果].sort((a, b) => b.反応率 - a.反応率);

    return {
        件: `${並び[0].名}曜日がいちばん効いています`,
        数: `反応率 ${(並び[0].反応率 * 100).toFixed(1)}%（${並び[0].件数}件）`,
        意味: '',
        次に: '',
        重さ: 0,
        並び: 結果,
    };
}

/** どの型（写真・動画・文章）が効くか */
function 型を見る(一覧) {
    const 型たち = {};
    一覧.filter((x) => x.表示 > 0).forEach((x) => {
        const t = x.型 || '写真';
        if (!型たち[t]) 型たち[t] = [];
        型たち[t].push(x);
    });

    const 結果 = Object.entries(型たち)
        .filter(([, v]) => v.length >= 2)
        .map(([k, v]) => ({ 名: k, 件数: v.length, 反応率: 平均(v.map(反応率)) }))
        .sort((a, b) => b.反応率 - a.反応率);

    if (結果.length < 2) return null;

    const 差 = 結果[結果.length - 1].反応率 > 0
        ? 結果[0].反応率 / 結果[結果.length - 1].反応率 : 0;

    return {
        件: `「${結果[0].名}」がいちばん効いています`,
        数: `反応率 ${(結果[0].反応率 * 100).toFixed(1)}%（${結果[0].件数}件）`,
        意味: 差 >= 1.5
            ? `「${結果[結果.length - 1].名}」の ${差.toFixed(1)}倍 です。`
            : '型による差は、それほど大きくありません。',
        次に: 差 >= 1.5 ? `「${結果[0].名}」を増やすと、反応が増えます。` : '',
        重さ: 差 >= 1.5 ? 1 : 0,
        並び: 結果,
    };
}

/** 本文の長さが効いているか */
function 長さを見る(一覧) {
    const 有効 = 一覧.filter((x) => x.表示 > 0 && x.本文);
    if (有効.length < 6) return null;

    const 短 = 有効.filter((x) => x.本文.length < 60);
    const 長 = 有効.filter((x) => x.本文.length >= 60);
    if (短.length < 2 || 長.length < 2) return null;

    const 短率 = 平均(短.map(反応率));
    const 長率 = 平均(長.map(反応率));
    const 良い方 = 短率 > 長率 ? '短い文' : '長い文';
    const 差 = Math.max(短率, 長率) / Math.max(0.0001, Math.min(短率, 長率));

    return {
        件: `${良い方}のほうが効いています`,
        数: `短い ${(短率 * 100).toFixed(1)}% / 長い ${(長率 * 100).toFixed(1)}%`,
        意味: 差 >= 1.4 ? `${差.toFixed(1)}倍の差があります。` : '大きな差はありません。',
        次に: 差 >= 1.4 ? `${良い方}に寄せてみてください。` : '',
        重さ: 差 >= 1.4 ? 1 : 0,
    };
}

/** 伸びているか、落ちているか */
function 流れを見る(一覧) {
    const 有効 = 一覧.filter((x) => x.表示 > 0)
        .sort((a, b) => new Date(a.日) - new Date(b.日));
    if (有効.length < 8) return null;

    const 半 = Math.floor(有効.length / 2);
    const 前半 = 平均(有効.slice(0, 半).map((x) => x.表示));
    const 後半 = 平均(有効.slice(半).map((x) => x.表示));
    const 変化 = 前半 > 0 ? (後半 - 前半) / 前半 : 0;

    return {
        件: 変化 >= 0.1 ? '見られる数が伸びています'
            : (変化 <= -0.1 ? '見られる数が落ちています' : '横ばいです'),
        数: `${Math.round(前半).toLocaleString('ja-JP')} → ${Math.round(後半).toLocaleString('ja-JP')}`
            + `（${変化 >= 0 ? '+' : ''}${Math.round(変化 * 100)}%）`,
        意味: 変化 <= -0.2
            ? '落ち方が大きいです。'
                + '同じことを続けても戻らないので、型か時間帯を変える必要があります。'
            : (変化 >= 0.2 ? 'いま効いているやり方があります。' : ''),
        次に: 変化 <= -0.2
            ? '効いていた時間帯・型に戻すか、新しい型を試してください。'
            : (変化 >= 0.2 ? '直近で効いた投稿の型を、続けてください。' : ''),
        重さ: 変化 <= -0.2 ? 2 : 0,
    };
}

/** いちばん効いた投稿・効かなかった投稿 */
function 良し悪しを見る(一覧) {
    const 有効 = 一覧.filter((x) => x.表示 > 0);
    if (有効.length < 4) return null;

    const 並び = [...有効].sort((a, b) => 反応率(b) - 反応率(a));
    return {
        良: 並び.slice(0, 3),
        悪: 並び.slice(-2),
    };
}

/**
 * まとめて分析する。
 */
function SNS成績を分析する(場所) {
    let 一覧 = 成績を読む();
    if (場所 && 場所 !== 'すべて') 一覧 = 一覧.filter((x) => x.場所 === 場所);

    if (一覧.length < 3) {
        return {
            足りる: false,
            件数: 一覧.length,
            訳: `いま ${一覧.length}件です。`
                + '3件をこえると、時間帯や型の違いが見えはじめます。'
                + '10件たまると、はっきり分かるようになります。',
        };
    }

    const 気づき = [
        流れを見る(一覧),
        時間帯を見る(一覧),
        型を見る(一覧),
        長さを見る(一覧),
        曜日を見る(一覧),
    ].filter(Boolean);

    気づき.sort((a, b) => (b.重さ || 0) - (a.重さ || 0));

    return {
        足りる: true,
        件数: 一覧.length,
        気づき,
        時間帯: 時間帯を見る(一覧),
        曜日: 曜日を見る(一覧),
        型: 型を見る(一覧),
        良し悪し: 良し悪しを見る(一覧),
        推移: 一覧.filter((x) => x.表示 > 0)
            .sort((a, b) => new Date(a.日) - new Date(b.日))
            .map((x) => ({ 日: x.日, 表示: x.表示, 反応: x.反応, 流入: x.流入 })),
    };
}

/** どの場所に出しているか */
function 場所の一覧() {
    const 場所 = {};
    成績を読む().forEach((x) => { 場所[x.場所] = (場所[x.場所] || 0) + 1; });
    return Object.entries(場所).sort((a, b) => b[1] - a[1]);
}

