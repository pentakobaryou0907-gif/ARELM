/**
 * 音を数値に変える（自作の音声認識の土台）
 *
 * なぜ一から作るのか:
 *   ・ブラウザ標準の認識は、音声をGoogleへ送ってしまう
 *   ・macOS の認識は、有料の署名がないと許可が下りない
 *   どちらも使えないので、自分で作る。
 *
 * 何ができて、何ができないか（先に書く）:
 *
 *   できること
 *     ・あなたが教えた言葉を聞き分ける（「アレラム」「今日の状況」など）
 *     ・教えた本人の声に、よく合う
 *     ・音声は一切外へ出ない
 *
 *   できないこと
 *     ・教えていない言葉は聞き取れない
 *     ・自由な文章の書き起こし
 *     　それには大量の音声で学習したモデルが要る。
 *     　「何でも聞き取れます」とは言わない。
 *
 * 仕組み:
 *   音を「メル周波数ケプストラム係数（MFCC）」という数値の並びに直す。
 *   これは人の耳の感じ方に合わせて音を要約したもので、
 *   同じ言葉なら似た並びになり、違う言葉なら違う並びになる。
 *
 *   話す速さは毎回ちがうので、単純に比べても合わない。
 *   そこで DTW（動的時間伸縮）で、伸び縮みを吸収して比べる。
 *
 * これは深層学習より前からある、確立した方法。
 * 語彙が少なく、話す人が決まっていれば、実用になる。
 *
 * すべてこの端末の中だけで計算する。外部へは一切送らない。
 */

/* ==========================================================
   1. フーリエ変換（音を周波数に分ける）
   ========================================================== */

/**
 * 高速フーリエ変換。
 *
 * 音の波形は「いろいろな高さの音が重なったもの」で、
 * これを高さごとの強さに分ける。
 *
 * 長さは2のべき乗でなければならない。
 * その前提で書くほうが、速くて短く済むため。
 */
function fft(実部, 虚部) {
    const n = 実部.length;
    if (n <= 1) return;

    // ビット反転で並べ替える。こうすると、その場で計算できる。
    for (let i = 1, j = 0; i < n; i++) {
        let bit = n >> 1;
        for (; j & bit; bit >>= 1) j ^= bit;
        j ^= bit;
        if (i < j) {
            [実部[i], 実部[j]] = [実部[j], 実部[i]];
            [虚部[i], 虚部[j]] = [虚部[j], 虚部[i]];
        }
    }

    for (let 長さ = 2; 長さ <= n; 長さ <<= 1) {
        const 角 = (-2 * Math.PI) / 長さ;
        const wr = Math.cos(角);
        const wi = Math.sin(角);

        for (let i = 0; i < n; i += 長さ) {
            let cr = 1;
            let ci = 0;
            for (let j = 0; j < 長さ / 2; j++) {
                const a = i + j;
                const b = i + j + 長さ / 2;

                const tr = 実部[b] * cr - 虚部[b] * ci;
                const ti = 実部[b] * ci + 虚部[b] * cr;

                実部[b] = 実部[a] - tr;
                虚部[b] = 虚部[a] - ti;
                実部[a] += tr;
                虚部[a] += ti;

                const 次r = cr * wr - ci * wi;
                ci = cr * wi + ci * wr;
                cr = 次r;
            }
        }
    }
}

/* ==========================================================
   2. メル尺度（人の耳の感じ方に合わせる）
   ========================================================== */

/**
 * 周波数をメル尺度に直す。
 *
 * 人の耳は、低い音の違いには敏感で、高い音の違いには鈍い。
 * 100Hz と 200Hz は倍違って聞こえるが、
 * 5000Hz と 5100Hz はほとんど同じに聞こえる。
 * その感じ方に合わせて目盛りを取り直す。
 */
function メルに直す(hz) {
    return 2595 * Math.log10(1 + hz / 700);
}

function メルから戻す(mel) {
    return 700 * (10 ** (mel / 2595) - 1);
}

/**
 * メルの帯を作る。
 *
 * 周波数を、耳の感じ方に沿った帯に分ける。
 * 帯ごとの強さを見れば、音の「色」が分かる。
 */
function メル帯を作る(帯数, フレーム長, 標本化周波数) {
    const 下 = メルに直す(80);      // 80Hz より下は、話し声にほぼ含まれない
    const 上 = メルに直す(標本化周波数 / 2);
    const 点 = [];

    for (let i = 0; i < 帯数 + 2; i++) {
        const mel = 下 + ((上 - 下) * i) / (帯数 + 1);
        点.push(Math.floor(((フレーム長 + 1) * メルから戻す(mel)) / 標本化周波数));
    }

    const 帯たち = [];
    for (let m = 1; m <= 帯数; m++) {
        const 帯 = new Float32Array(フレーム長 / 2 + 1);
        for (let k = 点[m - 1]; k < 点[m]; k++) {
            帯[k] = (k - 点[m - 1]) / (点[m] - 点[m - 1] || 1);
        }
        for (let k = 点[m]; k < 点[m + 1]; k++) {
            帯[k] = (点[m + 1] - k) / (点[m + 1] - 点[m] || 1);
        }
        帯たち.push(帯);
    }
    return 帯たち;
}

/* ==========================================================
   3. MFCC（音の特徴を数値の並びにする）
   ========================================================== */

const フレーム長 = 512;      // 一度に見る音の長さ（点の数）
const フレーム間隔 = 256;    // 次のフレームまでの間隔。半分ずらして見る。
const 帯数 = 26;             // メル帯の数
const 係数の数 = 13;         // 取り出す係数。多すぎると雑音まで拾う。

let メル帯の控え = null;
let 控えの周波数 = 0;

/**
 * 音の波形を、MFCC の並びに直す。
 *
 * @param {Float32Array} 波形
 * @param {number} 標本化周波数
 * @returns {Float32Array[]} フレームごとの係数の並び
 */
function MFCCにする(波形, 標本化周波数) {
    if (!メル帯の控え || 控えの周波数 !== 標本化周波数) {
        メル帯の控え = メル帯を作る(帯数, フレーム長, 標本化周波数);
        控えの周波数 = 標本化周波数;
    }

    const 結果 = [];

    for (let 開始 = 0; 開始 + フレーム長 <= 波形.length; 開始 += フレーム間隔) {
        const 実 = new Float64Array(フレーム長);
        const 虚 = new Float64Array(フレーム長);

        for (let i = 0; i < フレーム長; i++) {
            // ハミング窓。切り取った端で音がぶつ切りになるのを和らげる。
            const 窓 = 0.54 - 0.46 * Math.cos((2 * Math.PI * i) / (フレーム長 - 1));
            実[i] = 波形[開始 + i] * 窓;
        }

        fft(実, 虚);

        // 強さを出す
        const 強さ = new Float64Array(フレーム長 / 2 + 1);
        for (let i = 0; i <= フレーム長 / 2; i++) {
            強さ[i] = (実[i] * 実[i] + 虚[i] * 虚[i]) / フレーム長;
        }

        // メル帯ごとにまとめて、対数を取る。
        // 対数を取るのは、人の耳が音の大きさを対数的に感じるため。
        const 帯の値 = new Float64Array(帯数);
        for (let m = 0; m < 帯数; m++) {
            let 和 = 0;
            const 帯 = メル帯の控え[m];
            for (let k = 0; k < 帯.length; k++) 和 += 強さ[k] * 帯[k];
            帯の値[m] = Math.log(和 + 1e-10);
        }

        // 離散コサイン変換。帯どうしの重なりをほどいて、少ない数にまとめる。
        const 係数 = new Float32Array(係数の数);
        for (let i = 0; i < 係数の数; i++) {
            let 和 = 0;
            for (let m = 0; m < 帯数; m++) {
                和 += 帯の値[m] * Math.cos((Math.PI * i * (m + 0.5)) / 帯数);
            }
            係数[i] = 和;
        }

        結果.push(係数);
    }

    return 結果;
}

/* ==========================================================
   4. 声のある部分だけを取り出す
   ========================================================== */

/**
 * 前後の無音を落とす。
 *
 * 押してから話し始めるまでの間や、
 * 話し終わってから離すまでの間が入ると、
 * 同じ言葉でも長さが変わって比べにくくなる。
 */
/**
 * 声の部分を切り出す
 *
 * <b>呼び名は長くても1.5秒。</b>それ以上は前置きか後始末。
 *
 * ここで長いまま覚えていたため、
 * 覚えた声の74〜90%が無音になっていた。
 * すると:
 *   ・実際の声と合わない（聞き取れない）
 *   ・静かなときに「似ている」と判断する（誤って反応する）
 * という、正反対に見える二つの症状が同時に出ていた。
 *
 * 前後を削るだけでは足りない。
 * 声が最後まで続く録音では、一つも削れないため。
 * 削ったうえで、<b>いちばん声の濃いところ</b>を取る。
 */
function 声の部分を切り出す(波形) {
    // 全体の音量から、静かなときの目安を取る
    let 最大 = 0;
    for (let i = 0; i < 波形.length; i++) {
        const v = Math.abs(波形[i]);
        if (v > 最大) 最大 = v;
    }
    if (最大 < 0.01) return null;   // ほぼ無音。声が入っていない。

    const 境 = 最大 * 0.12;
    const 窓 = 400;

    let 始 = 0;
    let 終 = 波形.length;

    for (let i = 0; i + 窓 < 波形.length; i += 100) {
        let 和 = 0;
        for (let j = 0; j < 窓; j++) 和 += Math.abs(波形[i + j]);
        if (和 / 窓 > 境) { 始 = Math.max(0, i - 800); break; }
    }

    for (let i = 波形.length - 窓; i > 0; i -= 100) {
        let 和 = 0;
        for (let j = 0; j < 窓; j++) 和 += Math.abs(波形[i + j]);
        if (和 / 窓 > 境) { 終 = Math.min(波形.length, i + 窓 + 800); break; }
    }

    if (終 - 始 < 1600) return null;   // 短すぎる。物音のたぐい。
    // ここまでで前後は削れた。
    // だが、声が途切れずに続く録音では一つも削れない。
    // その場合に備えて、いちばん声の濃いところを取る。
    const 切った = 波形.slice(始, 終);

    // 呼び名の長さの上限。これを超えるなら、濃いところだけにする。
    const 上限 = Math.round(16000 * 1.5);
    if (切った.length <= 上限) return 切った;

    // 走らせながら合計する。全部を数え直すと遅い。
    let 和 = 0;
    for (let i = 0; i < 上限; i++) 和 += Math.abs(切った[i]);
    let 最良 = 和;
    let 最良の始 = 0;

    for (let i = 上限; i < 切った.length; i++) {
        和 += Math.abs(切った[i]) - Math.abs(切った[i - 上限]);
        if (和 > 最良) { 最良 = 和; 最良の始 = i - 上限 + 1; }
    }

    return 切った.slice(最良の始, 最良の始 + 上限);
}


/* ==========================================================
   5. DTW（話す速さの違いを吸収して比べる）
   ========================================================== */

/** 2つの係数の並びの距離 */
function 距離(a, b) {
    let 和 = 0;
    for (let i = 0; i < a.length; i++) {
        const d = a[i] - b[i];
        和 += d * d;
    }
    return Math.sqrt(和);
}

/**
 * DTW（動的時間伸縮）で、2つの音の近さを測る。
 *
 * 同じ言葉でも、話す速さは毎回ちがう。
 * 「アレラム」を早く言っても遅く言っても、同じと分かってほしい。
 * そこで、時間軸を伸び縮みさせながら、いちばん合う対応を探す。
 *
 * 返す値は「ずれの大きさ」。小さいほど似ている。
 */
function DTWで比べる(A, B) {
    const n = A.length;
    const m = B.length;
    if (!n || !m) return Infinity;

    // 前の行だけ持てば足りる。全部持つと、長い音で重くなる。
    let 前 = new Float64Array(m + 1).fill(Infinity);
    let 今 = new Float64Array(m + 1);
    前[0] = 0;

    for (let i = 1; i <= n; i++) {
        今.fill(Infinity);
        今[0] = Infinity;
        for (let j = 1; j <= m; j++) {
            const d = 距離(A[i - 1], B[j - 1]);
            今[j] = d + Math.min(前[j], 今[j - 1], 前[j - 1]);
        }
        [前, 今] = [今, 前];
    }

    // 長さで割る。長い言葉ほどずれが積み上がるため、そのままでは比べられない。
    return 前[m] / (n + m);
}


/**
 * 長い声の中から、覚えた言葉を探す（部分照合）
 *
 * なぜこれが要るのか:
 *   DTWで比べる は、全体どうしを比べる。
 *   だから「在庫を見せて」と覚えていても、
 *   「えーと、在庫を見せてくれる？」と言われると、
 *   前後の余計な音のせいで別物と判定されてしまった。
 *
 *   人は決まった言い方だけをするわけではない。
 *   言い淀みも、語尾の違いも、前置きもある。
 *   そこを許すために、長い方の「どこから始まって、どこで終わっても良い」
 *   という比べ方をする。
 *
 * やり方:
 *   ふつうのDTWは左上から右下まで通す。
 *   ここでは、長い方のどの位置から始めても罰を与えない（最初の列を0にする）。
 *   終わりも、長い方のどの位置で切っても良い（最後の列の最小を採る）。
 *
 * @param {Array} 長い  聞こえた声の特徴
 * @param {Array} 型    覚えている言葉の特徴
 * @returns {{ずれ:number, 始まり:number, 終わり:number}}
 */
function 中から探す(長い, 型) {
    const n = 長い.length;
    const m = 型.length;
    if (!n || !m) return { ずれ: Infinity, 始まり: 0, 終わり: 0 };

    // 型の方が長すぎるときは、部分照合の意味が無い。
    // ふつうの比べ方に任せる。
    if (m > n) {
        return { ずれ: DTWで比べる(長い, 型), 始まり: 0, 終わり: n };
    }

    // 一列ずつ持ち回す。行列を全部持つと、長い声で重くなるため。
    let 前 = new Float64Array(m + 1);
    let 今 = new Float64Array(m + 1);

    // どこから始まった道か、を一緒に持ち回す。
    // 終わったあとで長さを知りたいが、道を全部覚えると重い。
    let 前の始まり = new Int32Array(m + 1);
    let 今の始まり = new Int32Array(m + 1);

    前[0] = 0;
    for (let j = 1; j <= m; j++) 前[j] = Infinity;

    let 最小 = Infinity;
    let 最良の始まり = 0;
    let 最良の終わり = 0;

    for (let i = 1; i <= n; i++) {
        今[0] = 0;              // ここから始めても罰を与えない
        今の始まり[0] = i - 1;

        for (let j = 1; j <= m; j++) {
            const c = 距離(長い[i - 1], 型[j - 1]);

            // 斜め・上・左 のうち、いちばん安い道を選ぶ
            let 最安 = 前[j - 1];
            let 元 = 前の始まり[j - 1];

            if (前[j] < 最安) { 最安 = 前[j]; 元 = 前の始まり[j]; }
            if (今[j - 1] < 最安) { 最安 = 今[j - 1]; 元 = 今の始まり[j - 1]; }

            今[j] = c + 最安;
            今の始まり[j] = 元;
        }

        // 長い方のここで終わっても良い
        const 始 = 今の始まり[m];
        const 長さ = Math.max(1, i - 始);
        const 均した = 今[m] / (長さ + m);   // DTWで比べる と同じ均し方にそろえる

        if (均した < 最小) {
            最小 = 均した;
            最良の始まり = 始;
            最良の終わり = i;
        }

        // 入れ替え（作り直さないことで、長い声でも重くならない）
        let t = 前; 前 = 今; 今 = t;
        let u = 前の始まり; 前の始まり = 今の始まり; 今の始まり = u;
    }

    return { ずれ: 最小, 始まり: 最良の始まり, 終わり: 最良の終わり };
}

