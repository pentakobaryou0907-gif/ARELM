/**
 * 音の最小単位（拍）で覚える ― 使いながら育つ聞き取り
 *
 * なぜこの設計にするのか:
 *
 *   いまは「言葉まるごと」を覚えている。
 *   だから教えていない言葉は、絶対に聞き取れない。
 *   使うたびに録音のために立ち止まるのも、面倒の元だった。
 *
 *   そこで二つを同時に解く。
 *
 *   ・作業しながら覚える（立ち止まらない）
 *     呼びかけが通ったとき、その声は本物の呼びかけ。
 *     聞き返して文字で教わったとき、その音と文字は正しい組。
 *     どちらも、わざわざ録らなくても手に入る材料。
 *
 *   ・音の単位で覚える（教えていない言葉も届く）
 *     日本語は「か・た・ち」のような拍で出来ている。
 *     拍ごとに覚えれば、その組み合わせで
 *     教えていない言葉も組み立てられる。
 *     必要なのは百個ほどで、言葉の数だけ覚える必要がない。
 *
 *     <b>基本は日本語。</b>
 *     読み上げも、聞き取りも、拍の目安（100種類）も、日本語に合わせてある。
 *     ふだん使う言葉が日本語なので、そこを最も確かにする。
 *
 *     他の言語も、使えば同じように覚える。
 *     ハングルは一字が一音節なので、そのまま同じ扱いでよい。
 *     英語は母音のかたまりで区切る。
 *     どの言語でも「音の切れ端をためて、組み合わせる」やり方は変わらない。
 *
 *     ただし、他の言語のために日本語の精度を落とすことはしない。
 *     言葉ごとに仕組みを分けるのも避ける。
 *     分けると、言語が増えるたびに作り直すことになる。
 *
 * 正直に書いておきます:
 *
 *   これは Apple の音声認識と同等にはなりません。
 *   あちらは何千時間もの、文字が付いた音声で学習しています。
 *   その材料はこちらにありません。
 *
 *   ここで作るのは「あなたの声だけを、使いながら覚える」もの。
 *   最初は間違えます。使うほど当たるようになります。
 *   間違えたときは、当てずに聞き返します。
 *
 * すべてこの端末の中だけで動きます。外部へは一切送りません。
 */

const 拍の蓄えの鍵 = 'areglm_mora_bank';

/** 一つの拍について、これだけ集まれば当てにできる */
const 足りる数 = 3;

/** 拍ごとに持つ手本の上限。増やしすぎると比べる回数だけ増える。 */
const 手本の上限 = 8;

/* ==========================================================
   文字を拍に分ける

   「ざいこをみせて」→ ざ・い・こ・を・み・せ・て
   小さい「ゃゅょ」は前の字とくっつけて一拍にする。
   ========================================================== */

const 小さい字 = 'ゃゅょャュョァィゥェォ';
const 伸ばす字 = 'ーっッ';

function 文字を拍に分ける(文) {
    const 出 = [];
    const 字たち = [...(文 || '')];

    for (let i = 0; i < 字たち.length; i++) {
        const c = 字たち[i];
        if (!c.trim()) continue;

        // 小さい字は、前の拍にくっつける
        if (小さい字.includes(c) && 出.length) {
            出[出.length - 1] += c;
            continue;
        }
        // 伸ばす音・つまる音も、前にくっつける
        if (伸ばす字.includes(c) && 出.length) {
            出[出.length - 1] += c;
            continue;
        }

        // --- 英語など、アルファベットの言葉 ---
        //
        // 日本語は一字が一拍だが、英語は違う。
        // stock の s・t・o・c・k を一つずつ拍にすると、
        // 実際の音（ス・トッ・ク）と合わない。
        //
        // 母音のかたまりを一区切りとして、そこまでを一拍にする。
        // 正しい音節の切り方ではないが、
        // 同じ言葉なら毎回同じ切り方になるので、突き合わせには足りる。
        if (/[A-Za-z]/.test(c)) {
            let 塊 = c;
            let 母音を見た = /[aeiouAEIOU]/.test(c);
            while (i + 1 < 字たち.length && /[A-Za-z]/.test(字たち[i + 1])) {
                const 次 = 字たち[i + 1];
                const 次は母音 = /[aeiouAEIOU]/.test(次);
                // 母音を見たあとで、また子音→母音と続くなら、そこで切る
                if (母音を見た && !次は母音
                    && i + 2 < 字たち.length && /[aeiouAEIOU]/.test(字たち[i + 2])) {
                    break;
                }
                塊 += 次;
                if (次は母音) 母音を見た = true;
                i += 1;
            }
            出.push(塊.toLowerCase());
            continue;
        }

        // --- ハングル ---
        //
        // ハングルは一字が一音節なので、そのまま一拍でよい。
        // 日本語と同じ扱いで足りる。

        出.push(c);
    }
    return 出;
}

/**
 * その言葉が、どの言語らしいかを見る。
 *
 * 拍のため方は変わらないが、
 * 「何拍あるか」の見当を付けるのに使う。
 */
function 言葉の種類(文) {
    const t = 文 || '';
    if (/[\u3040-\u309f]/.test(t)) return '日本語（ひらがな）';
    if (/[\u30a0-\u30ff]/.test(t)) return '日本語（カタカナ）';
    if (/[\uac00-\ud7af]/.test(t)) return '韓国語';
    if (/[\u4e00-\u9fff]/.test(t)) return '漢字';
    if (/[A-Za-z]/.test(t)) return '英語など';
    return 'その他';
}

/* ==========================================================
   音を拍に切る

   声の強さが谷になるところで切る。
   拍と拍の間には、必ず息の切れ目がある。
   ========================================================== */

/**
 * 音の特徴の並びを、指定された数の区間に切る。
 *
 * 文字の側から「何拍あるか」が分かっているので、
 * その数に合わせて切る。
 * 数が分かっているぶん、切る場所を探すのが楽になる。
 */
function 特徴を拍に切る(特徴, 拍の数) {
    if (!特徴.length || 拍の数 < 1) return [];
    if (拍の数 === 1) return [特徴];

    // 各フレームの「強さ」を、係数の1番目（全体の大きさ）から見る
    const 強さ = 特徴.map((f) => f[0]);

    // 谷（前後より小さいところ）を探す
    const 谷 = [];
    for (let i = 2; i < 強さ.length - 2; i++) {
        if (強さ[i] < 強さ[i - 1] && 強さ[i] < 強さ[i + 1]
            && 強さ[i] < 強さ[i - 2] && 強さ[i] < 強さ[i + 2]) {
            谷.push({ 位置: i, 深さ: (強さ[i - 2] + 強さ[i + 2]) / 2 - 強さ[i] });
        }
    }

    // 深い谷から順に、必要な数だけ切れ目に使う
    谷.sort((a, b) => b.深さ - a.深さ);
    const 切れ目 = 谷.slice(0, 拍の数 - 1).map((x) => x.位置).sort((a, b) => a - b);

    // 谷が足りなければ、等分で補う
    while (切れ目.length < 拍の数 - 1) {
        const 等分 = Math.round(特徴.length * (切れ目.length + 1) / 拍の数);
        if (!切れ目.includes(等分)) 切れ目.push(等分);
        切れ目.sort((a, b) => a - b);
    }

    const 出 = [];
    let 前 = 0;
    切れ目.forEach((p) => {
        if (p > 前) 出.push(特徴.slice(前, p));
        前 = p;
    });
    出.push(特徴.slice(前));

    // 短すぎる区間は、比べても意味がない
    return 出.filter((x) => x.length >= 2);
}

/* ==========================================================
   蓄え
   ========================================================== */

function 拍の蓄えを読む() {
    try {
        const r = JSON.parse(localStorage.getItem(拍の蓄えの鍵) || '{}');
        return (r && typeof r === 'object') ? r : {};
    } catch {
        return {};
    }
}

function 拍の蓄えを書く(中身) {
    localStorage.setItem(拍の蓄えの鍵, JSON.stringify(中身));
}

/** 小数を丸めて縮める。細かい桁は聞き分けに効かない。 */
function 拍を縮める(特徴) {
    return 特徴.map((f) => Array.from(f).map((v) => Math.round(v * 100) / 100));
}

/**
 * 言葉と、その音から、拍ごとの手本をためる。
 *
 * ここが「作業しながら覚える」の入口。
 * わざわざ録らなくても、通った呼びかけや、
 * 聞き返して教わった言葉が、そのまま材料になる。
 *
 * @param {string} 言葉  何と言ったか（文字）
 * @param {Array} 特徴   その音の特徴（MFCC）
 * @returns {{足した: number, 蓄えた拍: number}}
 */
function 拍をためる(言葉, 特徴) {
    const 拍たち = 文字を拍に分ける(言葉);
    if (!拍たち.length || !特徴 || !特徴.length) return { 足した: 0, 蓄えた拍: 0 };

    const 区間 = 特徴を拍に切る(特徴, 拍たち.length);

    // 切った数と拍の数が合わないときは、当てにできない。
    // 無理に対応づけると、間違った手本が貯まる。
    if (区間.length !== 拍たち.length) {
        return { 足した: 0, 蓄えた拍: Object.keys(拍の蓄えを読む()).length };
    }

    const 蓄え = 拍の蓄えを読む();
    let 足した = 0;

    拍たち.forEach((拍, i) => {
        蓄え[拍] = 蓄え[拍] || [];
        蓄え[拍].push(拍を縮める(区間[i]));
        if (蓄え[拍].length > 手本の上限) 蓄え[拍].shift();
        足した += 1;
    });

    拍の蓄えを書く(蓄え);
    return { 足した, 蓄えた拍: Object.keys(蓄え).length };
}

/**
 * 拍の蓄えを使って、聞き取る。
 *
 * 教えていない言葉でも、拍が揃っていれば組み立てられる。
 * 揃っていなければ、正直に「分からない」と言う。
 */
function 拍から組み立てる(特徴) {
    const 蓄え = 拍の蓄えを読む();
    const 使える拍 = Object.keys(蓄え).filter((k) => 蓄え[k].length >= 足りる数);

    if (使える拍.length < 10) {
        return {
            結果: 'まだ足りない',
            訳: `覚えた拍が ${使える拍.length}種類です。`
                + '組み立てて聞き取るには、もう少し使う必要があります。',
        };
    }

    const 芯 = window.AReGLM_VOICE_CORE;
    if (!芯) return { 結果: '仕組みなし' };

    // 拍の数が分からないので、いくつかの区切り方を試す。
    // いちばん自信の持てたものを採る。
    let 最良 = null;

    for (let 数 = 2; 数 <= 8; 数++) {
        const 区間 = 特徴を拍に切る(特徴, 数);
        if (区間.length !== 数) continue;

        const 読み = [];
        let 合計のずれ = 0;

        区間.forEach((一区間) => {
            let 近い = Infinity;
            let 字 = '';
            使える拍.forEach((拍) => {
                蓄え[拍].forEach((手本) => {
                    const d = 芯.DTWで比べる(一区間, 手本.map((a) => Float32Array.from(a)));
                    if (d < 近い) { 近い = d; 字 = 拍; }
                });
            });
            読み.push(字);
            合計のずれ += 近い;
        });

        const 平均 = 合計のずれ / Math.max(1, 区間.length);
        if (!最良 || 平均 < 最良.ずれ) {
            最良 = { 言葉: 読み.join(''), ずれ: 平均, 拍数: 数 };
        }
    }

    if (!最良) return { 結果: '分からない' };

    // 自信の目安。これを超えたら、当てずに聞き返す。
    if (最良.ずれ > 40) {
        return {
            結果: '分からない',
            聞こえたかも: 最良.言葉,
            ずれ: Math.round(最良.ずれ * 10) / 10,
        };
    }

    return {
        結果: 最良.ずれ <= 25 ? 'たぶん' : 'あやしい',
        言葉: 最良.言葉,
        ずれ: Math.round(最良.ずれ * 10) / 10,
    };
}

/** いま何拍ぶん覚えているか */
function 拍の育ち具合() {
    const 蓄え = 拍の蓄えを読む();
    const 全部 = Object.keys(蓄え);
    const 使える = 全部.filter((k) => 蓄え[k].length >= 足りる数);
    // 拍の目安は日本語に合わせてある。
    // よく使うひらがな・カタカナの拍が、およそ100種類。
    // 他の言語を使えばその拍も貯まるが、
    // 目安は日本語のままにしておく。基本が日本語だから。
    return {
        覚えた拍: 全部.length,
        使える拍: 使える.length,
        目安: 100,
        割合: Math.min(100, Math.round((使える.length / 100) * 100)),
        中身: 使える.sort(),
    };
}

/**
 * 覚えた拍を、言語ごとに数える。
 *
 * 基本は日本語なので、日本語がどれだけ育ったかを先に見る。
 * 他の言語は「ついでに貯まったもの」として、その後に出す。
 */
function 言語ごとの育ち() {
    const 蓄え = 拍の蓄えを読む();
    const 数え = { 日本語: 0, 韓国語: 0, '英語など': 0, その他: 0 };

    Object.keys(蓄え).forEach((拍) => {
        if (蓄え[拍].length < 足りる数) return;
        if (/[\u3040-\u30ff]/.test(拍)) 数え.日本語 += 1;
        else if (/[\uac00-\ud7af]/.test(拍)) 数え.韓国語 += 1;
        else if (/[A-Za-z]/.test(拍)) 数え['英語など'] += 1;
        else 数え.その他 += 1;
    });

    return 数え;
}

function 拍を忘れる() {
    localStorage.removeItem(拍の蓄えの鍵);
}

