/**
 * 作業タブ ― いま何をしているかを、上に並べる
 *
 * なぜこれが要るのか:
 *
 *   作業が増えると、何をどこまでやったか分からなくなる。
 *   画面を行ったり来たりして、探すことが仕事になる。
 *
 *   頼んだ作業を、上に並べておく。
 *   終わったものは消え、確認が要るものは印が付く。
 *   <b>上を見れば、いま何が動いているかが分かる。</b>
 *
 * 二種類を並べる:
 *
 *   ・<b>頼んだ作業</b>（在庫を見る・図案を作る…）
 *     あなたが言ったこと。終われば消える。
 *
 *   ・<b>開いている画面</b>（SUZURI・Instagram…）
 *     いま見ているもの。閉じれば消える。
 *
 *   どちらも「いま関わっているもの」なので、同じ場所に並べる。
 *   分けて置くと、結局どちらも見ることになる。
 *
 * すべてこの端末の中だけで動きます。
 */

const 作業タブの鍵 = 'areglm_work_tabs';

/** 並べておく上限。多すぎると、探すのが仕事になる。 */
const 並べる上限 = 12;

/* ==========================================================
   読み書き
   ========================================================== */

function 作業タブを読む() {
    try {
        const r = JSON.parse(localStorage.getItem(作業タブの鍵) || '[]');
        return Array.isArray(r) ? r : [];
    } catch {
        return [];
    }
}

function 作業タブを書く(一覧) {
    localStorage.setItem(作業タブの鍵, JSON.stringify(一覧.slice(-並べる上限)));
    知らせる();
}

/** 変わったことを、画面に知らせる */
function 知らせる() {
    try {
        window.dispatchEvent(new CustomEvent('作業タブが変わった'));
    } catch {
        // 知らせられなくても、中身は変わっている。
        // 次に描き直したときに反映される。
    }
}

/* ==========================================================
   作業を足す・進める・終える
   ========================================================== */

/**
 * 作業を始めたことを残す。
 *
 * @param {string} 名前   何をするか（「在庫を見る」など）
 * @param {Object} 中身   { 目的, 全周手, 種類 }
 * @returns {string} この作業の目印
 */
function 作業を始める(名前, 中身) {
    中身 = 中身 || {};
    const 目印 = 'w_' + Date.now() + '_' + Math.random().toString(36).slice(2, 6);

    const 一覧 = 作業タブを読む();
    一覧.push({
        id: 目印,
        名前: String(名前 || '作業').slice(0, 40),
        種類: 中身.種類 || '頼んだ作業',
        目的: 中身.目的 || '',
        様子: '動いています',
        いま何手目: 0,
        全周手: 中身.全周手 || 0,
        いましていること: '',
        始めた: new Date().toISOString(),
    });
    作業タブを書く(一覧);
    return 目印;
}

/** 進み具合を伝える */
function 作業を進める(目印, 何手目, していること) {
    const 一覧 = 作業タブを読む();
    const x = 一覧.find((a) => a.id === 目印);
    if (!x) return;
    if (何手目 != null) x.いま何手目 = 何手目;
    if (していること) x.いましていること = String(していること).slice(0, 60);
    x.様子 = '動いています';
    作業タブを書く(一覧);
}

/**
 * 確認を待つ状態にする。
 *
 * ここが大事なところ。
 * 確認を待っているものが埋もれると、
 * <b>止まっていることに気づけない</b>。
 * だから、はっきり印を付ける。
 */
function 確認を待つ(目印, 何を) {
    const 一覧 = 作業タブを読む();
    const x = 一覧.find((a) => a.id === 目印);
    if (!x) return;
    x.様子 = '確認待ち';
    x.いましていること = String(何を || '確認をお願いします').slice(0, 60);
    作業タブを書く(一覧);
}

/** 終わったことを残す */
function 作業を終える(目印, どうなったか) {
    const 一覧 = 作業タブを読む();
    const x = 一覧.find((a) => a.id === 目印);
    if (!x) return;
    x.様子 = どうなったか === '止まった' ? '止まりました' : '終わりました';
    x.終わった = new Date().toISOString();
    作業タブを書く(一覧);

    // 終わったものは、しばらくしたら消す。
    // すぐ消すと、終わったことに気づけない。
    setTimeout(() => {
        const 後 = 作業タブを読む().filter((a) => a.id !== 目印);
        作業タブを書く(後);
    }, 8000);
}

/** 全部片づける */
function 終わったものを片づける() {
    const 一覧 = 作業タブを読む().filter((x) => x.様子 === '動いています' || x.様子 === '確認待ち');
    作業タブを書く(一覧);
    return 一覧.length;
}

/* ==========================================================
   まとめて見る
   ========================================================== */

/**
 * 作業のいまの様子をまとめる。
 *
 * 画面の下に出す「いま何をしているか」の中身になる。
 */
// 名前は「作業のいまの様子」。
// 「いまの様子」だと js/modules/様子.js とぶつかり、
// const の二重宣言でページ全体が止まる。検査で見つけた。
// 同じ間違いを、この開発で8回している。
function 作業のいまの様子() {
    const 一覧 = 作業タブを読む();
    const 動いている = 一覧.filter((x) => x.様子 === '動いています');
    const 確認待ち = 一覧.filter((x) => x.様子 === '確認待ち');

    // 確認待ちがあるなら、それが最優先。
    // 動いているものより先に、人の手が要る。
    //
    // ここは合っていたが、下の欄では
    // 「動いているもの」の目的を出してしまっていた。
    // <b>止まっているものを差し置いて、動いているものを見せない。</b>
    const いま = 確認待ち[0] || 動いている[動いている.length - 1] || null;

    return {
        全部: 一覧,
        動いている: 動いている.length,
        確認待ち: 確認待ち.length,
        いま,
        目的: いま ? いま.目的 : '',
        していること: いま
            ? (いま.いましていること
                || (いま.全周手
                    ? `${いま.名前}（${いま.いま何手目}／${いま.全周手}手）`
                    : いま.名前))
            : '',
        一つにまとめるか: 一覧.length === 0,
    };
}

window.作業タブを読む = 作業タブを読む;
window.作業を始める = 作業を始める;
window.作業を進める = 作業を進める;
window.確認を待つ = 確認を待つ;
window.作業を終える = 作業を終える;
window.終わったものを片づける = 終わったものを片づける;
window.作業のいまの様子 = 作業のいまの様子;
