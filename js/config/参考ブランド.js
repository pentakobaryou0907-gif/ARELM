/**
 * 参考ブランドを取り込む。
 *
 * すでに同じ名前があれば飛ばす。
 * 二重に入ると、どちらが本当か分からなくなる。
 */
function 参考ブランドを取り込む() {
    const brands = JSON.parse(localStorage.getItem('brands') || '[]');
    const ある名前 = new Set(brands.map((b) => b.name));
    let 足した = 0;

    AReGLM_参考ブランド.forEach((x) => {
        if (ある名前.has(x.name)) return;
        brands.push({
            id: 'brand_' + Date.now() + '_' + Math.random().toString(36).slice(2, 7),
            name: x.name,
            description: x.特徴,
            category: x.category,
            country: x.国,
            price: x.price,
            // 詳細画面は established / ceo という名前で読む。
            // 別の名前で入れると、画面には「未設定」と出てしまう。
            website: x.公式 || '',
            url: x.公式 || '',
            established: x.創業 ? String(x.創業) + '年' : '',
            ceo: x.創業者 || '',
            参考になる点: x.参考,
            tags: ['参考ブランド'],
            createdAt: new Date().toISOString(),
        });
        足した += 1;
    });

    localStorage.setItem('brands', JSON.stringify(brands));

    if (typeof logActivity === 'function') {
        logActivity(`参考ブランドを${足した}件読み込みました`,
            { category: 'brands', text: '参考ブランド集 読み込み' });
    }
    if (typeof showNotification === 'function') {
        showNotification(
            足した ? `参考ブランドを${足した}件追加しました（全${AReGLM_参考ブランド.length}件中）`
                   : 'すべて登録済みでした',
            足した ? 'success' : 'info');
    }
    // 描き直す。関数名を取り違えると、
    // 保存はできているのに画面に出ない、という状態になる。
    // 実際、はじめは loadBrands と書いていて、画面に出なかった。
    if (typeof loadBrandsData === 'function') loadBrandsData();
    if (typeof renderBrandSplit === 'function') renderBrandSplit();
    if (typeof refreshBrands === 'function') refreshBrands();
    return 足した;
}

window.AReGLM_参考ブランド = AReGLM_参考ブランド;
window.参考ブランドを取り込む = 参考ブランドを取り込む;
