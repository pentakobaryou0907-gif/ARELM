/**
 * ブランド名から、歴史と理念を引く。
 *
 * 名前には読み仮名が付いていることがあるので、
 * 括弧より前で照らす。
 */
function ブランドの歴史を引く(名前) {
    if (!名前) return null;
    const 素の名 = String(名前).split(/[（(]/)[0].trim();

    if (ブランドの歴史と理念[素の名]) return ブランドの歴史と理念[素の名];

    // 大文字小文字の違いも見る
    const 見つけた = Object.keys(ブランドの歴史と理念)
        .find((k) => k.toLowerCase() === 素の名.toLowerCase());
    return 見つけた ? ブランドの歴史と理念[見つけた] : null;
}

/** いま持っているブランドの数 */
function 歴史を持つブランドの数() {
    return Object.keys(ブランドの歴史と理念).length;
}

